USE SISTEMA_FACTURACION;
GO

SET NOCOUNT ON;

DECLARE @INICIO DATETIME2(3) = SYSDATETIME();

-- 1. DATOS ELEGIDOS DE FORMA DINÁMICA
DECLARE @ID_EMPRESA INT = (
    SELECT TOP (1) EM.ID_EMPRESA
    FROM DBO.EMPRESA AS EM
    WHERE
        EM.ESTA_ACTIVA = 1
        AND (
            SELECT COUNT(*)
            FROM DBO.PRODUCTO AS P
            INNER JOIN DBO.TIPO_PRODUCTO AS TP
                ON P.ID_TIPO_PRODUCTO = TP.ID_TIPO_PRODUCTO
            WHERE
                P.ID_RUBRO = EM.ID_RUBRO
                AND P.ESTADO_PRODUCTO = 1
                AND TP.CODIGO_TIPO = 'PRD'
                AND P.EXISTENCIA >= 5
        ) >= 3
    ORDER BY EM.ID_EMPRESA
);

DECLARE @ID_RUBRO TINYINT = (
    SELECT EM.ID_RUBRO
    FROM DBO.EMPRESA AS EM
    WHERE EM.ID_EMPRESA = @ID_EMPRESA
);

DECLARE @ID_CLIENTE INT = (
    SELECT TOP (1) C.ID_CLIENTE
    FROM DBO.CLIENTE AS C
    INNER JOIN DBO.CLIENTE_FISICO AS CF
        ON C.ID_CLIENTE = CF.ID_CLIENTE
    ORDER BY C.ID_CLIENTE
);

DECLARE @CEDULA_FISICA VARCHAR(12) = (
    SELECT C.CEDULA_CLIENTE
    FROM DBO.CLIENTE AS C
    WHERE C.ID_CLIENTE = @ID_CLIENTE
);

DECLARE @CEDULA_JURIDICA VARCHAR(12) = (
    SELECT TOP (1) C.CEDULA_CLIENTE
    FROM DBO.CLIENTE AS C
    INNER JOIN DBO.CLIENTE_JURIDICO AS CJ
        ON C.ID_CLIENTE = CJ.ID_CLIENTE
    WHERE
        EXISTS (
            SELECT 1
            FROM DBO.FACTURA AS F
            WHERE F.ID_CLIENTE_COMPRADOR = C.ID_CLIENTE
        )
    ORDER BY C.ID_CLIENTE
);

DECLARE @ID_TIPO_DOCUMENTO TINYINT = (
    SELECT TD.ID_TIPO_DOCUMENTO
    FROM DBO.TIPO_DOCUMENTO AS TD
    WHERE TD.CODIGO_IDENTIFICADOR = 'FAC'
);

DECLARE @ID_MONEDA TINYINT = (
    SELECT TOP (1) M.ID_MONEDA
    FROM DBO.MONEDA AS M
    ORDER BY M.ID_MONEDA
);

IF @ID_EMPRESA IS NULL OR @ID_CLIENTE IS NULL
    BEGIN
        SELECT N'No hay datos suficientes para la demostración.' AS AVISO;
        RETURN;
    END;

-- 2. LÍNEAS DE LA FACTURA: 
DECLARE @LINEAS DBO.TT_LINEA_FACTURA;

INSERT INTO @LINEAS (ID_PRODUCTO, CANTIDAD, MONTO_DESCUENTO)
SELECT TOP (3)
    P.ID_PRODUCTO,
    CAST(
        ROW_NUMBER() OVER (ORDER BY P.ID_PRODUCTO) AS DECIMAL(9, 3)
    ) AS CANTIDAD,
    CAST(0 AS DECIMAL(18, 2)) AS MONTO_DESCUENTO
FROM DBO.PRODUCTO AS P
INNER JOIN DBO.TIPO_PRODUCTO AS TP
    ON P.ID_TIPO_PRODUCTO = TP.ID_TIPO_PRODUCTO
WHERE
    P.ID_RUBRO = @ID_RUBRO
    AND P.ESTADO_PRODUCTO = 1
    AND TP.CODIGO_TIPO = 'PRD'
    AND P.EXISTENCIA >= 5
ORDER BY P.ID_PRODUCTO;

-- 3. CREAR LA FACTURA COMO USR_CAJERO 
DECLARE @ID_FACTURA INT;
DECLARE @CONSECUTIVO CHAR(20);
DECLARE @CODIGO_ERROR INT;
DECLARE @MENSAJE NVARCHAR(4000);

EXECUTE AS USER = 'USR_CAJERO'; -- noqa: PRS
EXECUTE DBO.USP_CREAR_FACTURA
    @ID_EMPRESA = @ID_EMPRESA,
    @ID_CLIENTE = @ID_CLIENTE,
    @ID_TIPO_DOCUMENTO = @ID_TIPO_DOCUMENTO,
    @ID_MONEDA = @ID_MONEDA,
    @OBSERVACIONES = N'Demostración de la Entrega 4',
    @LINEAS = @LINEAS,
    @ID_FACTURA = @ID_FACTURA OUTPUT,
    @CODIGO_ERROR = @CODIGO_ERROR OUTPUT,
    @MENSAJE = @MENSAJE OUTPUT;
REVERT; -- noqa: PRS

IF @CODIGO_ERROR <> 0
    BEGIN
        SELECT @CODIGO_ERROR AS CODIGO_ERROR, @MENSAJE AS MENSAJE;
        RETURN;
    END;

-- 4. EMITIR LA FACTURA COMO USR_CAJERO 
EXECUTE AS USER = 'USR_CAJERO'; -- noqa: PRS
EXECUTE DBO.USP_CAMBIAR_ESTADO_FACTURA
    @ID_FACTURA = @ID_FACTURA,
    @NUEVO_ESTADO = 'EMITIDA',
    @CONSECUTIVO = @CONSECUTIVO OUTPUT,
    @CODIGO_ERROR = @CODIGO_ERROR OUTPUT,
    @MENSAJE = @MENSAJE OUTPUT;
REVERT; -- noqa: PRS

IF @CODIGO_ERROR <> 0
    BEGIN
        SELECT @CODIGO_ERROR AS CODIGO_ERROR, @MENSAJE AS MENSAJE;
        RETURN;
    END;

-- 5. CAMBIAR EL TELÉFONO DEL CLIENTE COMO USR_CAJERO
DECLARE @TELEFONO_ANTERIOR VARCHAR(12) = (
    SELECT C.TELEFONO_CLIENTE
    FROM DBO.CLIENTE AS C
    WHERE C.ID_CLIENTE = @ID_CLIENTE
);

DECLARE @TELEFONO_NUEVO VARCHAR(12) =
    CASE WHEN @TELEFONO_ANTERIOR LIKE '7%' THEN '8' ELSE '7' END
    + RIGHT(CONCAT('0000000', ABS(CHECKSUM(NEWID()) % 10000000)), 7);

EXECUTE AS USER = 'USR_CAJERO'; -- noqa: PRS
EXECUTE DBO.USP_ACTUALIZAR_CLIENTE
    @ID_CLIENTE = @ID_CLIENTE,
    @TELEFONO = @TELEFONO_NUEVO,
    @CODIGO_ERROR = @CODIGO_ERROR OUTPUT,
    @MENSAJE = @MENSAJE OUTPUT;
REVERT; -- noqa: PRS

IF @CODIGO_ERROR <> 0
    BEGIN
        SELECT @CODIGO_ERROR AS CODIGO_ERROR, @MENSAJE AS MENSAJE;
        RETURN;
    END;

-- 6. HISTORIAL DEL ENCABEZADO: INSERT Y UPDATE
SELECT
    H.ID_HISTORIAL,
    T.CODIGO_OPERACION AS OPERACION,
    H.USUARIO_RESPONSABLE,
    H.FECHA_CAMBIO,
    RTRIM(H.CONSECUTIVO) AS CONSECUTIVO,
    E.ESTADO,
    H.MONTO_FINAL
FROM DBO.FACTURA_HISTORIAL AS H
INNER JOIN DBO.TIPO_OPERACION AS T
    ON H.ID_TIPO_OPERACION = T.ID_TIPO_OPERACION
INNER JOIN DBO.ESTADO_FACTURA AS E
    ON H.ID_ESTADO_FACTURA = E.ID_ESTADO_FACTURA
WHERE H.ID_FACTURA = @ID_FACTURA
ORDER BY H.ID_HISTORIAL;

-- 7. HISTORIAL DEL DETALLE: UNA FILA INSERT POR CADA LÍNEA
SELECT
    H.ID_HISTORIAL,
    T.CODIGO_OPERACION AS OPERACION,
    H.USUARIO_RESPONSABLE,
    H.NUMERO_LINEA,
    H.CANTIDAD_FACTURADA,
    H.PRECIO_UNITARIO,
    H.MONTO_TOTAL_LINEA
FROM DBO.DETALLE_FACTURA_HISTORIAL AS H
INNER JOIN DBO.TIPO_OPERACION AS T
    ON H.ID_TIPO_OPERACION = T.ID_TIPO_OPERACION
WHERE H.ID_FACTURA = @ID_FACTURA
ORDER BY H.NUMERO_LINEA;

-- 8. HISTORIAL DEL CLIENTE: EL UPDATE GUARDA EL TELÉFONO ANTERIOR
SELECT TOP (1)
    H.ID_HISTORIAL,
    T.CODIGO_OPERACION AS OPERACION,
    H.USUARIO_RESPONSABLE,
    H.FECHA_CAMBIO,
    H.TELEFONO_CLIENTE AS TELEFONO_ANTERIOR,
    @TELEFONO_NUEVO AS TELEFONO_NUEVO
FROM DBO.CLIENTE_HISTORIAL AS H
INNER JOIN DBO.TIPO_OPERACION AS T
    ON H.ID_TIPO_OPERACION = T.ID_TIPO_OPERACION
WHERE H.ID_CLIENTE = @ID_CLIENTE
ORDER BY H.ID_HISTORIAL DESC;

DECLARE @T0 DATETIME2(7);

EXECUTE AS USER = 'USR_CONSULTA';
SET @T0 = SYSDATETIME();

SELECT *
FROM DBO.UFN_FACTURAS_PERSONA_FISICA(@CEDULA_FISICA)
ORDER BY FECHA_EMISION DESC;

SELECT DATEDIFF(MILLISECOND, @T0, SYSDATETIME()) AS MS_CONSULTA_06;

SET @T0 = SYSDATETIME();

SELECT *
FROM DBO.UFN_FACTURAS_PERSONA_JURIDICA(@CEDULA_JURIDICA)
ORDER BY FECHA_EMISION DESC;

SELECT DATEDIFF(MILLISECOND, @T0, SYSDATETIME()) AS MS_CONSULTA_07;

SET @T0 = SYSDATETIME();

SELECT *
FROM DBO.UFN_TOTALES_CLIENTE_ANIO(@CEDULA_FISICA);

SELECT DATEDIFF(MILLISECOND, @T0, SYSDATETIME()) AS MS_CONSULTA_12;

REVERT;

-- 10. RESUMEN DE LA VERIFICACIÓN
SELECT
    CASE
        WHEN (
            SELECT COUNT(*)
            FROM DBO.FACTURA_HISTORIAL
            WHERE
                ID_FACTURA = @ID_FACTURA
                AND USUARIO_RESPONSABLE = 'USR_CAJERO'
        ) = 2 THEN 'PASA'
        ELSE 'FALLA'
    END AS TRIGGER_FACTURA,
    CASE
        WHEN (
            SELECT COUNT(*)
            FROM DBO.DETALLE_FACTURA_HISTORIAL
            WHERE
                ID_FACTURA = @ID_FACTURA
                AND USUARIO_RESPONSABLE = 'USR_CAJERO'
        ) = (SELECT COUNT(*) FROM @LINEAS) THEN 'PASA'
        ELSE 'FALLA'
    END AS TRIGGER_DETALLE,
    CASE
        WHEN EXISTS (
            SELECT 1
            FROM DBO.CLIENTE_HISTORIAL AS H
            INNER JOIN DBO.TIPO_OPERACION AS T
                ON H.ID_TIPO_OPERACION = T.ID_TIPO_OPERACION
            WHERE
                H.ID_CLIENTE = @ID_CLIENTE
                AND T.CODIGO_OPERACION = 'UPDATE'
                AND H.USUARIO_RESPONSABLE = 'USR_CAJERO'
                AND H.TELEFONO_CLIENTE = @TELEFONO_ANTERIOR
                AND H.FECHA_CAMBIO >= @INICIO
        ) THEN 'PASA'
        ELSE 'FALLA'
    END AS TRIGGER_CLIENTE;
GO
