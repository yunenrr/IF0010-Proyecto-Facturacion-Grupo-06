/* DEMOSTRACIÓN DE CATÁLOGO Y UBICACIÓN: TRIGGERS DE DIRECCIÓN, PRODUCTO Y
   SERVICIO, Y CONSULTAS 10, 11 Y 13 CRONOMETRADAS. TODO EL DML PASA POR
   PROCEDIMIENTOS EJECUTADOS COMO USR_ADMINISTRATIVO. SE PUEDE REPETIR. */

USE SISTEMA_FACTURACION;
GO

SET NOCOUNT ON;

DECLARE @SUFIJO NVARCHAR(14) = FORMAT(SYSDATETIME(), 'yyyyMMddHHmmss');
DECLARE @COD INT;
DECLARE @MSG NVARCHAR(4000);
DECLARE @R TABLE (ORDEN INT, PRUEBA VARCHAR(70), PASA BIT, DETALLE VARCHAR(80));

-- DATOS DE PARTIDA, ELEGIDOS DINÁMICAMENTE
DECLARE @ID_CLIENTE INT = (
    SELECT TOP (1) ID_CLIENTE
    FROM DBO.CLIENTE
    ORDER BY ID_CLIENTE
);
DECLARE @ID_DIR_CLI INT = (
    SELECT ID_DIRECCION
    FROM DBO.CLIENTE
    WHERE ID_CLIENTE = @ID_CLIENTE
);
DECLARE @ID_EMPRESA INT = (
    SELECT TOP (1) ID_EMPRESA
    FROM DBO.EMPRESA
    ORDER BY ID_EMPRESA
);
DECLARE @ID_DIR_EMP INT = (
    SELECT ID_DIRECCION
    FROM DBO.EMPRESA
    WHERE ID_EMPRESA = @ID_EMPRESA
);

DECLARE @DIST_ANT_CLI INT, @SENAS_ANT_CLI NVARCHAR(250);
DECLARE @DIST_ANT_EMP INT, @SENAS_ANT_EMP NVARCHAR(250);

SELECT
    @DIST_ANT_CLI = ID_DISTRITO,
    @SENAS_ANT_CLI = OTRAS_SENAS
FROM DBO.DIRECCION
WHERE ID_DIRECCION = @ID_DIR_CLI;

SELECT
    @DIST_ANT_EMP = ID_DISTRITO,
    @SENAS_ANT_EMP = OTRAS_SENAS
FROM DBO.DIRECCION
WHERE ID_DIRECCION = @ID_DIR_EMP;

DECLARE @DIST_NUEVO_CLI INT = (
    SELECT TOP (1) ID_DISTRITO
    FROM DBO.DISTRITO
    WHERE ID_DISTRITO <> @DIST_ANT_CLI
    ORDER BY ID_DISTRITO
);
DECLARE @DIST_NUEVO_EMP INT = (
    SELECT TOP (1) ID_DISTRITO
    FROM DBO.DISTRITO
    WHERE ID_DISTRITO <> @DIST_ANT_EMP
    ORDER BY ID_DISTRITO DESC
);
DECLARE @SENAS_NUEVAS_CLI NVARCHAR(250) = CONCAT(N'Demo cliente ', @SUFIJO);
DECLARE @SENAS_NUEVAS_EMP NVARCHAR(250) = CONCAT(N'Demo empresa ', @SUFIJO);

DECLARE @HIST_ANTES_CLI INT = (
    SELECT COUNT(*) FROM DBO.DIRECCION_HISTORIAL
    WHERE ID_DIRECCION = @ID_DIR_CLI
);
DECLARE @HIST_ANTES_EMP INT = (
    SELECT COUNT(*) FROM DBO.DIRECCION_HISTORIAL
    WHERE ID_DIRECCION = @ID_DIR_EMP
);

-- BIEN ACTIVO PARA CAMBIAR EL PRECIO
DECLARE @ID_BIEN INT, @PRECIO_ANT DECIMAL(18, 5);

SELECT TOP (1)
    @ID_BIEN = P.ID_PRODUCTO,
    @PRECIO_ANT = P.PRECIO_UNITARIO
FROM DBO.PRODUCTO AS P
INNER JOIN DBO.TIPO_PRODUCTO AS TP
    ON P.ID_TIPO_PRODUCTO = TP.ID_TIPO_PRODUCTO
WHERE TP.CODIGO_TIPO = 'PRD' AND P.ESTADO_PRODUCTO = 1
ORDER BY P.ID_PRODUCTO;

DECLARE @PRECIO_NUEVO DECIMAL(18, 5) = @PRECIO_ANT + 100;
DECLARE @HIST_ANTES_BIEN INT = (
    SELECT COUNT(*) FROM DBO.PRODUCTO_HISTORIAL
    WHERE ID_PRODUCTO = @ID_BIEN
);

-- DATOS PARA REGISTRAR UN SERVICIO NUEVO
DECLARE @ID_TIPO_SRV TINYINT = (
    SELECT ID_TIPO_PRODUCTO
    FROM DBO.TIPO_PRODUCTO
    WHERE CODIGO_TIPO = 'SRV'
);
DECLARE @ID_RUBRO_CON TINYINT = (
    SELECT ID_RUBRO
    FROM DBO.RUBRO
    WHERE CODIGO_RUBRO = 'CON'
);
DECLARE @DESC_SRV NVARCHAR(150) = CONCAT(N'Servicio demo ', @SUFIJO);
DECLARE @ID_SRV INT, @CODIGO_SRV VARCHAR(20);

-- RESULTADOS DE CADA LLAMADA
DECLARE @COD_CLI INT, @MSG_CLI NVARCHAR(4000);
DECLARE @COD_EMP INT, @MSG_EMP NVARCHAR(4000);
DECLARE @COD_P1 INT, @MSG_P1 NVARCHAR(4000);
DECLARE @COD_P2 INT, @MSG_P2 NVARCHAR(4000);
DECLARE @COD_S1 INT, @MSG_S1 NVARCHAR(4000);
DECLARE @COD_S2 INT, @MSG_S2 NVARCHAR(4000);

EXECUTE AS USER = 'USR_ADMINISTRATIVO'; -- noqa: PRS

EXEC DBO.USP_ACTUALIZAR_CLIENTE
    @ID_CLIENTE = @ID_CLIENTE,
    @ID_DISTRITO = @DIST_NUEVO_CLI,
    @OTRAS_SENAS = @SENAS_NUEVAS_CLI,
    @CODIGO_ERROR = @COD_CLI OUTPUT,
    @MENSAJE = @MSG_CLI OUTPUT;

EXEC DBO.USP_ACTUALIZAR_EMPRESA
    @ID_EMPRESA = @ID_EMPRESA,
    @ID_DISTRITO = @DIST_NUEVO_EMP,
    @OTRAS_SENAS = @SENAS_NUEVAS_EMP,
    @CODIGO_ERROR = @COD_EMP OUTPUT,
    @MENSAJE = @MSG_EMP OUTPUT;

EXEC DBO.USP_ACTUALIZAR_PRECIO_PRODUCTO
    @ID_PRODUCTO = @ID_BIEN,
    @NUEVO_PRECIO = @PRECIO_NUEVO,
    @CODIGO_ERROR = @COD_P1 OUTPUT,
    @MENSAJE = @MSG_P1 OUTPUT;

EXEC DBO.USP_REGISTRAR_PRODUCTO
    @ID_TIPO_PRODUCTO = @ID_TIPO_SRV,
    @ID_RUBRO = @ID_RUBRO_CON,
    @DESCRIPCION = @DESC_SRV,
    @PRECIO_UNITARIO = 50000,
    @TASA_IMPUESTO = 0.1300,
    @EXISTENCIA = 0,
    @DURACION_ESTIMADA_MIN = 60,
    @SE_BRINDA_A_DOMICILIO = 0,
    @ID_PRODUCTO = @ID_SRV OUTPUT,
    @CODIGO_INTERNO = @CODIGO_SRV OUTPUT,
    @CODIGO_ERROR = @COD_S1 OUTPUT,
    @MENSAJE = @MSG_S1 OUTPUT;

EXEC DBO.USP_ACTUALIZAR_SERVICIO
    @ID_PRODUCTO = @ID_SRV,
    @DURACION_ESTIMADA_MIN = 90,
    @SE_BRINDA_A_DOMICILIO = 1,
    @CODIGO_ERROR = @COD_S2 OUTPUT,
    @MENSAJE = @MSG_S2 OUTPUT;


REVERT; -- SALIMOS DEL CONTEXTO TEMPORALMENTE PARA PODER LEER EL HISTORIAL

-- MISMO PRECIO OTRA VEZ: NO CAMBIA NINGUNA COLUMNA AUDITADA
DECLARE @HIST_MEDIO_BIEN INT = (
    SELECT COUNT(*) FROM DBO.PRODUCTO_HISTORIAL
    WHERE ID_PRODUCTO = @ID_BIEN
);

EXECUTE AS USER = 'USR_ADMINISTRATIVO'; -- VOLVEMOS A ENTRAR PARA LA ÚLTIMA PRUEBA DML

EXEC DBO.USP_ACTUALIZAR_PRECIO_PRODUCTO
    @ID_PRODUCTO = @ID_BIEN,
    @NUEVO_PRECIO = @PRECIO_NUEVO,
    @CODIGO_ERROR = @COD_P2 OUTPUT,
    @MENSAJE = @MSG_P2 OUTPUT;

REVERT; -- SALIMOS DEFINITIVAMENTE


-- COMPROBACIONES: EN UPDATE EL HISTORIAL GUARDA LA VERSIÓN ANTERIOR
DECLARE @OP VARCHAR(6), @USU SYSNAME, @DIST INT, @SENAS NVARCHAR(250);
DECLARE @PRECIO DECIMAL(18, 5), @DUR SMALLINT, @DOM BIT;

SELECT TOP (1)
    @OP = T.CODIGO_OPERACION,
    @USU = H.USUARIO_RESPONSABLE,
    @DIST = H.ID_DISTRITO,
    @SENAS = H.OTRAS_SENAS
FROM DBO.DIRECCION_HISTORIAL AS H
INNER JOIN DBO.TIPO_OPERACION AS T
    ON H.ID_TIPO_OPERACION = T.ID_TIPO_OPERACION
WHERE H.ID_DIRECCION = @ID_DIR_CLI
ORDER BY H.ID_HISTORIAL DESC;

INSERT INTO @R
SELECT
    1,
    'Dirección de cliente: UPDATE guarda la versión anterior',
    CASE
        WHEN
            @COD_CLI = 0 AND @OP = 'UPDATE' AND @USU = 'USR_ADMINISTRATIVO'
            AND @DIST = @DIST_ANT_CLI AND @SENAS = @SENAS_ANT_CLI
            AND (
                SELECT COUNT(*) FROM DBO.DIRECCION_HISTORIAL
                WHERE ID_DIRECCION = @ID_DIR_CLI
            ) = @HIST_ANTES_CLI + 1
            THEN 1
        ELSE 0
    END,
    LEFT(CONCAT('codigo=', @COD_CLI, ' ', @MSG_CLI), 80);

SELECT TOP (1)
    @OP = T.CODIGO_OPERACION,
    @USU = H.USUARIO_RESPONSABLE,
    @DIST = H.ID_DISTRITO,
    @SENAS = H.OTRAS_SENAS
FROM DBO.DIRECCION_HISTORIAL AS H
INNER JOIN DBO.TIPO_OPERACION AS T
    ON H.ID_TIPO_OPERACION = T.ID_TIPO_OPERACION
WHERE H.ID_DIRECCION = @ID_DIR_EMP
ORDER BY H.ID_HISTORIAL DESC;

INSERT INTO @R
SELECT
    2,
    'Dirección de empresa: UPDATE guarda la versión anterior',
    CASE
        WHEN
            @COD_EMP = 0 AND @OP = 'UPDATE' AND @USU = 'USR_ADMINISTRATIVO'
            AND @DIST = @DIST_ANT_EMP AND @SENAS = @SENAS_ANT_EMP
            AND (
                SELECT COUNT(*) FROM DBO.DIRECCION_HISTORIAL
                WHERE ID_DIRECCION = @ID_DIR_EMP
            ) = @HIST_ANTES_EMP + 1
            THEN 1
        ELSE 0
    END,
    LEFT(CONCAT('codigo=', @COD_EMP, ' ', @MSG_EMP), 80);

SELECT TOP (1)
    @OP = T.CODIGO_OPERACION,
    @USU = H.USUARIO_RESPONSABLE,
    @PRECIO = H.PRECIO_UNITARIO
FROM DBO.PRODUCTO_HISTORIAL AS H
INNER JOIN DBO.TIPO_OPERACION AS T
    ON H.ID_TIPO_OPERACION = T.ID_TIPO_OPERACION
WHERE H.ID_PRODUCTO = @ID_BIEN
ORDER BY H.ID_HISTORIAL DESC;

INSERT INTO @R
SELECT
    3,
    'Precio de un bien: UPDATE guarda el precio anterior',
    CASE
        WHEN
            @COD_P1 = 0 AND @OP = 'UPDATE' AND @USU = 'USR_ADMINISTRATIVO'
            AND @PRECIO = @PRECIO_ANT
            AND @HIST_MEDIO_BIEN = @HIST_ANTES_BIEN + 1
            THEN 1
        ELSE 0
    END,
    LEFT(CONCAT('codigo=', @COD_P1, ' ', @MSG_P1), 80);

INSERT INTO @R
SELECT
    4,
    'Mismo precio de nuevo: NO genera fila de historial',
    CASE
        WHEN
            @COD_P2 = 0
            AND (
                SELECT COUNT(*) FROM DBO.PRODUCTO_HISTORIAL
                WHERE ID_PRODUCTO = @ID_BIEN
            ) = @HIST_MEDIO_BIEN
            THEN 1
        ELSE 0
    END,
    LEFT(CONCAT('codigo=', @COD_P2, ' ', @MSG_P2), 80);

INSERT INTO @R
SELECT
    5,
    'Servicio nuevo: INSERT en PRODUCTO_HISTORIAL y SERVICIO_HISTORIAL',
    CASE
        WHEN
            @COD_S1 = 0
            AND EXISTS (
                SELECT 1
                FROM DBO.PRODUCTO_HISTORIAL AS H
                INNER JOIN DBO.TIPO_OPERACION AS T
                    ON H.ID_TIPO_OPERACION = T.ID_TIPO_OPERACION
                WHERE
                    H.ID_PRODUCTO = @ID_SRV
                    AND T.CODIGO_OPERACION = 'INSERT'
                    AND H.USUARIO_RESPONSABLE = 'USR_ADMINISTRATIVO'
            )
            AND EXISTS (
                SELECT 1
                FROM DBO.SERVICIO_HISTORIAL AS H
                INNER JOIN DBO.TIPO_OPERACION AS T
                    ON H.ID_TIPO_OPERACION = T.ID_TIPO_OPERACION
                WHERE
                    H.ID_PRODUCTO = @ID_SRV
                    AND T.CODIGO_OPERACION = 'INSERT'
                    AND H.DURACION_ESTIMADA_MIN = 60
            )
            THEN 1
        ELSE 0
    END,
    LEFT(CONCAT('codigo=', @COD_S1, ' ', @MSG_S1), 80);

SELECT TOP (1)
    @OP = T.CODIGO_OPERACION,
    @USU = H.USUARIO_RESPONSABLE,
    @DUR = H.DURACION_ESTIMADA_MIN,
    @DOM = H.SE_BRINDA_A_DOMICILIO
FROM DBO.SERVICIO_HISTORIAL AS H
INNER JOIN DBO.TIPO_OPERACION AS T
    ON H.ID_TIPO_OPERACION = T.ID_TIPO_OPERACION
WHERE H.ID_PRODUCTO = @ID_SRV
ORDER BY H.ID_HISTORIAL DESC;

INSERT INTO @R
SELECT
    6,
    'Servicio: UPDATE guarda duración y modalidad anteriores',
    CASE
        WHEN
            @COD_S2 = 0 AND @OP = 'UPDATE' AND @USU = 'USR_ADMINISTRATIVO'
            AND @DUR = 60 AND @DOM = 0
            THEN 1
        ELSE 0
    END,
    LEFT(CONCAT('codigo=', @COD_S2, ' ', @MSG_S2), 80);

-- HISTORIALES (CONTENIDO INDICA QUÉ VERSIÓN GUARDA CADA FILA)
SELECT
    H.ID_HISTORIAL,
    T.CODIGO_OPERACION AS OPERACION,
    H.USUARIO_RESPONSABLE AS USUARIO,
    H.FECHA_CAMBIO,
    H.ID_DIRECCION,
    H.ID_DISTRITO,
    H.OTRAS_SENAS,
    CASE T.CODIGO_OPERACION
        WHEN 'UPDATE' THEN 'Versión anterior'
        WHEN 'INSERT' THEN 'Versión nueva (alta)'
        ELSE 'Última versión'
    END AS CONTENIDO
FROM DBO.DIRECCION_HISTORIAL AS H
INNER JOIN DBO.TIPO_OPERACION AS T
    ON H.ID_TIPO_OPERACION = T.ID_TIPO_OPERACION
WHERE H.ID_DIRECCION IN (@ID_DIR_CLI, @ID_DIR_EMP)
ORDER BY H.ID_DIRECCION, H.ID_HISTORIAL;

SELECT
    H.ID_HISTORIAL,
    T.CODIGO_OPERACION AS OPERACION,
    H.USUARIO_RESPONSABLE AS USUARIO,
    H.FECHA_CAMBIO,
    H.ID_PRODUCTO,
    H.PRECIO_UNITARIO,
    H.TASA_IMPUESTO,
    CASE T.CODIGO_OPERACION
        WHEN 'UPDATE' THEN 'Versión anterior'
        WHEN 'INSERT' THEN 'Versión nueva (alta)'
        ELSE 'Última versión'
    END AS CONTENIDO
FROM DBO.PRODUCTO_HISTORIAL AS H
INNER JOIN DBO.TIPO_OPERACION AS T
    ON H.ID_TIPO_OPERACION = T.ID_TIPO_OPERACION
WHERE H.ID_PRODUCTO IN (@ID_BIEN, @ID_SRV)
ORDER BY H.ID_PRODUCTO, H.ID_HISTORIAL;

SELECT
    H.ID_HISTORIAL,
    T.CODIGO_OPERACION AS OPERACION,
    H.USUARIO_RESPONSABLE AS USUARIO,
    H.FECHA_CAMBIO,
    H.ID_PRODUCTO,
    H.DURACION_ESTIMADA_MIN,
    H.SE_BRINDA_A_DOMICILIO,
    CASE T.CODIGO_OPERACION
        WHEN 'UPDATE' THEN 'Versión anterior'
        WHEN 'INSERT' THEN 'Versión nueva (alta)'
        ELSE 'Última versión'
    END AS CONTENIDO
FROM DBO.SERVICIO_HISTORIAL AS H
INNER JOIN DBO.TIPO_OPERACION AS T
    ON H.ID_TIPO_OPERACION = T.ID_TIPO_OPERACION
WHERE H.ID_PRODUCTO = @ID_SRV
ORDER BY H.ID_HISTORIAL;

-- CONSULTAS 10, 11 Y 13, CRONOMETRADAS (CRITERIO: MENOS DE 1 000 MS)
DECLARE @TEXTO_RS NVARCHAR(150) = (
    SELECT TOP (1)
        LEFT(RAZON_SOCIAL, CHARINDEX(N' ', CONCAT(RAZON_SOCIAL, N' ')) - 1)
    FROM DBO.CLIENTE_JURIDICO
    ORDER BY ID_CLIENTE
);
DECLARE @TEXTO_NC NVARCHAR(150) = (
    SELECT TOP (1)
        LEFT(
            NOMBRE_COMERCIAL,
            CHARINDEX(N' ', CONCAT(NOMBRE_COMERCIAL, N' ')) - 1
        )
    FROM DBO.CLIENTE_JURIDICO
    ORDER BY ID_CLIENTE
);
DECLARE @CODIGO_VENDIDO VARCHAR(20) = (
    SELECT TOP (1) P.CODIGO_INTERNO
    FROM DBO.DETALLE_FACTURA AS D
    INNER JOIN DBO.PRODUCTO AS P
        ON D.ID_PRODUCTO = P.ID_PRODUCTO
    GROUP BY P.CODIGO_INTERNO
    ORDER BY COUNT(*) DESC
);
DECLARE @HASTA DATE = CAST(SYSDATETIME() AS DATE);
DECLARE @DESDE DATE = DATEADD(YEAR, -1, @HASTA);

DECLARE @T0 DATETIME2(7), @FILAS INT, @MS INT, @X VARCHAR(30);

SET @T0 = SYSDATETIME();
SELECT @FILAS = COUNT(*), @X = MAX(CEDULA)
FROM DBO.UFN_BUSCAR_JURIDICA_RAZON_SOCIAL(@TEXTO_RS);
SET @MS = DATEDIFF(MILLISECOND, @T0, SYSDATETIME());
INSERT INTO @R
SELECT
    7,
    'Consulta 10: razón social contiene el texto',
    CASE WHEN @MS < 1000 THEN 1 ELSE 0 END,
    CONCAT(@FILAS, ' fila(s) en ', @MS, ' ms');

SET @T0 = SYSDATETIME();
SELECT @FILAS = COUNT(*), @X = MAX(CEDULA)
FROM DBO.UFN_BUSCAR_JURIDICA_NOMBRE_COMERCIAL(@TEXTO_NC);
SET @MS = DATEDIFF(MILLISECOND, @T0, SYSDATETIME());
INSERT INTO @R
SELECT
    8,
    'Consulta 11: nombre comercial contiene el texto',
    CASE WHEN @MS < 1000 THEN 1 ELSE 0 END,
    CONCAT(@FILAS, ' fila(s) en ', @MS, ' ms');

DECLARE @MAX_FACTURA INT, @MAX_FECHA DATETIME2(0);

SET @T0 = SYSDATETIME();
SELECT
    @FILAS = COUNT(*),
    @MAX_FACTURA = MAX(ID_FACTURA),
    @MAX_FECHA = MAX(FECHA_EMISION)
FROM DBO.UFN_VENTAS_PRODUCTO_RANGO(@CODIGO_VENDIDO, @DESDE, @HASTA);
SET @MS = DATEDIFF(MILLISECOND, @T0, SYSDATETIME());
INSERT INTO @R
SELECT
    9,
    'Consulta 13: ventas del producto más vendido en el último año',
    CASE WHEN @MS < 1000 THEN 1 ELSE 0 END,
    CONCAT(@FILAS, ' línea(s) en ', @MS, ' ms');

-- MUESTRAS DE LAS CONSULTAS
SELECT TOP (5) *
FROM DBO.UFN_BUSCAR_JURIDICA_RAZON_SOCIAL(@TEXTO_RS)
ORDER BY RAZON_SOCIAL;

SELECT TOP (5) *
FROM DBO.UFN_BUSCAR_JURIDICA_NOMBRE_COMERCIAL(@TEXTO_NC)
ORDER BY NOMBRE_COMERCIAL;

SELECT TOP (5) *
FROM DBO.UFN_VENTAS_PRODUCTO_RANGO(@CODIGO_VENDIDO, @DESDE, @HASTA)
ORDER BY FECHA_EMISION DESC, ID_FACTURA;

-- RESUMEN
SELECT
    R.ORDEN,
    R.PRUEBA,
    CASE WHEN R.PASA = 1 THEN 'PASA' ELSE 'FALLA' END AS RESULTADO,
    R.DETALLE
FROM @R AS R
ORDER BY R.ORDEN;
GO
