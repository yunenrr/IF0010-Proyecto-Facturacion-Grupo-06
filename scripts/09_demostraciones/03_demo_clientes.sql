/* DEMOSTRACIÓN — AUDITORÍA DE PERSONAS FÍSICAS Y JURÍDICAS, Y BÚSQUEDA DE
   PERSONAS FÍSICAS POR NOMBRE Y APELLIDO.
   1. USR_ADMINISTRATIVO REGISTRA UNA PERSONA FÍSICA Y UNA JURÍDICA Y LUEGO
      CAMBIA SUS NOMBRES. LOS TRIGGERS DEJAN EL RASTRO EN LOS HISTORIALES.
   2. USR_CONSULTA EJECUTA LAS DOS BÚSQUEDAS Y SE MIDE SU DURACIÓN (< 1 S).
   CADA EJECUCIÓN CREA CLIENTES NUEVOS (CÉDULA Y CORREO GENERADOS) Y LOS
   CONSERVA. */

USE SISTEMA_FACTURACION;
GO

SET NOCOUNT ON;

-- DATOS ÚNICOS POR EJECUCIÓN. LAS FÍSICAS CARGADAS EMPIEZAN CON 1 A 7 Y LAS
-- JURÍDICAS CON 3102, ASÍ QUE ESTAS CÉDULAS NO CHOCAN CON LA CARGA.
DECLARE @SELLO INT = DATEDIFF(SECOND, '20260101', SYSDATETIME());
DECLARE @CEDULA_FISICA VARCHAR(12) = CONCAT(
    '9', RIGHT(CONCAT('00000000', @SELLO % 100000000), 8)
);
DECLARE @CEDULA_JURIDICA VARCHAR(12) = CONCAT(
    '3101', 900000 + @SELLO % 100000
);
DECLARE @CORREO_FISICA VARCHAR(254) = CONCAT(
    'demo.fisica', @SELLO, '@ejemplo.com'
);
DECLARE @CORREO_JURIDICA VARCHAR(254) = CONCAT(
    'demo.juridica', @SELLO, '@ejemplo.cr'
);
DECLARE @ID_DISTRITO INT = (SELECT MIN(ID_DISTRITO) FROM DBO.DISTRITO);

DECLARE @ID_FISICA INT;
DECLARE @ID_JURIDICA INT;
DECLARE @CODIGO INT;
DECLARE @MENSAJE NVARCHAR(4000);
DECLARE @ERRORES NVARCHAR(4000) = N'';

DECLARE @F_INSERT INT;
DECLARE @F_UPDATE INT;
DECLARE @F_TOTAL INT;
DECLARE @J_INSERT INT;
DECLARE @J_UPDATE INT;
DECLARE @J_ACTUAL NVARCHAR(150);

DECLARE @T0 DATETIME2(7);
DECLARE @MS_08 INT;
DECLARE @MS_09 INT;

DECLARE @R08 TABLE (
    CEDULA VARCHAR(12) NOT NULL,
    NOMBRE NVARCHAR(50) NOT NULL,
    PRIMER_APELLIDO NVARCHAR(50) NOT NULL,
    SEGUNDO_APELLIDO NVARCHAR(50) NOT NULL,
    FECHA_REGISTRO DATETIME2(3) NOT NULL
);

DECLARE @R09 TABLE (
    CEDULA VARCHAR(12) NOT NULL,
    NOMBRE NVARCHAR(50) NOT NULL,
    PRIMER_APELLIDO NVARCHAR(50) NOT NULL,
    SEGUNDO_APELLIDO NVARCHAR(50) NOT NULL,
    FECHA_REGISTRO DATETIME2(3) NOT NULL
);

-- 1. CAMBIOS DE DATOS COMO USR_ADMINISTRATIVO
EXECUTE AS USER = 'USR_ADMINISTRATIVO'; -- noqa: PRS

EXEC DBO.USP_REGISTRAR_CLIENTE_FISICO
    @CEDULA = @CEDULA_FISICA,
    @NOMBRE = N'Lucía',
    @PRIMER_APELLIDO = N'Mora',
    @SEGUNDO_APELLIDO = N'Soto',
    @CORREO = @CORREO_FISICA,
    @TELEFONO = '88887777',
    @ID_DISTRITO = @ID_DISTRITO,
    @OTRAS_SENAS = N'Frente al parque central',
    @ID_CLIENTE = @ID_FISICA OUTPUT,
    @CODIGO_ERROR = @CODIGO OUTPUT,
    @MENSAJE = @MENSAJE OUTPUT;
IF @CODIGO <> 0 SET @ERRORES = CONCAT(@ERRORES, N'[REG. FÍSICA] ', @MENSAJE);

EXEC DBO.USP_REGISTRAR_CLIENTE_JURIDICO
    @CEDULA = @CEDULA_JURIDICA,
    @RAZON_SOCIAL = N'Servicios Demo Mora y Soto S.A.',
    @NOMBRE_COMERCIAL = N'Soda La Demo',
    @CORREO = @CORREO_JURIDICA,
    @TELEFONO = '22223333',
    @ID_DISTRITO = @ID_DISTRITO,
    @OTRAS_SENAS = N'Costado norte de la iglesia',
    @ID_CLIENTE = @ID_JURIDICA OUTPUT,
    @CODIGO_ERROR = @CODIGO OUTPUT,
    @MENSAJE = @MENSAJE OUTPUT;
IF @CODIGO <> 0 SET @ERRORES = CONCAT(@ERRORES, N'[REG. JURÍDICA] ', @MENSAJE);

-- CAMBIO REAL: SE GUARDA EL SEGUNDO APELLIDO ANTERIOR (SOTO)
EXEC DBO.USP_ACTUALIZAR_CLIENTE_FISICO
    @ID_CLIENTE = @ID_FISICA,
    @SEGUNDO_APELLIDO = N'Solano',
    @CODIGO_ERROR = @CODIGO OUTPUT,
    @MENSAJE = @MENSAJE OUTPUT;
IF @CODIGO <> 0 SET @ERRORES = CONCAT(@ERRORES, N'[ACT. FÍSICA] ', @MENSAJE);

-- MISMO VALOR: EL TRIGGER NO DEBE REGISTRAR NADA
EXEC DBO.USP_ACTUALIZAR_CLIENTE_FISICO
    @ID_CLIENTE = @ID_FISICA,
    @NOMBRE = N'Lucía',
    @CODIGO_ERROR = @CODIGO OUTPUT,
    @MENSAJE = @MENSAJE OUTPUT;
IF @CODIGO <> 0 SET @ERRORES = CONCAT(@ERRORES, N'[SIN CAMBIO] ', @MENSAJE);

-- CAMBIO REAL: SE GUARDA EL NOMBRE COMERCIAL ANTERIOR (SODA LA DEMO)
EXEC DBO.USP_ACTUALIZAR_CLIENTE_JURIDICO
    @ID_CLIENTE = @ID_JURIDICA,
    @NOMBRE_COMERCIAL = N'Soda La Esquina',
    @CODIGO_ERROR = @CODIGO OUTPUT,
    @MENSAJE = @MENSAJE OUTPUT;
IF @CODIGO <> 0 SET @ERRORES = CONCAT(@ERRORES, N'[ACT. JURÍDICA] ', @MENSAJE);

REVERT; -- noqa: PRS

-- 2. LO QUE DEJARON LOS TRIGGERS
SELECT @F_INSERT = COUNT(*)
FROM DBO.CLIENTE_FISICO_HISTORIAL AS H
INNER JOIN DBO.TIPO_OPERACION AS T
    ON H.ID_TIPO_OPERACION = T.ID_TIPO_OPERACION
WHERE
    H.ID_CLIENTE = @ID_FISICA
    AND T.CODIGO_OPERACION = 'INSERT'
    AND H.SEGUNDO_APELLIDO = N'Soto'
    AND H.USUARIO_RESPONSABLE = 'USR_ADMINISTRATIVO';

SELECT @F_UPDATE = COUNT(*)
FROM DBO.CLIENTE_FISICO_HISTORIAL AS H
INNER JOIN DBO.TIPO_OPERACION AS T
    ON H.ID_TIPO_OPERACION = T.ID_TIPO_OPERACION
WHERE
    H.ID_CLIENTE = @ID_FISICA
    AND T.CODIGO_OPERACION = 'UPDATE'
    AND H.SEGUNDO_APELLIDO = N'Soto';

SELECT @F_TOTAL = COUNT(*)
FROM DBO.CLIENTE_FISICO_HISTORIAL
WHERE ID_CLIENTE = @ID_FISICA;

SELECT @J_INSERT = COUNT(*)
FROM DBO.CLIENTE_JURIDICO_HISTORIAL AS H
INNER JOIN DBO.TIPO_OPERACION AS T
    ON H.ID_TIPO_OPERACION = T.ID_TIPO_OPERACION
WHERE
    H.ID_CLIENTE = @ID_JURIDICA
    AND T.CODIGO_OPERACION = 'INSERT'
    AND H.NOMBRE_COMERCIAL = N'Soda La Demo';

SELECT @J_UPDATE = COUNT(*)
FROM DBO.CLIENTE_JURIDICO_HISTORIAL AS H
INNER JOIN DBO.TIPO_OPERACION AS T
    ON H.ID_TIPO_OPERACION = T.ID_TIPO_OPERACION
WHERE
    H.ID_CLIENTE = @ID_JURIDICA
    AND T.CODIGO_OPERACION = 'UPDATE'
    AND H.NOMBRE_COMERCIAL = N'Soda La Demo';

SELECT @J_ACTUAL = NOMBRE_COMERCIAL
FROM DBO.CLIENTE_JURIDICO
WHERE ID_CLIENTE = @ID_JURIDICA;

-- 3. BÚSQUEDAS COMO USR_CONSULTA, CRONOMETRADAS
EXECUTE AS USER = 'USR_CONSULTA'; -- noqa: PRS

SET @T0 = SYSDATETIME();
INSERT INTO @R08
SELECT
    B.CEDULA,
    B.NOMBRE,
    B.PRIMER_APELLIDO,
    B.SEGUNDO_APELLIDO,
    B.FECHA_REGISTRO
FROM DBO.UFN_BUSCAR_FISICA_PRIMER_APELLIDO(N'María', N'Vargas') AS B;
SET @MS_08 = DATEDIFF(MILLISECOND, @T0, SYSDATETIME());

SET @T0 = SYSDATETIME();
INSERT INTO @R09
SELECT
    B.CEDULA,
    B.NOMBRE,
    B.PRIMER_APELLIDO,
    B.SEGUNDO_APELLIDO,
    B.FECHA_REGISTRO
FROM DBO.UFN_BUSCAR_FISICA_SEGUNDO_APELLIDO(N'Lucía', N'Solano') AS B;
SET @MS_09 = DATEDIFF(MILLISECOND, @T0, SYSDATETIME());

REVERT; -- noqa: PRS

-- 4. RESULTADOS
SELECT
    V.NUMERO,
    V.PRUEBA,
    V.ESPERADO,
    ISNULL(V.OBTENIDO, N'(sin valor)') AS OBTENIDO,
    CASE WHEN V.CUMPLE = 1 THEN 'PASA' ELSE 'FALLA' END AS RESULTADO
FROM (
    VALUES
    (
        1, N'Los procedimientos terminan sin error', N'(sin errores)',
        NULLIF(@ERRORES, N''),
        IIF(@ERRORES = N'', 1, 0)
    ),
    (
        2, N'Física: INSERT con el valor nuevo y USR_ADMINISTRATIVO',
        N'1',
        CONCAT(@F_INSERT, N''),
        IIF(@F_INSERT = 1, 1, 0)
    ),
    (
        3, N'Física: UPDATE guarda el segundo apellido anterior',
        N'1',
        CONCAT(@F_UPDATE, N''),
        IIF(@F_UPDATE = 1, 1, 0)
    ),
    (
        4, N'Física: un UPDATE sin cambios no genera fila',
        N'2 filas en total',
        CONCAT(@F_TOTAL, N' filas en total'),
        IIF(@F_TOTAL = 2, 1, 0)
    ),
    (
        5, N'Jurídica: INSERT con el nombre comercial nuevo',
        N'1',
        CONCAT(@J_INSERT, N''),
        IIF(@J_INSERT = 1, 1, 0)
    ),
    (
        6, N'Jurídica: UPDATE guarda el nombre comercial anterior',
        N'1 (actual: Soda La Esquina)',
        CONCAT(@J_UPDATE, N' (actual: ', @J_ACTUAL, N')'),
        IIF(@J_UPDATE = 1 AND @J_ACTUAL = N'Soda La Esquina', 1, 0)
    ),
    (
        7, N'Búsqueda por nombre y primer apellido (María Vargas)',
        N'Filas > 0 y < 1000 ms',
        CONCAT((SELECT COUNT(*) FROM @R08), N' filas, ', @MS_08, N' ms'),
        IIF((SELECT COUNT(*) FROM @R08) > 0 AND @MS_08 < 1000, 1, 0)
    ),
    (
        8, N'Búsqueda por nombre y segundo apellido (Lucía Solano)',
        N'Incluye la física de la demo y < 1000 ms',
        CONCAT((SELECT COUNT(*) FROM @R09), N' filas, ', @MS_09, N' ms'),
        IIF(
            EXISTS (SELECT 1 FROM @R09 WHERE CEDULA = @CEDULA_FISICA)
            AND @MS_09 < 1000,
            1,
            0
        )
    )
) AS V (NUMERO, PRUEBA, ESPERADO, OBTENIDO, CUMPLE)
ORDER BY V.NUMERO;

-- DETALLE: HISTORIAL DE LOS DOS CLIENTES DE ESTA EJECUCIÓN
SELECT
    'CLIENTE_FISICO' AS TABLA,
    H.ID_CLIENTE,
    T.CODIGO_OPERACION AS OPERACION,
    H.USUARIO_RESPONSABLE,
    H.FECHA_CAMBIO,
    CONCAT(
        H.NOMBRE, N' ', H.PRIMER_APELLIDO, N' ', H.SEGUNDO_APELLIDO
    ) AS VALORES_GUARDADOS
FROM DBO.CLIENTE_FISICO_HISTORIAL AS H
INNER JOIN DBO.TIPO_OPERACION AS T
    ON H.ID_TIPO_OPERACION = T.ID_TIPO_OPERACION
WHERE H.ID_CLIENTE = @ID_FISICA
UNION ALL
SELECT
    'CLIENTE_JURIDICO' AS TABLA,
    H.ID_CLIENTE,
    T.CODIGO_OPERACION AS OPERACION,
    H.USUARIO_RESPONSABLE,
    H.FECHA_CAMBIO,
    CONCAT(H.RAZON_SOCIAL, N' | ', H.NOMBRE_COMERCIAL) AS VALORES_GUARDADOS
FROM DBO.CLIENTE_JURIDICO_HISTORIAL AS H
INNER JOIN DBO.TIPO_OPERACION AS T
    ON H.ID_TIPO_OPERACION = T.ID_TIPO_OPERACION
WHERE H.ID_CLIENTE = @ID_JURIDICA
ORDER BY TABLA, FECHA_CAMBIO;

-- DETALLE: PRIMERAS FILAS DE CADA BÚSQUEDA
SELECT TOP (10)
    R.CEDULA,
    R.NOMBRE,
    R.PRIMER_APELLIDO,
    R.SEGUNDO_APELLIDO,
    R.FECHA_REGISTRO
FROM @R08 AS R
ORDER BY R.SEGUNDO_APELLIDO, R.CEDULA;

SELECT TOP (10)
    R.CEDULA,
    R.NOMBRE,
    R.PRIMER_APELLIDO,
    R.SEGUNDO_APELLIDO,
    R.FECHA_REGISTRO
FROM @R09 AS R
ORDER BY R.PRIMER_APELLIDO, R.CEDULA;
GO
