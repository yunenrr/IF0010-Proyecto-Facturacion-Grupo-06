/* SEGURIDAD — ROLES DEL SISTEMA Y USUARIOS DE PRUEBA. */

USE SISTEMA_FACTURACION;
GO

SET NOCOUNT ON;
SET XACT_ABORT ON;

BEGIN TRY
    BEGIN TRANSACTION;

    -- 1. ROLES
    IF DATABASE_PRINCIPAL_ID('AUDITOR') IS NULL
        CREATE ROLE AUDITOR;

    IF DATABASE_PRINCIPAL_ID('DBA') IS NULL
        CREATE ROLE DBA;

    IF DATABASE_PRINCIPAL_ID('ADMINISTRATIVO') IS NULL
        CREATE ROLE ADMINISTRATIVO;

    IF DATABASE_PRINCIPAL_ID('CAJERO') IS NULL
        CREATE ROLE CAJERO;

    IF DATABASE_PRINCIPAL_ID('CONSULTA') IS NULL
        CREATE ROLE CONSULTA;

    -- 2. USUARIOS DE PRUEBA
    IF DATABASE_PRINCIPAL_ID('USR_AUDITOR') IS NULL
        CREATE USER USR_AUDITOR WITHOUT LOGIN;

    IF DATABASE_PRINCIPAL_ID('USR_DBA') IS NULL
        CREATE USER USR_DBA WITHOUT LOGIN;

    IF DATABASE_PRINCIPAL_ID('USR_ADMINISTRATIVO') IS NULL
        CREATE USER USR_ADMINISTRATIVO WITHOUT LOGIN;

    IF DATABASE_PRINCIPAL_ID('USR_CAJERO') IS NULL
        CREATE USER USR_CAJERO WITHOUT LOGIN;

    IF DATABASE_PRINCIPAL_ID('USR_CONSULTA') IS NULL
        CREATE USER USR_CONSULTA WITHOUT LOGIN;

    -- 3. CADA USUARIO DE PRUEBA EN SU ROL
    IF ISNULL(IS_ROLEMEMBER('AUDITOR', 'USR_AUDITOR'), 0) = 0
        ALTER ROLE AUDITOR ADD MEMBER USR_AUDITOR;

    IF ISNULL(IS_ROLEMEMBER('DBA', 'USR_DBA'), 0) = 0
        ALTER ROLE DBA ADD MEMBER USR_DBA;

    IF ISNULL(IS_ROLEMEMBER('ADMINISTRATIVO', 'USR_ADMINISTRATIVO'), 0) = 0
        ALTER ROLE ADMINISTRATIVO ADD MEMBER USR_ADMINISTRATIVO;

    IF ISNULL(IS_ROLEMEMBER('CAJERO', 'USR_CAJERO'), 0) = 0
        ALTER ROLE CAJERO ADD MEMBER USR_CAJERO;

    IF ISNULL(IS_ROLEMEMBER('CONSULTA', 'USR_CONSULTA'), 0) = 0
        ALTER ROLE CONSULTA ADD MEMBER USR_CONSULTA;

    COMMIT TRANSACTION;
END TRY
BEGIN CATCH
    IF XACT_STATE() <> 0
        ROLLBACK TRANSACTION;

    THROW;
END CATCH;
GO
