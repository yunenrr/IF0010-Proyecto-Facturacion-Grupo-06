/* DATOS DE DBO.TIPO_PRODUCTO — DISTINGUE BIENES (PRD) DE SERVICIOS (SRV). */

USE SISTEMA_FACTURACION;
GO

CREATE OR ALTER PROCEDURE DBO.USP_CARGAR_TIPO_PRODUCTO
    @FILAS_INSERTADAS INT OUTPUT,
    @CODIGO_ERROR INT OUTPUT,
    @MENSAJE NVARCHAR(4000) OUTPUT
AS
BEGIN
    SET NOCOUNT ON;
    SET XACT_ABORT ON;

    SET @FILAS_INSERTADAS = 0;
    SET @CODIGO_ERROR = 0;
    SET @MENSAJE = N'Tipos de producto cargados.';

    BEGIN TRY
        BEGIN TRANSACTION;

        INSERT INTO DBO.TIPO_PRODUCTO (
            ID_TIPO_PRODUCTO,
            CODIGO_TIPO,
            DESCRIPCION_TIPO
        )
        SELECT
            V.ID_TIPO_PRODUCTO,
            V.CODIGO_TIPO,
            V.DESCRIPCION_TIPO
        FROM (
            VALUES
            (1, 'PRD', N'Bien'),
            (2, 'SRV', N'Servicio')
        ) AS V(ID_TIPO_PRODUCTO, CODIGO_TIPO, DESCRIPCION_TIPO)
        WHERE NOT EXISTS (
            SELECT 1
            FROM DBO.TIPO_PRODUCTO AS T
            WHERE T.ID_TIPO_PRODUCTO = V.ID_TIPO_PRODUCTO
        );

        SET @FILAS_INSERTADAS = @@ROWCOUNT;

        IF (SELECT COUNT(*) FROM DBO.TIPO_PRODUCTO) < 2
            THROW 50716,
            N'El catálogo de tipos de producto quedó incompleto.',
            1;

        COMMIT TRANSACTION;
    END TRY
    BEGIN CATCH
        IF XACT_STATE() <> 0
            ROLLBACK TRANSACTION;

        SET @FILAS_INSERTADAS = 0;
        SET @CODIGO_ERROR = ERROR_NUMBER();
        SET @MENSAJE = ERROR_MESSAGE();
    END CATCH;
END;
GO

-- EJECUCIÓN DE LA CARGA
DECLARE @FILAS INT, @CODIGO INT, @MENSAJE NVARCHAR(4000);

EXEC DBO.USP_CARGAR_TIPO_PRODUCTO
    @FILAS_INSERTADAS = @FILAS OUTPUT,
    @CODIGO_ERROR = @CODIGO OUTPUT,
    @MENSAJE = @MENSAJE OUTPUT;

PRINT CONCAT('TIPO_PRODUCTO: ', @FILAS, ' fila(s) nueva(s). ', @MENSAJE);

IF @CODIGO <> 0
    THROW 50700, @MENSAJE, 1;
GO
