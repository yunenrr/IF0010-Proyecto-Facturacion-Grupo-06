/* DATOS DE DBO.TIPO_DOCUMENTO — TIPOS DE COMPROBANTE QUE PUEDE EMITIR UNA
   EMPRESA.*/

USE SISTEMA_FACTURACION;
GO

SET NOCOUNT ON;

INSERT INTO DBO.TIPO_DOCUMENTO (
    ID_TIPO_DOCUMENTO,
    CODIGO_IDENTIFICADOR,
    DESCRIPCION
)
SELECT
    V.ID_TIPO_DOCUMENTO,
    V.CODIGO_IDENTIFICADOR,
    V.DESCRIPCION
FROM (
    VALUES
    (1, 'FAC', N'Factura electrónica'),
    (2, 'TIQ', N'Tiquete electrónico')
) AS V (ID_TIPO_DOCUMENTO, CODIGO_IDENTIFICADOR, DESCRIPCION)
WHERE NOT EXISTS (
    SELECT 1
    FROM DBO.TIPO_DOCUMENTO AS T
    WHERE T.ID_TIPO_DOCUMENTO = V.ID_TIPO_DOCUMENTO
);

PRINT CONCAT('TIPO_DOCUMENTO: ', @@ROWCOUNT, ' FILA(S) NUEVA(S).');
GO

SET NOCOUNT OFF;
GO
