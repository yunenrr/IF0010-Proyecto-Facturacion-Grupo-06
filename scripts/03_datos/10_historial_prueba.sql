/* DATOS DE PRUEBA PARA LAS TABLAS DE HISTORIAL (AUDITORÍA). */

USE SISTEMA_FACTURACION;
GO

SET QUOTED_IDENTIFIER ON;
SET ANSI_NULLS ON;
GO

CREATE OR ALTER PROCEDURE DBO.USP_CARGAR_HISTORIAL_PRUEBA
    @CANTIDAD_INSERTADA INT OUTPUT,
    @CODIGO_ERROR INT OUTPUT,
    @MENSAJE NVARCHAR(4000) OUTPUT
AS
BEGIN
    SET NOCOUNT ON;
    SET XACT_ABORT ON;

    SET @CANTIDAD_INSERTADA = 0;
    SET @CODIGO_ERROR = 0;
    SET @MENSAJE = N'Historial de prueba cargado.';

    DECLARE @ID_INSERT TINYINT;
    DECLARE @ID_UPDATE TINYINT;
    DECLARE @ID_BORRADOR TINYINT;
    DECLARE @ID_MIN INT;
    DECLARE @PASO INT;

    BEGIN TRY
        IF
            EXISTS (SELECT 1 FROM DBO.FACTURA_HISTORIAL)
            OR EXISTS (SELECT 1 FROM DBO.DETALLE_FACTURA_HISTORIAL)
            OR EXISTS (SELECT 1 FROM DBO.CLIENTE_HISTORIAL)
            OR EXISTS (SELECT 1 FROM DBO.PRODUCTO_HISTORIAL)
            BEGIN
                SET @MENSAJE = N'El historial ya tenía datos; no se cargó.';
                RETURN;
            END;

        SELECT @ID_INSERT = ID_TIPO_OPERACION
        FROM DBO.TIPO_OPERACION
        WHERE CODIGO_OPERACION = 'INSERT';

        SELECT @ID_UPDATE = ID_TIPO_OPERACION
        FROM DBO.TIPO_OPERACION
        WHERE CODIGO_OPERACION = 'UPDATE';

        SELECT @ID_BORRADOR = ID_ESTADO_FACTURA
        FROM DBO.ESTADO_FACTURA
        WHERE ESTADO = 'BORRADOR';

        IF @ID_INSERT IS NULL OR @ID_UPDATE IS NULL OR @ID_BORRADOR IS NULL
            THROW 50801,
            N'Faltan datos en TIPO_OPERACION o ESTADO_FACTURA.',
            1;

        -- MUESTRA DE 20 FACTURAS
        SELECT
            @ID_MIN = MIN(ID_FACTURA),
            @PASO = CEILING(COUNT(*) / 20.0)
        FROM DBO.FACTURA;

        IF @ID_MIN IS NULL
            THROW 50802,
            N'FACTURA está vacía; ejecute primero la carga de facturas.',
            1;

        CREATE TABLE #MUESTRA_FACTURA (ID_FACTURA INT NOT NULL PRIMARY KEY);

        INSERT INTO #MUESTRA_FACTURA (ID_FACTURA)
        SELECT TOP (20) F.ID_FACTURA
        FROM DBO.FACTURA AS F
        WHERE (F.ID_FACTURA - @ID_MIN) % @PASO = 0
        ORDER BY F.ID_FACTURA;

        BEGIN TRANSACTION;

        -- 1. FACTURA: CREACIÓN EN BORRADOR
        INSERT INTO DBO.FACTURA_HISTORIAL (
            ID_FACTURA, ID_TIPO_OPERACION, USUARIO_RESPONSABLE,
            FECHA_CAMBIO, CONSECUTIVO, ID_ESTADO_FACTURA, MONTO_FINAL
        )
        SELECT
            F.ID_FACTURA,
            @ID_INSERT AS ID_TIPO_OPERACION,
            'USR_CAJERO' AS USUARIO_RESPONSABLE,
            F.FECHA_CREACION AS FECHA_CAMBIO,
            F.CONSECUTIVO,
            @ID_BORRADOR AS ID_ESTADO_FACTURA,
            F.MONTO_FINAL
        FROM DBO.FACTURA AS F
        INNER JOIN #MUESTRA_FACTURA AS M
            ON F.ID_FACTURA = M.ID_FACTURA;

        SET @CANTIDAD_INSERTADA += @@ROWCOUNT;

        -- 2. FACTURA: CAMBIO AL ESTADO ACTUAL
        INSERT INTO DBO.FACTURA_HISTORIAL (
            ID_FACTURA, ID_TIPO_OPERACION, USUARIO_RESPONSABLE,
            FECHA_CAMBIO, CONSECUTIVO, ID_ESTADO_FACTURA, MONTO_FINAL
        )
        SELECT
            F.ID_FACTURA,
            @ID_UPDATE AS ID_TIPO_OPERACION,
            'USR_CAJERO' AS USUARIO_RESPONSABLE,
            F.FECHA_MODIFICACION AS FECHA_CAMBIO,
            F.CONSECUTIVO,
            F.ID_ESTADO_FACTURA,
            F.MONTO_FINAL
        FROM DBO.FACTURA AS F
        INNER JOIN #MUESTRA_FACTURA AS M
            ON F.ID_FACTURA = M.ID_FACTURA
        WHERE F.ID_ESTADO_FACTURA <> @ID_BORRADOR;

        SET @CANTIDAD_INSERTADA += @@ROWCOUNT;

        -- 3. DETALLE_FACTURA
        INSERT INTO DBO.DETALLE_FACTURA_HISTORIAL (
            ID_DETALLE, ID_FACTURA, NUMERO_LINEA, ID_TIPO_OPERACION,
            USUARIO_RESPONSABLE, FECHA_CAMBIO, CANTIDAD_FACTURADA,
            PRECIO_UNITARIO, MONTO_DESCUENTO, TASA_IMPUESTO,
            MONTO_IMPUESTO_LINEA, MONTO_TOTAL_LINEA
        )
        SELECT
            D.ID_DETALLE,
            D.ID_FACTURA,
            D.NUMERO_LINEA,
            @ID_INSERT AS ID_TIPO_OPERACION,
            'USR_CAJERO' AS USUARIO_RESPONSABLE,
            F.FECHA_CREACION AS FECHA_CAMBIO,
            D.CANTIDAD_FACTURADA,
            D.PRECIO_UNITARIO,
            D.MONTO_DESCUENTO,
            D.TASA_IMPUESTO,
            D.MONTO_IMPUESTO_LINEA,
            D.MONTO_TOTAL_LINEA
        FROM DBO.DETALLE_FACTURA AS D
        INNER JOIN #MUESTRA_FACTURA AS M
            ON D.ID_FACTURA = M.ID_FACTURA
        INNER JOIN DBO.FACTURA AS F
            ON D.ID_FACTURA = F.ID_FACTURA;

        SET @CANTIDAD_INSERTADA += @@ROWCOUNT;

        -- 4. CLIENTE
        INSERT INTO DBO.CLIENTE_HISTORIAL (
            ID_CLIENTE, ID_TIPO_OPERACION, USUARIO_RESPONSABLE, FECHA_CAMBIO,
            CEDULA_CLIENTE, CORREO_CLIENTE, TELEFONO_CLIENTE, ID_DIRECCION
        )
        SELECT TOP (10)
            C.ID_CLIENTE,
            @ID_INSERT AS ID_TIPO_OPERACION,
            'USR_ADMINISTRATIVO' AS USUARIO_RESPONSABLE,
            C.FECHA_REGISTRO AS FECHA_CAMBIO,
            C.CEDULA_CLIENTE,
            C.CORREO_CLIENTE,
            C.TELEFONO_CLIENTE,
            C.ID_DIRECCION
        FROM DBO.CLIENTE AS C
        ORDER BY C.ID_CLIENTE;

        SET @CANTIDAD_INSERTADA += @@ROWCOUNT;

        -- 5. CLIENTE
        INSERT INTO DBO.CLIENTE_HISTORIAL (
            ID_CLIENTE, ID_TIPO_OPERACION, USUARIO_RESPONSABLE, FECHA_CAMBIO,
            CEDULA_CLIENTE, CORREO_CLIENTE, TELEFONO_CLIENTE, ID_DIRECCION
        )
        SELECT
            C.ID_CLIENTE,
            @ID_UPDATE AS ID_TIPO_OPERACION,
            'USR_ADMINISTRATIVO' AS USUARIO_RESPONSABLE,
            C.FECHA_ACTUALIZACION AS FECHA_CAMBIO,
            C.CEDULA_CLIENTE,
            C.CORREO_CLIENTE,
            C.TELEFONO_CLIENTE,
            C.ID_DIRECCION
        FROM DBO.CLIENTE AS C
        WHERE
            C.FECHA_ACTUALIZACION > C.FECHA_REGISTRO
            AND C.ID_CLIENTE IN (
                SELECT TOP (10) C2.ID_CLIENTE
                FROM DBO.CLIENTE AS C2
                ORDER BY C2.ID_CLIENTE
            );

        SET @CANTIDAD_INSERTADA += @@ROWCOUNT;

        -- 6. PRODUCTO
        INSERT INTO DBO.PRODUCTO_HISTORIAL (
            ID_PRODUCTO, ID_TIPO_OPERACION, USUARIO_RESPONSABLE,
            FECHA_CAMBIO, PRECIO_UNITARIO, TASA_IMPUESTO
        )
        SELECT TOP (10)
            P.ID_PRODUCTO,
            @ID_INSERT AS ID_TIPO_OPERACION,
            'USR_ADMINISTRATIVO' AS USUARIO_RESPONSABLE,
            P.FECHA_CREACION AS FECHA_CAMBIO,
            P.PRECIO_UNITARIO,
            P.TASA_IMPUESTO
        FROM DBO.PRODUCTO AS P
        ORDER BY P.ID_PRODUCTO;

        SET @CANTIDAD_INSERTADA += @@ROWCOUNT;

        COMMIT TRANSACTION;
    END TRY
    BEGIN CATCH
        IF XACT_STATE() <> 0
            ROLLBACK TRANSACTION;

        SET @CANTIDAD_INSERTADA = 0;
        SET @CODIGO_ERROR = ERROR_NUMBER();
        SET @MENSAJE = ERROR_MESSAGE();
    END CATCH;
END;
GO

-- EJECUCIÓN
DECLARE @FILAS INT, @CODIGO INT, @MENSAJE NVARCHAR(4000);

EXEC DBO.USP_CARGAR_HISTORIAL_PRUEBA
    @CANTIDAD_INSERTADA = @FILAS OUTPUT,
    @CODIGO_ERROR = @CODIGO OUTPUT,
    @MENSAJE = @MENSAJE OUTPUT;

PRINT CONCAT('HISTORIAL DE PRUEBA: ', @FILAS, ' fila(s) nueva(s). ', @MENSAJE);

IF @CODIGO <> 0
    THROW 50800, @MENSAJE, 1;
GO

-- VERIFICACIÓN
SELECT
    'FACTURA_HISTORIAL' AS TABLA,
    COUNT(*) AS FILAS
FROM DBO.FACTURA_HISTORIAL
UNION ALL
SELECT
    'DETALLE_FACTURA_HISTORIAL' AS TABLA,
    COUNT(*) AS FILAS
FROM DBO.DETALLE_FACTURA_HISTORIAL
UNION ALL
SELECT
    'CLIENTE_HISTORIAL' AS TABLA,
    COUNT(*) AS FILAS
FROM DBO.CLIENTE_HISTORIAL
UNION ALL
SELECT
    'PRODUCTO_HISTORIAL' AS TABLA,
    COUNT(*) AS FILAS
FROM DBO.PRODUCTO_HISTORIAL;
GO
