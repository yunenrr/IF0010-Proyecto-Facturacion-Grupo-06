/* DATOS DE DBO.TIPO_DOCUMENTO — TIPOS DE COMPROBANTE QUE PUEDE EMITIR UNA
   EMPRESA. */

USE SISTEMA_FACTURACION;
GO

CREATE OR ALTER PROCEDURE DBO.USP_CARGAR_TIPO_DOCUMENTO
    @FILAS_INSERTADAS INT OUTPUT,
    @CODIGO_ERROR INT OUTPUT,
    @MENSAJE NVARCHAR(4000) OUTPUT
AS
BEGIN
    SET NOCOUNT ON;
    SET XACT_ABORT ON;

    SET @FILAS_INSERTADAS = 0;
    SET @CODIGO_ERROR = 0;
    SET @MENSAJE = N'Tipos de documento cargados.';

    BEGIN TRY
        BEGIN TRANSACTION;

        INSERT INTO DBO.TIPO_DOCUMENTO (
            ID_TIPO_DOCUMENTO,
            CODIGO_IDENTIFICADOR,
            DESCRIPCION
        )
        SELECT
            V.ID_TIPO_DOCUMENTO,
            V.CODIGO_IDENTIFICADOR,
            V.DESCRIPCION
        FROM (
            VALUES
            (1, 'FAC', N'Factura electrónica'),
            (2, 'TIQ', N'Tiquete electrónico')
        ) AS V (ID_TIPO_DOCUMENTO, CODIGO_IDENTIFICADOR, DESCRIPCION)
        WHERE NOT EXISTS (
            SELECT 1
            FROM DBO.TIPO_DOCUMENTO AS T
            WHERE T.ID_TIPO_DOCUMENTO = V.ID_TIPO_DOCUMENTO
        );

        SET @FILAS_INSERTADAS = @@ROWCOUNT;

        IF (SELECT COUNT(*) FROM DBO.TIPO_DOCUMENTO) < 2
            THROW 50701,
            N'El catálogo de tipos de documento quedó incompleto.',
            1;

        COMMIT TRANSACTION;
    END TRY
    BEGIN CATCH
        IF XACT_STATE() <> 0
            ROLLBACK TRANSACTION;

        SET @FILAS_INSERTADAS = 0;
        SET @CODIGO_ERROR = ERROR_NUMBER();
        SET @MENSAJE = ERROR_MESSAGE();
    END CATCH;
END;
GO

-- EJECUCIÓN DE LA CARGA
DECLARE @FILAS INT, @CODIGO INT, @MENSAJE NVARCHAR(4000);

EXEC DBO.USP_CARGAR_TIPO_DOCUMENTO
    @FILAS_INSERTADAS = @FILAS OUTPUT,
    @CODIGO_ERROR = @CODIGO OUTPUT,
    @MENSAJE = @MENSAJE OUTPUT;

PRINT CONCAT('TIPO_DOCUMENTO: ', @FILAS, ' fila(s) nueva(s). ', @MENSAJE);

IF @CODIGO <> 0
    THROW 50700, @MENSAJE, 1;
GO
