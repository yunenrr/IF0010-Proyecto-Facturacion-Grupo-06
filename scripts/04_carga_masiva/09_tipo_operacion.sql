USE SISTEMA_FACTURACION;
GO

CREATE OR ALTER PROCEDURE DBO.USP_CARGAR_TIPO_OPERACION
    @FILAS_INSERTADAS INT OUTPUT,
    @CODIGO_ERROR INT OUTPUT,
    @MENSAJE NVARCHAR(4000) OUTPUT
AS
BEGIN
    SET NOCOUNT ON;
    SET XACT_ABORT ON;

    SET @FILAS_INSERTADAS = 0;
    SET @CODIGO_ERROR = 0;
    SET @MENSAJE = N'Tipos de operación cargados.';

    BEGIN TRY
        BEGIN TRANSACTION;

        INSERT INTO DBO.TIPO_OPERACION (
            ID_TIPO_OPERACION,
            CODIGO_OPERACION
        )
        SELECT
            V.ID_TIPO_OPERACION,
            V.CODIGO_OPERACION
        FROM (
            VALUES
            (1, 'INSERT'),
            (2, 'UPDATE'),
            (3, 'DELETE')
        ) AS V(ID_TIPO_OPERACION, CODIGO_OPERACION)
        WHERE NOT EXISTS (
            SELECT 1
            FROM DBO.TIPO_OPERACION AS T
            WHERE T.ID_TIPO_OPERACION = V.ID_TIPO_OPERACION
        );

        SET @FILAS_INSERTADAS = @@ROWCOUNT;

        IF (SELECT COUNT(*) FROM DBO.TIPO_OPERACION) < 3
            THROW 50781,
            N'El catálogo de tipos de operación quedó incompleto.',
            1;

        COMMIT TRANSACTION;
    END TRY
    BEGIN CATCH
        IF XACT_STATE() <> 0
            ROLLBACK TRANSACTION;

        SET @FILAS_INSERTADAS = 0;
        SET @CODIGO_ERROR = ERROR_NUMBER();
        SET @MENSAJE = ERROR_MESSAGE();
    END CATCH;
END;
GO

DECLARE @FILAS INT, @CODIGO INT, @MENSAJE NVARCHAR(4000);

EXEC DBO.USP_CARGAR_TIPO_OPERACION
    @FILAS_INSERTADAS = @FILAS OUTPUT,
    @CODIGO_ERROR = @CODIGO OUTPUT,
    @MENSAJE = @MENSAJE OUTPUT;

PRINT CONCAT('TIPO_OPERACION: ', @FILAS, ' fila(s) nueva(s). ', @MENSAJE);

IF @CODIGO <> 0
    THROW 50780, @MENSAJE, 1;
GO
