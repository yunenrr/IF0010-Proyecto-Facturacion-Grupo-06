USE SISTEMA_FACTURACION;
GO

SET NOCOUNT ON;

DECLARE @CEDULA VARCHAR(12) = (
    SELECT TOP (1) CEDULA_CLIENTE
    FROM DBO.CLIENTE
    ORDER BY ID_CLIENTE
);

DECLARE @R TABLE (
    ORDEN INT,
    USUARIO VARCHAR(30),
    FILAS INT,
    CORREO VARCHAR(254),
    TELEFONO VARCHAR(12)
);

INSERT INTO @R
SELECT
    1 AS ORDEN,
    'DBO (sin rol)' AS USUARIO,
    COUNT(*) AS FILAS,
    MAX(CORREO) AS CORREO,
    MAX(TELEFONO) AS TELEFONO
FROM DBO.UFN_INFO_CLIENTE(@CEDULA);

EXECUTE AS USER = 'USR_ADMINISTRATIVO'; -- noqa: PRS
INSERT INTO @R
SELECT
    2 AS ORDEN,
    'USR_ADMINISTRATIVO' AS USUARIO,
    COUNT(*) AS FILAS,
    MAX(CORREO) AS CORREO,
    MAX(TELEFONO) AS TELEFONO
FROM DBO.UFN_INFO_CLIENTE(@CEDULA);
REVERT; -- noqa: PRS

EXECUTE AS USER = 'USR_DBA'; -- noqa: PRS
INSERT INTO @R
SELECT
    3 AS ORDEN,
    'USR_DBA' AS USUARIO,
    COUNT(*) AS FILAS,
    MAX(CORREO) AS CORREO,
    MAX(TELEFONO) AS TELEFONO
FROM DBO.UFN_INFO_CLIENTE(@CEDULA);
REVERT; -- noqa: PRS

EXECUTE AS USER = 'USR_CAJERO'; -- noqa: PRS
INSERT INTO @R
SELECT
    4 AS ORDEN,
    'USR_CAJERO' AS USUARIO,
    COUNT(*) AS FILAS,
    MAX(CORREO) AS CORREO,
    MAX(TELEFONO) AS TELEFONO
FROM DBO.UFN_INFO_CLIENTE(@CEDULA);
REVERT; -- noqa: PRS

EXECUTE AS USER = 'USR_CONSULTA'; -- noqa: PRS
INSERT INTO @R
SELECT
    5 AS ORDEN,
    'USR_CONSULTA' AS USUARIO,
    COUNT(*) AS FILAS,
    MAX(CORREO) AS CORREO,
    MAX(TELEFONO) AS TELEFONO
FROM DBO.UFN_INFO_CLIENTE(@CEDULA);
REVERT; -- noqa: PRS

EXECUTE AS USER = 'USR_AUDITOR'; -- noqa: PRS
INSERT INTO @R
SELECT
    6 AS ORDEN,
    'USR_AUDITOR' AS USUARIO,
    COUNT(*) AS FILAS,
    MAX(CORREO) AS CORREO,
    MAX(TELEFONO) AS TELEFONO
FROM DBO.UFN_INFO_CLIENTE(@CEDULA);
REVERT; -- noqa: PRS

SELECT
    R.USUARIO,
    R.FILAS,
    R.CORREO,
    R.TELEFONO,
    CASE
        WHEN R.ORDEN IN (2, 3) AND R.FILAS = 1 AND R.CORREO NOT LIKE '%***%'
            THEN 'PASA'
        WHEN R.ORDEN IN (4, 5) AND R.FILAS = 1 AND R.CORREO LIKE '%***@%'
            THEN 'PASA'
        WHEN R.ORDEN IN (1, 6) AND R.FILAS = 0 THEN 'PASA'
        ELSE 'FALLA'
    END AS RESULTADO
FROM @R AS R
ORDER BY R.ORDEN;
GO