USE SISTEMA_FACTURACION;
GO

SET NOCOUNT ON;

DECLARE @CEDULA VARCHAR(12) = (
    SELECT TOP (1) CEDULA_CLIENTE
    FROM DBO.CLIENTE
    ORDER BY ID_CLIENTE
);

DECLARE @R TABLE (
    ORDEN INT,
    USUARIO VARCHAR(30),
    FILAS INT,
    CORREO VARCHAR(254),
    TELEFONO VARCHAR(12)
);

INSERT INTO @R
SELECT
    1,
    'DBO (sin rol)',
    COUNT(*),
    MAX(CORREO),
    MAX(TELEFONO)
FROM DBO.UFN_INFO_CLIENTE(@CEDULA);

EXECUTE AS USER = 'USR_ADMINISTRATIVO';
INSERT INTO @R
SELECT 2, 'USR_ADMINISTRATIVO', COUNT(*), MAX(CORREO), MAX(TELEFONO)
FROM DBO.UFN_INFO_CLIENTE(@CEDULA);
REVERT;

EXECUTE AS USER = 'USR_DBA';
INSERT INTO @R
SELECT 3, 'USR_DBA', COUNT(*), MAX(CORREO), MAX(TELEFONO)
FROM DBO.UFN_INFO_CLIENTE(@CEDULA);
REVERT;

EXECUTE AS USER = 'USR_CAJERO';
INSERT INTO @R
SELECT 4, 'USR_CAJERO', COUNT(*), MAX(CORREO), MAX(TELEFONO)
FROM DBO.UFN_INFO_CLIENTE(@CEDULA);
REVERT;

EXECUTE AS USER = 'USR_CONSULTA';
INSERT INTO @R
SELECT 5, 'USR_CONSULTA', COUNT(*), MAX(CORREO), MAX(TELEFONO)
FROM DBO.UFN_INFO_CLIENTE(@CEDULA);
REVERT;

EXECUTE AS USER = 'USR_AUDITOR';
INSERT INTO @R
SELECT 6, 'USR_AUDITOR', COUNT(*), MAX(CORREO), MAX(TELEFONO)
FROM DBO.UFN_INFO_CLIENTE(@CEDULA);
REVERT;

SELECT
    R.USUARIO,
    R.FILAS,
    R.CORREO,
    R.TELEFONO,
    CASE
        WHEN R.ORDEN IN (2, 3) AND R.FILAS = 1 AND R.CORREO NOT LIKE '%***%'
            THEN 'PASA'
        WHEN R.ORDEN IN (4, 5) AND R.FILAS = 1 AND R.CORREO LIKE '%***@%'
            THEN 'PASA'
        WHEN R.ORDEN IN (1, 6) AND R.FILAS = 0 THEN 'PASA'
        ELSE 'FALLA'
    END AS RESULTADO
FROM @R AS R
ORDER BY R.ORDEN;
GO
