/* PRUEBAS DE ROLES Y PERMISOS.
   VERIFICA QUE LOS ROLES DE 05_SEGURIDAD/01_ROLES.SQL EXISTEN Y QUE LAS
   FUNCIONES SE COMPORTAN SEGÚN EL ROL DE QUIEN LAS EJECUTA. CADA PRUEBA
   SE CORRE COMO EL USUARIO DE PRUEBA DEL ROL (EXECUTE AS USER ... REVERT).
   INCLUYE LA DEMOSTRACIÓN DE LA RÚBRICA: LA FUNCIÓN DEL HISTORIAL DE
   CAMBIOS FUNCIONA EXCLUSIVAMENTE CON LOS ROLES AUDITOR Y DBA.
   RESULTADO: UNA TABLA CON CADA PRUEBA, LO ESPERADO, LO OBTENIDO Y SI
   PASA O FALLA.
   SQLFLUFF NO RECONOCE EXECUTE AS NI REVERT; ESAS LÍNEAS LLEVAN
   "-- noqa: PRS". */

USE SISTEMA_FACTURACION;
GO

SET NOCOUNT ON;

DECLARE @ROLES_CREADOS INT;
DECLARE @MEMBRESIAS INT;
DECLARE @TOTAL_HISTORIAL INT;
DECLARE @DESDE DATE;
DECLARE @HASTA DATE;
DECLARE @CONSECUTIVO CHAR(20);
DECLARE @ES_BORRADOR BIT;
DECLARE @PRUEBA INT;

-- FILAS DEL HISTORIAL QUE VE CADA IDENTIDAD
DECLARE @N_DBO INT;
DECLARE @N_AUDITOR INT;
DECLARE @N_AUDITOR_RANGO INT;
DECLARE @N_DBA INT;
DECLARE @N_ADMINISTRATIVO INT;
DECLARE @N_CAJERO INT;
DECLARE @N_CONSULTA INT;

-- UN CLIENTE DEL HISTORIAL, TAL COMO LO VE CADA ROL
DECLARE @CLIENTE_AUDITOR NVARCHAR(400);
DECLARE @CLIENTE_DBA NVARCHAR(400);

-- LECTURA DIRECTA DE LA TABLA POR PARTE DEL CAJERO
DECLARE @ACCESO_DIRECTO NVARCHAR(400);

-- ROLES QUE PUDIERON EJECUTAR FN_FACTURA_ES_BORRADOR (1 = SÍ)
DECLARE @BORRADOR_AUDITOR INT = 0;
DECLARE @BORRADOR_DBA INT = 0;
DECLARE @BORRADOR_ADMINISTRATIVO INT = 0;
DECLARE @BORRADOR_CAJERO INT = 0;
DECLARE @BORRADOR_CONSULTA INT = 0;

-- PREPARACIÓN (COMO DBO) ---------------------------------------------
SELECT @ROLES_CREADOS = COUNT(*)
FROM SYS.DATABASE_PRINCIPALS AS P
WHERE
    P.TYPE = 'R'
    AND P.NAME IN ('AUDITOR', 'DBA', 'ADMINISTRATIVO', 'CAJERO', 'CONSULTA');

SET
    @MEMBRESIAS = ISNULL(IS_ROLEMEMBER('AUDITOR', 'USR_AUDITOR'), 0)
    + ISNULL(IS_ROLEMEMBER('DBA', 'USR_DBA'), 0)
    + ISNULL(IS_ROLEMEMBER('ADMINISTRATIVO', 'USR_ADMINISTRATIVO'), 0)
    + ISNULL(IS_ROLEMEMBER('CAJERO', 'USR_CAJERO'), 0)
    + ISNULL(IS_ROLEMEMBER('CONSULTA', 'USR_CONSULTA'), 0);

-- CONTROL: FILAS QUE REALMENTE EXISTEN EN LAS TABLAS DE HISTORIAL
SET
    @TOTAL_HISTORIAL = (SELECT COUNT(*) FROM DBO.FACTURA_HISTORIAL)
    + (SELECT COUNT(*) FROM DBO.DETALLE_FACTURA_HISTORIAL)
    + (SELECT COUNT(*) FROM DBO.CLIENTE_HISTORIAL)
    + (SELECT COUNT(*) FROM DBO.PRODUCTO_HISTORIAL);

-- RANGO DE PRUEBA: EL PRIMER MES CON CAMBIOS EN FACTURAS
SET @DESDE = (
    SELECT CAST(MIN(FECHA_CAMBIO) AS DATE)
    FROM DBO.FACTURA_HISTORIAL
);
SET @HASTA = DATEADD(DAY, 30, @DESDE);

-- UN CONSECUTIVO CUALQUIERA PARA PROBAR EL PERMISO SOBRE LA FUNCIÓN
SET @CONSECUTIVO = (
    SELECT TOP (1) F.CONSECUTIVO
    FROM DBO.FACTURA AS F
    ORDER BY F.ID_FACTURA
);

-- DBO (QUIEN EJECUTA EL SCRIPT, NORMALMENTE SA; NO PERTENECE A ROLES)
SELECT @N_DBO = COUNT(*) FROM DBO.FN_HISTORIAL_CAMBIOS(DEFAULT, DEFAULT);

-- AUDITOR ------------------------------------------------------------
EXECUTE AS USER = 'USR_AUDITOR'; -- noqa: PRS
SELECT @N_AUDITOR = COUNT(*)
FROM DBO.FN_HISTORIAL_CAMBIOS(DEFAULT, DEFAULT);
SELECT @N_AUDITOR_RANGO = COUNT(*)
FROM DBO.FN_HISTORIAL_CAMBIOS(@DESDE, @HASTA);
SELECT TOP (1) @CLIENTE_AUDITOR = DETALLE
FROM DBO.FN_HISTORIAL_CAMBIOS(DEFAULT, DEFAULT)
WHERE TABLA = 'CLIENTE'
ORDER BY ID_REGISTRO;
BEGIN TRY
    SET @ES_BORRADOR = DBO.FN_FACTURA_ES_BORRADOR(@CONSECUTIVO);
    SET @BORRADOR_AUDITOR = 1;
END TRY
BEGIN CATCH
    SET @BORRADOR_AUDITOR = 0;
END CATCH;
REVERT; -- noqa: PRS

-- DBA ----------------------------------------------------------------
EXECUTE AS USER = 'USR_DBA'; -- noqa: PRS
SELECT @N_DBA = COUNT(*)
FROM DBO.FN_HISTORIAL_CAMBIOS(DEFAULT, DEFAULT);
SELECT TOP (1) @CLIENTE_DBA = DETALLE
FROM DBO.FN_HISTORIAL_CAMBIOS(DEFAULT, DEFAULT)
WHERE TABLA = 'CLIENTE'
ORDER BY ID_REGISTRO;
BEGIN TRY
    SET @ES_BORRADOR = DBO.FN_FACTURA_ES_BORRADOR(@CONSECUTIVO);
    SET @BORRADOR_DBA = 1;
END TRY
BEGIN CATCH
    SET @BORRADOR_DBA = 0;
END CATCH;
REVERT; -- noqa: PRS

-- ADMINISTRATIVO -----------------------------------------------------
EXECUTE AS USER = 'USR_ADMINISTRATIVO'; -- noqa: PRS
SELECT @N_ADMINISTRATIVO = COUNT(*)
FROM DBO.FN_HISTORIAL_CAMBIOS(DEFAULT, DEFAULT);
BEGIN TRY
    SET @ES_BORRADOR = DBO.FN_FACTURA_ES_BORRADOR(@CONSECUTIVO);
    SET @BORRADOR_ADMINISTRATIVO = 1;
END TRY
BEGIN CATCH
    SET @BORRADOR_ADMINISTRATIVO = 0;
END CATCH;
REVERT; -- noqa: PRS

-- CAJERO -------------------------------------------------------------
EXECUTE AS USER = 'USR_CAJERO'; -- noqa: PRS
SELECT @N_CAJERO = COUNT(*)
FROM DBO.FN_HISTORIAL_CAMBIOS(DEFAULT, DEFAULT);
BEGIN TRY
    SET @ES_BORRADOR = DBO.FN_FACTURA_ES_BORRADOR(@CONSECUTIVO);
    SET @BORRADOR_CAJERO = 1;
END TRY
BEGIN CATCH
    SET @BORRADOR_CAJERO = 0;
END CATCH;
-- INTENTO DE SALTARSE LA FUNCIÓN LEYENDO LA TABLA DIRECTAMENTE
BEGIN TRY
    SELECT @PRUEBA = COUNT(*) FROM DBO.FACTURA_HISTORIAL;
    SET @ACCESO_DIRECTO = N'PERMITIDO';
END TRY
BEGIN CATCH
    SET @ACCESO_DIRECTO = CONCAT(N'DENEGADO (error ', ERROR_NUMBER(), N')');
END CATCH;
REVERT; -- noqa: PRS

-- CONSULTA -----------------------------------------------------------
EXECUTE AS USER = 'USR_CONSULTA'; -- noqa: PRS
SELECT @N_CONSULTA = COUNT(*)
FROM DBO.FN_HISTORIAL_CAMBIOS(DEFAULT, DEFAULT);
BEGIN TRY
    SET @ES_BORRADOR = DBO.FN_FACTURA_ES_BORRADOR(@CONSECUTIVO);
    SET @BORRADOR_CONSULTA = 1;
END TRY
BEGIN CATCH
    SET @BORRADOR_CONSULTA = 0;
END CATCH;
REVERT; -- noqa: PRS

-- RESULTADOS ---------------------------------------------------------
SELECT
    V.NUMERO,
    V.PRUEBA,
    V.ESPERADO,
    ISNULL(V.OBTENIDO, N'(sin valor)') AS OBTENIDO,
    CASE WHEN V.CUMPLE = 1 THEN 'PASA' ELSE 'FALLA' END AS RESULTADO
FROM (
    VALUES
    (
        1, N'Existen los 5 roles', N'5',
        CONCAT(@ROLES_CREADOS, N''),
        IIF(@ROLES_CREADOS = 5, 1, 0)
    ),
    (
        2, N'Cada usuario de prueba está en su rol', N'5',
        CONCAT(@MEMBRESIAS, N''),
        IIF(@MEMBRESIAS = 5, 1, 0)
    ),
    (
        3, N'Control: el historial tiene filas', N'Más de 0',
        CONCAT(@TOTAL_HISTORIAL, N''),
        IIF(@TOTAL_HISTORIAL > 0, 1, 0)
    ),
    (
        4, N'Historial: dbo (sa, sin rol) no ve filas', N'0',
        CONCAT(@N_DBO, N''),
        IIF(@N_DBO = 0, 1, 0)
    ),
    (
        5, N'Historial: AUDITOR ve todas las filas',
        CONCAT(@TOTAL_HISTORIAL, N''),
        CONCAT(@N_AUDITOR, N''),
        IIF(@N_AUDITOR = @TOTAL_HISTORIAL, 1, 0)
    ),
    (
        6, N'Historial: DBA ve todas las filas',
        CONCAT(@TOTAL_HISTORIAL, N''),
        CONCAT(@N_DBA, N''),
        IIF(@N_DBA = @TOTAL_HISTORIAL, 1, 0)
    ),
    (
        7, N'Historial: ADMINISTRATIVO no ve filas', N'0',
        CONCAT(@N_ADMINISTRATIVO, N''),
        IIF(@N_ADMINISTRATIVO = 0, 1, 0)
    ),
    (
        8, N'Historial: CAJERO no ve filas', N'0',
        CONCAT(@N_CAJERO, N''),
        IIF(@N_CAJERO = 0, 1, 0)
    ),
    (
        9, N'Historial: CONSULTA no ve filas', N'0',
        CONCAT(@N_CONSULTA, N''),
        IIF(@N_CONSULTA = 0, 1, 0)
    ),
    (
        10, N'Historial: AUDITOR filtra por rango de fechas',
        CONCAT(N'Entre 1 y ', @TOTAL_HISTORIAL),
        CONCAT(@N_AUDITOR_RANGO, N' (', @DESDE, N' a ', @HASTA, N')'),
        IIF(@N_AUDITOR_RANGO BETWEEN 1 AND @TOTAL_HISTORIAL, 1, 0)
    ),
    (
        11, N'Historial: AUDITOR ve correo y teléfono enmascarados',
        N'Correo con ***@',
        @CLIENTE_AUDITOR,
        IIF(@CLIENTE_AUDITOR LIKE N'%***@%', 1, 0)
    ),
    (
        12, N'Historial: DBA ve correo y teléfono completos',
        N'Sin ***',
        @CLIENTE_DBA,
        IIF(@CLIENTE_DBA NOT LIKE N'%***%', 1, 0)
    ),
    (
        13, N'CAJERO no puede leer FACTURA_HISTORIAL directamente',
        N'DENEGADO',
        @ACCESO_DIRECTO,
        IIF(@ACCESO_DIRECTO LIKE N'DENEGADO%', 1, 0)
    ),
    (
        14, N'Los 5 roles pueden ejecutar FN_FACTURA_ES_BORRADOR',
        N'5 de 5',
        CONCAT(
            @BORRADOR_AUDITOR + @BORRADOR_DBA + @BORRADOR_ADMINISTRATIVO
            + @BORRADOR_CAJERO + @BORRADOR_CONSULTA,
            N' de 5'
        ),
        IIF(
            @BORRADOR_AUDITOR + @BORRADOR_DBA + @BORRADOR_ADMINISTRATIVO
            + @BORRADOR_CAJERO + @BORRADOR_CONSULTA = 5,
            1, 0
        )
    )
) AS V (NUMERO, PRUEBA, ESPERADO, OBTENIDO, CUMPLE)
ORDER BY V.NUMERO;
GO
