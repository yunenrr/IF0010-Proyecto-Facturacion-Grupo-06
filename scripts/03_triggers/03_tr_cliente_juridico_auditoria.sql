/* DBO.TR_CLIENTE_JURIDICO_AUDITORIA — REGISTRA EN CAMBIOS EN LA RAZÓN
   SOCIAL Y EL NOMBRE COMERCIAL DE LAS PERSONAS JURÍDICAS. */

USE SISTEMA_FACTURACION;
GO

SET QUOTED_IDENTIFIER ON;
SET ANSI_NULLS ON;
GO

CREATE OR ALTER TRIGGER DBO.TR_CLIENTE_JURIDICO_AUDITORIA
ON DBO.CLIENTE_JURIDICO
AFTER INSERT, UPDATE, DELETE
AS
BEGIN
    SET NOCOUNT ON;

    IF
        NOT EXISTS (SELECT 1 FROM INSERTED)
        AND NOT EXISTS (SELECT 1 FROM DELETED)
        RETURN;

    DECLARE @AHORA DATETIME2(3) = SYSDATETIME();
    DECLARE @USUARIO SYSNAME = USER_NAME();

    -- INSERT GUARDA EL NUEVO VALOR
    INSERT INTO DBO.CLIENTE_JURIDICO_HISTORIAL (
        ID_CLIENTE, ID_TIPO_OPERACION, USUARIO_RESPONSABLE, FECHA_CAMBIO,
        RAZON_SOCIAL, NOMBRE_COMERCIAL
    )
    SELECT
        I.ID_CLIENTE,
        T.ID_TIPO_OPERACION,
        @USUARIO AS USUARIO_RESPONSABLE,
        @AHORA AS FECHA_CAMBIO,
        I.RAZON_SOCIAL,
        I.NOMBRE_COMERCIAL
    FROM INSERTED AS I
    INNER JOIN DBO.TIPO_OPERACION AS T
        ON T.CODIGO_OPERACION = 'INSERT'
    WHERE NOT EXISTS (SELECT 1 FROM DELETED);

    -- UPDATE GUARDA EL VALOR ANTERIOR, SOLO SI CAMBIÓ UNA COLUMNA AUDITADA
    INSERT INTO DBO.CLIENTE_JURIDICO_HISTORIAL (
        ID_CLIENTE, ID_TIPO_OPERACION, USUARIO_RESPONSABLE, FECHA_CAMBIO,
        RAZON_SOCIAL, NOMBRE_COMERCIAL
    )
    SELECT
        D.ID_CLIENTE,
        T.ID_TIPO_OPERACION,
        @USUARIO AS USUARIO_RESPONSABLE,
        @AHORA AS FECHA_CAMBIO,
        D.RAZON_SOCIAL,
        D.NOMBRE_COMERCIAL
    FROM DELETED AS D
    INNER JOIN INSERTED AS I
        ON D.ID_CLIENTE = I.ID_CLIENTE
    INNER JOIN DBO.TIPO_OPERACION AS T
        ON T.CODIGO_OPERACION = 'UPDATE'
    WHERE EXISTS (
        SELECT
            D.RAZON_SOCIAL,
            D.NOMBRE_COMERCIAL
        EXCEPT
        SELECT
            I.RAZON_SOCIAL,
            I.NOMBRE_COMERCIAL
    );

    -- DELETE GUARADA LA ÚLTIMA VERSIÓN
    INSERT INTO DBO.CLIENTE_JURIDICO_HISTORIAL (
        ID_CLIENTE, ID_TIPO_OPERACION, USUARIO_RESPONSABLE, FECHA_CAMBIO,
        RAZON_SOCIAL, NOMBRE_COMERCIAL
    )
    SELECT
        D.ID_CLIENTE,
        T.ID_TIPO_OPERACION,
        @USUARIO AS USUARIO_RESPONSABLE,
        @AHORA AS FECHA_CAMBIO,
        D.RAZON_SOCIAL,
        D.NOMBRE_COMERCIAL
    FROM DELETED AS D
    INNER JOIN DBO.TIPO_OPERACION AS T
        ON T.CODIGO_OPERACION = 'DELETE'
    WHERE NOT EXISTS (SELECT 1 FROM INSERTED);
END;
GO
