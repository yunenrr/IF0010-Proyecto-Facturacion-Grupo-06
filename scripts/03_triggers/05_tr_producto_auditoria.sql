/* DBO.TR_PRODUCTO_AUDITORIA — REGISTRA EN DBO.PRODUCTO_HISTORIAL LAS ALTAS,
   CAMBIOS Y BAJAS DE DBO.PRODUCTO. AUDITA TODAS LAS COLUMNAS.
   EN UPDATE GUARDA LA VERSIÓN ANTERIOR AL CAMBIO (DELETED); EN INSERT LA
   NUEVA; EN DELETE LA ÚLTIMA. */

USE SISTEMA_FACTURACION;
GO

SET QUOTED_IDENTIFIER ON;
SET ANSI_NULLS ON;
GO

CREATE OR ALTER TRIGGER DBO.TR_PRODUCTO_AUDITORIA
ON DBO.PRODUCTO
AFTER INSERT, UPDATE, DELETE
AS
BEGIN
    SET NOCOUNT ON;

    IF
        NOT EXISTS (SELECT 1 FROM INSERTED)
        AND NOT EXISTS (SELECT 1 FROM DELETED)
        RETURN;

    DECLARE @AHORA DATETIME2(3) = SYSDATETIME();
    DECLARE @USUARIO SYSNAME = USER_NAME();

    -- INSERT: VERSIÓN NUEVA
    INSERT INTO DBO.PRODUCTO_HISTORIAL (
        ID_PRODUCTO, ID_TIPO_OPERACION, USUARIO_RESPONSABLE,
        FECHA_CAMBIO,
        CODIGO_INTERNO,
        ID_TIPO_PRODUCTO,
        ID_RUBRO,
        DESCRIPCION_PRODUCTO,
        PRECIO_UNITARIO,
        EXISTENCIA,
        TASA_IMPUESTO,
        ESTADO_PRODUCTO,
        FECHA_CREACION
    )
    SELECT
        I.ID_PRODUCTO,
        T.ID_TIPO_OPERACION,
        @USUARIO AS USUARIO_RESPONSABLE,
        @AHORA AS FECHA_CAMBIO,
        I.CODIGO_INTERNO,
        I.ID_TIPO_PRODUCTO,
        I.ID_RUBRO,
        I.DESCRIPCION_PRODUCTO,
        I.PRECIO_UNITARIO,
        I.EXISTENCIA,
        I.TASA_IMPUESTO,
        I.ESTADO_PRODUCTO,
        I.FECHA_CREACION
    FROM INSERTED AS I
    INNER JOIN DBO.TIPO_OPERACION AS T
        ON T.CODIGO_OPERACION = 'INSERT'
    WHERE NOT EXISTS (SELECT 1 FROM DELETED);

    -- UPDATE: VERSIÓN ANTERIOR, SOLO SI CAMBIÓ UNA COLUMNA AUDITADA
    INSERT INTO DBO.PRODUCTO_HISTORIAL (
        ID_PRODUCTO, ID_TIPO_OPERACION, USUARIO_RESPONSABLE,
        FECHA_CAMBIO,
        CODIGO_INTERNO,
        ID_TIPO_PRODUCTO,
        ID_RUBRO,
        DESCRIPCION_PRODUCTO,
        PRECIO_UNITARIO,
        EXISTENCIA,
        TASA_IMPUESTO,
        ESTADO_PRODUCTO,
        FECHA_CREACION
    )
    SELECT
        D.ID_PRODUCTO,
        T.ID_TIPO_OPERACION,
        @USUARIO AS USUARIO_RESPONSABLE,
        @AHORA AS FECHA_CAMBIO,
        D.CODIGO_INTERNO,
        D.ID_TIPO_PRODUCTO,
        D.ID_RUBRO,
        D.DESCRIPCION_PRODUCTO,
        D.PRECIO_UNITARIO,
        D.EXISTENCIA,
        D.TASA_IMPUESTO,
        D.ESTADO_PRODUCTO,
        D.FECHA_CREACION
    FROM DELETED AS D
    INNER JOIN INSERTED AS I
        ON D.ID_PRODUCTO = I.ID_PRODUCTO
    INNER JOIN DBO.TIPO_OPERACION AS T
        ON T.CODIGO_OPERACION = 'UPDATE'
    WHERE EXISTS (
        SELECT
            D.CODIGO_INTERNO,
            D.ID_TIPO_PRODUCTO,
            D.ID_RUBRO,
            D.DESCRIPCION_PRODUCTO,
            D.PRECIO_UNITARIO,
            D.EXISTENCIA,
            D.TASA_IMPUESTO,
            D.ESTADO_PRODUCTO,
            D.FECHA_CREACION
        EXCEPT
        SELECT
            I.CODIGO_INTERNO,
            I.ID_TIPO_PRODUCTO,
            I.ID_RUBRO,
            I.DESCRIPCION_PRODUCTO,
            I.PRECIO_UNITARIO,
            I.EXISTENCIA,
            I.TASA_IMPUESTO,
            I.ESTADO_PRODUCTO,
            I.FECHA_CREACION
    );

    -- DELETE: ÚLTIMA VERSIÓN
    INSERT INTO DBO.PRODUCTO_HISTORIAL (
        ID_PRODUCTO, ID_TIPO_OPERACION, USUARIO_RESPONSABLE,
        FECHA_CAMBIO,
        CODIGO_INTERNO,
        ID_TIPO_PRODUCTO,
        ID_RUBRO,
        DESCRIPCION_PRODUCTO,
        PRECIO_UNITARIO,
        EXISTENCIA,
        TASA_IMPUESTO,
        ESTADO_PRODUCTO,
        FECHA_CREACION
    )
    SELECT
        D.ID_PRODUCTO,
        T.ID_TIPO_OPERACION,
        @USUARIO AS USUARIO_RESPONSABLE,
        @AHORA AS FECHA_CAMBIO,
        D.CODIGO_INTERNO,
        D.ID_TIPO_PRODUCTO,
        D.ID_RUBRO,
        D.DESCRIPCION_PRODUCTO,
        D.PRECIO_UNITARIO,
        D.EXISTENCIA,
        D.TASA_IMPUESTO,
        D.ESTADO_PRODUCTO,
        D.FECHA_CREACION
    FROM DELETED AS D
    INNER JOIN DBO.TIPO_OPERACION AS T
        ON T.CODIGO_OPERACION = 'DELETE'
    WHERE NOT EXISTS (SELECT 1 FROM INSERTED);
END;
GO
