/* DBO.TR_CLIENTE_AUDITORIA — REGISTRA EN DBO.CLIENTE_HISTORIAL LAS ALTAS,
   CAMBIOS Y BAJAS DE DBO.CLIENTE. */

USE SISTEMA_FACTURACION;
GO

SET QUOTED_IDENTIFIER ON;
SET ANSI_NULLS ON;
GO

CREATE OR ALTER TRIGGER DBO.TR_CLIENTE_AUDITORIA
ON DBO.CLIENTE
AFTER INSERT, UPDATE, DELETE
AS
BEGIN
    SET NOCOUNT ON;

    IF
        NOT EXISTS (SELECT 1 FROM INSERTED)
        AND NOT EXISTS (SELECT 1 FROM DELETED)
        RETURN;

    DECLARE @AHORA DATETIME2(3) = SYSDATETIME();
    DECLARE @USUARIO SYSNAME = USER_NAME();

    -- INSERT: VERSIÓN NUEVA
    INSERT INTO DBO.CLIENTE_HISTORIAL (
        ID_CLIENTE, ID_TIPO_OPERACION, USUARIO_RESPONSABLE,
        FECHA_CAMBIO, CEDULA_CLIENTE, CORREO_CLIENTE,
        TELEFONO_CLIENTE, ID_DIRECCION
    )
    SELECT
        I.ID_CLIENTE,
        T.ID_TIPO_OPERACION,
        @USUARIO AS USUARIO_RESPONSABLE,
        @AHORA AS FECHA_CAMBIO,
        I.CEDULA_CLIENTE,
        I.CORREO_CLIENTE,
        I.TELEFONO_CLIENTE,
        I.ID_DIRECCION
    FROM INSERTED AS I
    INNER JOIN DBO.TIPO_OPERACION AS T
        ON T.CODIGO_OPERACION = 'INSERT'
    WHERE NOT EXISTS (SELECT 1 FROM DELETED);

    -- UPDATE: VERSIÓN ANTERIOR, SOLO SI CAMBIÓ UNA COLUMNA AUDITADA
    INSERT INTO DBO.CLIENTE_HISTORIAL (
        ID_CLIENTE, ID_TIPO_OPERACION, USUARIO_RESPONSABLE,
        FECHA_CAMBIO, CEDULA_CLIENTE, CORREO_CLIENTE,
        TELEFONO_CLIENTE, ID_DIRECCION
    )
    SELECT
        D.ID_CLIENTE,
        T.ID_TIPO_OPERACION,
        @USUARIO AS USUARIO_RESPONSABLE,
        @AHORA AS FECHA_CAMBIO,
        D.CEDULA_CLIENTE,
        D.CORREO_CLIENTE,
        D.TELEFONO_CLIENTE,
        D.ID_DIRECCION
    FROM DELETED AS D
    INNER JOIN INSERTED AS I
        ON D.ID_CLIENTE = I.ID_CLIENTE
    INNER JOIN DBO.TIPO_OPERACION AS T
        ON T.CODIGO_OPERACION = 'UPDATE'
    WHERE EXISTS (
        SELECT
            D.CEDULA_CLIENTE,
            D.CORREO_CLIENTE,
            D.TELEFONO_CLIENTE,
            D.ID_DIRECCION
        EXCEPT
        SELECT
            I.CEDULA_CLIENTE,
            I.CORREO_CLIENTE,
            I.TELEFONO_CLIENTE,
            I.ID_DIRECCION
    );

    -- DELETE: ÚLTIMA VERSIÓN
    INSERT INTO DBO.CLIENTE_HISTORIAL (
        ID_CLIENTE, ID_TIPO_OPERACION, USUARIO_RESPONSABLE,
        FECHA_CAMBIO, CEDULA_CLIENTE, CORREO_CLIENTE,
        TELEFONO_CLIENTE, ID_DIRECCION
    )
    SELECT
        D.ID_CLIENTE,
        T.ID_TIPO_OPERACION,
        @USUARIO AS USUARIO_RESPONSABLE,
        @AHORA AS FECHA_CAMBIO,
        D.CEDULA_CLIENTE,
        D.CORREO_CLIENTE,
        D.TELEFONO_CLIENTE,
        D.ID_DIRECCION
    FROM DELETED AS D
    INNER JOIN DBO.TIPO_OPERACION AS T
        ON T.CODIGO_OPERACION = 'DELETE'
    WHERE NOT EXISTS (SELECT 1 FROM INSERTED);
END;
GO
