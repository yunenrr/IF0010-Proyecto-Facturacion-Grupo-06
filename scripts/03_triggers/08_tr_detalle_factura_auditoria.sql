/* DBO.TR_DETALLE_FACTURA_AUDITORIA — REGISTRA EN
   DBO.DETALLE_FACTURA_HISTORIAL CAMBIOS DE DBO.DETALLE_FACTURA,
   CON TODAS SUS COLUMNAS. EN UPDATE SE REGISTRA LA
   VERSIÓN ANTERIOR SI CAMBIÓ CUALQUIER COLUMNA. */

USE SISTEMA_FACTURACION;
GO

SET QUOTED_IDENTIFIER ON;
SET ANSI_NULLS ON;
GO

CREATE OR ALTER TRIGGER DBO.TR_DETALLE_FACTURA_AUDITORIA
ON DBO.DETALLE_FACTURA
AFTER INSERT, UPDATE, DELETE
AS
BEGIN
    SET NOCOUNT ON;

    IF
        NOT EXISTS (SELECT 1 FROM INSERTED)
        AND NOT EXISTS (SELECT 1 FROM DELETED)
        RETURN;

    DECLARE @AHORA DATETIME2(3) = SYSDATETIME();
    DECLARE @USUARIO SYSNAME = USER_NAME();

    -- INSERT: VERSIÓN NUEVA
    INSERT INTO DBO.DETALLE_FACTURA_HISTORIAL (
        ID_DETALLE, ID_TIPO_OPERACION, USUARIO_RESPONSABLE,
        FECHA_CAMBIO, ID_FACTURA, ID_PRODUCTO, NUMERO_LINEA,
        CANTIDAD_FACTURADA, PRECIO_UNITARIO, MONTO_DESCUENTO, TASA_IMPUESTO,
        MONTO_IMPUESTO_LINEA, SUBTOTAL_LINEA, MONTO_TOTAL_LINEA
    )
    SELECT
        I.ID_DETALLE,
        T.ID_TIPO_OPERACION,
        @USUARIO AS USUARIO_RESPONSABLE,
        @AHORA AS FECHA_CAMBIO,
        I.ID_FACTURA,
        I.ID_PRODUCTO,
        I.NUMERO_LINEA,
        I.CANTIDAD_FACTURADA,
        I.PRECIO_UNITARIO,
        I.MONTO_DESCUENTO,
        I.TASA_IMPUESTO,
        I.MONTO_IMPUESTO_LINEA,
        I.SUBTOTAL_LINEA,
        I.MONTO_TOTAL_LINEA
    FROM INSERTED AS I
    INNER JOIN DBO.TIPO_OPERACION AS T
        ON T.CODIGO_OPERACION = 'INSERT'
    WHERE NOT EXISTS (SELECT 1 FROM DELETED);

    -- UPDATE: VERSIÓN ANTERIOR, SOLO SI CAMBIÓ ALGUNA COLUMNA
    INSERT INTO DBO.DETALLE_FACTURA_HISTORIAL (
        ID_DETALLE, ID_TIPO_OPERACION, USUARIO_RESPONSABLE,
        FECHA_CAMBIO, ID_FACTURA, ID_PRODUCTO, NUMERO_LINEA,
        CANTIDAD_FACTURADA, PRECIO_UNITARIO, MONTO_DESCUENTO, TASA_IMPUESTO,
        MONTO_IMPUESTO_LINEA, SUBTOTAL_LINEA, MONTO_TOTAL_LINEA
    )
    SELECT
        D.ID_DETALLE,
        T.ID_TIPO_OPERACION,
        @USUARIO AS USUARIO_RESPONSABLE,
        @AHORA AS FECHA_CAMBIO,
        D.ID_FACTURA,
        D.ID_PRODUCTO,
        D.NUMERO_LINEA,
        D.CANTIDAD_FACTURADA,
        D.PRECIO_UNITARIO,
        D.MONTO_DESCUENTO,
        D.TASA_IMPUESTO,
        D.MONTO_IMPUESTO_LINEA,
        D.SUBTOTAL_LINEA,
        D.MONTO_TOTAL_LINEA
    FROM DELETED AS D
    INNER JOIN INSERTED AS I
        ON D.ID_DETALLE = I.ID_DETALLE
    INNER JOIN DBO.TIPO_OPERACION AS T
        ON T.CODIGO_OPERACION = 'UPDATE'
    WHERE EXISTS (
        SELECT
            D.ID_FACTURA,
            D.ID_PRODUCTO,
            D.NUMERO_LINEA,
            D.CANTIDAD_FACTURADA,
            D.PRECIO_UNITARIO,
            D.MONTO_DESCUENTO,
            D.TASA_IMPUESTO,
            D.MONTO_IMPUESTO_LINEA,
            D.SUBTOTAL_LINEA,
            D.MONTO_TOTAL_LINEA
        EXCEPT
        SELECT
            I.ID_FACTURA,
            I.ID_PRODUCTO,
            I.NUMERO_LINEA,
            I.CANTIDAD_FACTURADA,
            I.PRECIO_UNITARIO,
            I.MONTO_DESCUENTO,
            I.TASA_IMPUESTO,
            I.MONTO_IMPUESTO_LINEA,
            I.SUBTOTAL_LINEA,
            I.MONTO_TOTAL_LINEA
    );

    -- DELETE: ÚLTIMA VERSIÓN
    INSERT INTO DBO.DETALLE_FACTURA_HISTORIAL (
        ID_DETALLE, ID_TIPO_OPERACION, USUARIO_RESPONSABLE,
        FECHA_CAMBIO, ID_FACTURA, ID_PRODUCTO, NUMERO_LINEA,
        CANTIDAD_FACTURADA, PRECIO_UNITARIO, MONTO_DESCUENTO, TASA_IMPUESTO,
        MONTO_IMPUESTO_LINEA, SUBTOTAL_LINEA, MONTO_TOTAL_LINEA
    )
    SELECT
        D.ID_DETALLE,
        T.ID_TIPO_OPERACION,
        @USUARIO AS USUARIO_RESPONSABLE,
        @AHORA AS FECHA_CAMBIO,
        D.ID_FACTURA,
        D.ID_PRODUCTO,
        D.NUMERO_LINEA,
        D.CANTIDAD_FACTURADA,
        D.PRECIO_UNITARIO,
        D.MONTO_DESCUENTO,
        D.TASA_IMPUESTO,
        D.MONTO_IMPUESTO_LINEA,
        D.SUBTOTAL_LINEA,
        D.MONTO_TOTAL_LINEA
    FROM DELETED AS D
    INNER JOIN DBO.TIPO_OPERACION AS T
        ON T.CODIGO_OPERACION = 'DELETE'
    WHERE NOT EXISTS (SELECT 1 FROM INSERTED);
END;
GO
