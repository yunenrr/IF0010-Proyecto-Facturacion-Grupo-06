/* DBO.TR_CLIENTE_FISICO_AUDITORIA — REGISTRA CAMBIOS EN NOMBRE
   Y LOS APELLIDOS DE LAS PERSONAS FÍSICAS. */

USE SISTEMA_FACTURACION;
GO

SET QUOTED_IDENTIFIER ON;
SET ANSI_NULLS ON;
GO

CREATE OR ALTER TRIGGER DBO.TR_CLIENTE_FISICO_AUDITORIA
ON DBO.CLIENTE_FISICO
AFTER INSERT, UPDATE, DELETE
AS
BEGIN
    SET NOCOUNT ON;

    IF
        NOT EXISTS (SELECT 1 FROM INSERTED)
        AND NOT EXISTS (SELECT 1 FROM DELETED)
        RETURN;

    DECLARE @AHORA DATETIME2(3) = SYSDATETIME();
    DECLARE @USUARIO SYSNAME = USER_NAME();

    -- INSERT GUARDA EL NUEVO VALOR
    INSERT INTO DBO.CLIENTE_FISICO_HISTORIAL (
        ID_CLIENTE, ID_TIPO_OPERACION, USUARIO_RESPONSABLE, FECHA_CAMBIO,
        NOMBRE, PRIMER_APELLIDO, SEGUNDO_APELLIDO
    )
    SELECT
        I.ID_CLIENTE,
        T.ID_TIPO_OPERACION,
        @USUARIO AS USUARIO_RESPONSABLE,
        @AHORA AS FECHA_CAMBIO,
        I.NOMBRE,
        I.PRIMER_APELLIDO,
        I.SEGUNDO_APELLIDO
    FROM INSERTED AS I
    INNER JOIN DBO.TIPO_OPERACION AS T
        ON T.CODIGO_OPERACION = 'INSERT'
    WHERE NOT EXISTS (SELECT 1 FROM DELETED);

    -- UPDATE GUARDA EL VALOR ANTERIOR, SOLO SI CAMBIÓ UNA COLUMNA AUDITADA
    INSERT INTO DBO.CLIENTE_FISICO_HISTORIAL (
        ID_CLIENTE, ID_TIPO_OPERACION, USUARIO_RESPONSABLE, FECHA_CAMBIO,
        NOMBRE, PRIMER_APELLIDO, SEGUNDO_APELLIDO
    )
    SELECT
        D.ID_CLIENTE,
        T.ID_TIPO_OPERACION,
        @USUARIO AS USUARIO_RESPONSABLE,
        @AHORA AS FECHA_CAMBIO,
        D.NOMBRE,
        D.PRIMER_APELLIDO,
        D.SEGUNDO_APELLIDO
    FROM DELETED AS D
    INNER JOIN INSERTED AS I
        ON D.ID_CLIENTE = I.ID_CLIENTE
    INNER JOIN DBO.TIPO_OPERACION AS T
        ON T.CODIGO_OPERACION = 'UPDATE'
    WHERE EXISTS (
        SELECT
            D.NOMBRE,
            D.PRIMER_APELLIDO,
            D.SEGUNDO_APELLIDO
        EXCEPT
        SELECT
            I.NOMBRE,
            I.PRIMER_APELLIDO,
            I.SEGUNDO_APELLIDO
    );

    -- DELETE GUARADA LA ÚLTIMA VERSIÓN
    INSERT INTO DBO.CLIENTE_FISICO_HISTORIAL (
        ID_CLIENTE, ID_TIPO_OPERACION, USUARIO_RESPONSABLE, FECHA_CAMBIO,
        NOMBRE, PRIMER_APELLIDO, SEGUNDO_APELLIDO
    )
    SELECT
        D.ID_CLIENTE,
        T.ID_TIPO_OPERACION,
        @USUARIO AS USUARIO_RESPONSABLE,
        @AHORA AS FECHA_CAMBIO,
        D.NOMBRE,
        D.PRIMER_APELLIDO,
        D.SEGUNDO_APELLIDO
    FROM DELETED AS D
    INNER JOIN DBO.TIPO_OPERACION AS T
        ON T.CODIGO_OPERACION = 'DELETE'
    WHERE NOT EXISTS (SELECT 1 FROM INSERTED);
END;
GO
