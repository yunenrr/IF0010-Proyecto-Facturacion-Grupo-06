/* DBO.TR_FACTURA_AUDITORIA — REGISTRA EN DBO.FACTURA_HISTORIAL LAS ALTAS,
   CAMBIOS Y BAJAS DE DBO.FACTURA. */

USE SISTEMA_FACTURACION;
GO

SET QUOTED_IDENTIFIER ON;
SET ANSI_NULLS ON;
GO

CREATE OR ALTER TRIGGER DBO.TR_FACTURA_AUDITORIA
ON DBO.FACTURA
AFTER INSERT, UPDATE, DELETE
AS
BEGIN
    SET NOCOUNT ON;

    IF
        NOT EXISTS (SELECT 1 FROM INSERTED)
        AND NOT EXISTS (SELECT 1 FROM DELETED)
        RETURN;

    DECLARE @AHORA DATETIME2(3) = SYSDATETIME();
    DECLARE @USUARIO SYSNAME = USER_NAME();

    -- INSERT: VERSIÓN NUEVA
    INSERT INTO DBO.FACTURA_HISTORIAL (
        ID_FACTURA, ID_TIPO_OPERACION, USUARIO_RESPONSABLE,
        FECHA_CAMBIO, CONSECUTIVO, ID_ESTADO_FACTURA, MONTO_FINAL
    )
    SELECT
        I.ID_FACTURA,
        T.ID_TIPO_OPERACION,
        @USUARIO AS USUARIO_RESPONSABLE,
        @AHORA AS FECHA_CAMBIO,
        I.CONSECUTIVO,
        I.ID_ESTADO_FACTURA,
        I.MONTO_FINAL
    FROM INSERTED AS I
    INNER JOIN DBO.TIPO_OPERACION AS T
        ON T.CODIGO_OPERACION = 'INSERT'
    WHERE NOT EXISTS (SELECT 1 FROM DELETED);

    -- UPDATE: VERSIÓN ANTERIOR, SOLO SI CAMBIÓ UNA COLUMNA AUDITADA
    INSERT INTO DBO.FACTURA_HISTORIAL (
        ID_FACTURA, ID_TIPO_OPERACION, USUARIO_RESPONSABLE,
        FECHA_CAMBIO, CONSECUTIVO, ID_ESTADO_FACTURA, MONTO_FINAL
    )
    SELECT
        D.ID_FACTURA,
        T.ID_TIPO_OPERACION,
        @USUARIO AS USUARIO_RESPONSABLE,
        @AHORA AS FECHA_CAMBIO,
        D.CONSECUTIVO,
        D.ID_ESTADO_FACTURA,
        D.MONTO_FINAL
    FROM DELETED AS D
    INNER JOIN INSERTED AS I
        ON D.ID_FACTURA = I.ID_FACTURA
    INNER JOIN DBO.TIPO_OPERACION AS T
        ON T.CODIGO_OPERACION = 'UPDATE'
    WHERE EXISTS (
        SELECT
            D.CONSECUTIVO,
            D.ID_ESTADO_FACTURA,
            D.MONTO_FINAL
        EXCEPT
        SELECT
            I.CONSECUTIVO,
            I.ID_ESTADO_FACTURA,
            I.MONTO_FINAL
    );

    -- DELETE: ÚLTIMA VERSIÓN
    INSERT INTO DBO.FACTURA_HISTORIAL (
        ID_FACTURA, ID_TIPO_OPERACION, USUARIO_RESPONSABLE,
        FECHA_CAMBIO, CONSECUTIVO, ID_ESTADO_FACTURA, MONTO_FINAL
    )
    SELECT
        D.ID_FACTURA,
        T.ID_TIPO_OPERACION,
        @USUARIO AS USUARIO_RESPONSABLE,
        @AHORA AS FECHA_CAMBIO,
        D.CONSECUTIVO,
        D.ID_ESTADO_FACTURA,
        D.MONTO_FINAL
    FROM DELETED AS D
    INNER JOIN DBO.TIPO_OPERACION AS T
        ON T.CODIGO_OPERACION = 'DELETE'
    WHERE NOT EXISTS (SELECT 1 FROM INSERTED);
END;
GO
