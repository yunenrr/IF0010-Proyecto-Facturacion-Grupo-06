/* DBO.TR_FACTURA_AUDITORIA — REGISTRA EN DBO.FACTURA_HISTORIAL LAS ALTAS,
   CAMBIOS Y BAJAS DE DBO.FACTURA, CON LA FILA COMPLETA EN CADA REGISTRO. */

USE SISTEMA_FACTURACION;
GO

SET QUOTED_IDENTIFIER ON;
SET ANSI_NULLS ON;
GO

CREATE OR ALTER TRIGGER DBO.TR_FACTURA_AUDITORIA
ON DBO.FACTURA
AFTER INSERT, UPDATE, DELETE
AS
BEGIN
    SET NOCOUNT ON;

    IF
        NOT EXISTS (SELECT 1 FROM INSERTED)
        AND NOT EXISTS (SELECT 1 FROM DELETED)
        RETURN;

    DECLARE @AHORA DATETIME2(3) = SYSDATETIME();
    DECLARE @USUARIO SYSNAME = USER_NAME();

    -- INSERT: VERSIÓN NUEVA
    INSERT INTO DBO.FACTURA_HISTORIAL (
        ID_FACTURA, ID_TIPO_OPERACION, USUARIO_RESPONSABLE, FECHA_CAMBIO,
        ID_TIPO_DOCUMENTO, ID_EMPRESA_EMISORA, ID_CLIENTE_COMPRADOR,
        ID_ESTADO_FACTURA, ID_MONEDA, CONSECUTIVO, FECHA_CREACION,
        FECHA_MODIFICACION, FECHA_EMISION, SUBTOTAL_FACTURA,
        TOTAL_DESCUENTOS, TOTAL_IMPUESTOS, MONTO_FINAL
    )
    SELECT
        I.ID_FACTURA,
        T.ID_TIPO_OPERACION,
        @USUARIO AS USUARIO_RESPONSABLE,
        @AHORA AS FECHA_CAMBIO,
        I.ID_TIPO_DOCUMENTO,
        I.ID_EMPRESA_EMISORA,
        I.ID_CLIENTE_COMPRADOR,
        I.ID_ESTADO_FACTURA,
        I.ID_MONEDA,
        I.CONSECUTIVO,
        I.FECHA_CREACION,
        I.FECHA_MODIFICACION,
        I.FECHA_EMISION,
        I.SUBTOTAL_FACTURA,
        I.TOTAL_DESCUENTOS,
        I.TOTAL_IMPUESTOS,
        I.MONTO_FINAL
    FROM INSERTED AS I
    INNER JOIN DBO.TIPO_OPERACION AS T
        ON T.CODIGO_OPERACION = 'INSERT'
    WHERE NOT EXISTS (SELECT 1 FROM DELETED);

    -- UPDATE: VERSIÓN ANTERIOR, SOLO SI CAMBIÓ ALGUNA COLUMNA
    INSERT INTO DBO.FACTURA_HISTORIAL (
        ID_FACTURA, ID_TIPO_OPERACION, USUARIO_RESPONSABLE, FECHA_CAMBIO,
        ID_TIPO_DOCUMENTO, ID_EMPRESA_EMISORA, ID_CLIENTE_COMPRADOR,
        ID_ESTADO_FACTURA, ID_MONEDA, CONSECUTIVO, FECHA_CREACION,
        FECHA_MODIFICACION, FECHA_EMISION, SUBTOTAL_FACTURA,
        TOTAL_DESCUENTOS, TOTAL_IMPUESTOS, MONTO_FINAL
    )
    SELECT
        D.ID_FACTURA,
        T.ID_TIPO_OPERACION,
        @USUARIO AS USUARIO_RESPONSABLE,
        @AHORA AS FECHA_CAMBIO,
        D.ID_TIPO_DOCUMENTO,
        D.ID_EMPRESA_EMISORA,
        D.ID_CLIENTE_COMPRADOR,
        D.ID_ESTADO_FACTURA,
        D.ID_MONEDA,
        D.CONSECUTIVO,
        D.FECHA_CREACION,
        D.FECHA_MODIFICACION,
        D.FECHA_EMISION,
        D.SUBTOTAL_FACTURA,
        D.TOTAL_DESCUENTOS,
        D.TOTAL_IMPUESTOS,
        D.MONTO_FINAL
    FROM DELETED AS D
    INNER JOIN INSERTED AS I
        ON D.ID_FACTURA = I.ID_FACTURA
    INNER JOIN DBO.TIPO_OPERACION AS T
        ON T.CODIGO_OPERACION = 'UPDATE'
    WHERE EXISTS (
        SELECT
            D.ID_TIPO_DOCUMENTO,
            D.ID_EMPRESA_EMISORA,
            D.ID_CLIENTE_COMPRADOR,
            D.ID_ESTADO_FACTURA,
            D.ID_MONEDA,
            D.CONSECUTIVO,
            D.FECHA_CREACION,
            D.FECHA_MODIFICACION,
            D.FECHA_EMISION,
            D.SUBTOTAL_FACTURA,
            D.TOTAL_DESCUENTOS,
            D.TOTAL_IMPUESTOS,
            D.MONTO_FINAL
        EXCEPT
        SELECT
            I.ID_TIPO_DOCUMENTO,
            I.ID_EMPRESA_EMISORA,
            I.ID_CLIENTE_COMPRADOR,
            I.ID_ESTADO_FACTURA,
            I.ID_MONEDA,
            I.CONSECUTIVO,
            I.FECHA_CREACION,
            I.FECHA_MODIFICACION,
            I.FECHA_EMISION,
            I.SUBTOTAL_FACTURA,
            I.TOTAL_DESCUENTOS,
            I.TOTAL_IMPUESTOS,
            I.MONTO_FINAL
    );

    -- DELETE: ÚLTIMA VERSIÓN
    INSERT INTO DBO.FACTURA_HISTORIAL (
        ID_FACTURA, ID_TIPO_OPERACION, USUARIO_RESPONSABLE, FECHA_CAMBIO,
        ID_TIPO_DOCUMENTO, ID_EMPRESA_EMISORA, ID_CLIENTE_COMPRADOR,
        ID_ESTADO_FACTURA, ID_MONEDA, CONSECUTIVO, FECHA_CREACION,
        FECHA_MODIFICACION, FECHA_EMISION, SUBTOTAL_FACTURA,
        TOTAL_DESCUENTOS, TOTAL_IMPUESTOS, MONTO_FINAL
    )
    SELECT
        D.ID_FACTURA,
        T.ID_TIPO_OPERACION,
        @USUARIO AS USUARIO_RESPONSABLE,
        @AHORA AS FECHA_CAMBIO,
        D.ID_TIPO_DOCUMENTO,
        D.ID_EMPRESA_EMISORA,
        D.ID_CLIENTE_COMPRADOR,
        D.ID_ESTADO_FACTURA,
        D.ID_MONEDA,
        D.CONSECUTIVO,
        D.FECHA_CREACION,
        D.FECHA_MODIFICACION,
        D.FECHA_EMISION,
        D.SUBTOTAL_FACTURA,
        D.TOTAL_DESCUENTOS,
        D.TOTAL_IMPUESTOS,
        D.MONTO_FINAL
    FROM DELETED AS D
    INNER JOIN DBO.TIPO_OPERACION AS T
        ON T.CODIGO_OPERACION = 'DELETE'
    WHERE NOT EXISTS (SELECT 1 FROM INSERTED);
END;
GO
