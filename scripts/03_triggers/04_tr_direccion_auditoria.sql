/* DBO.TR_DIRECCION_AUDITORIA — REGISTRA EN DBO.DIRECCION_HISTORIAL LAS ALTAS,
   CAMBIOS Y BAJAS DE DBO.DIRECCION. UBICACIÓN DE CLIENTES Y EMPRESAS.
   EN UPDATE GUARDA LA VERSIÓN ANTERIOR AL CAMBIO (DELETED); EN INSERT LA
   NUEVA; EN DELETE LA ÚLTIMA. */

USE SISTEMA_FACTURACION;
GO

SET QUOTED_IDENTIFIER ON;
SET ANSI_NULLS ON;
GO

CREATE OR ALTER TRIGGER DBO.TR_DIRECCION_AUDITORIA
ON DBO.DIRECCION
AFTER INSERT, UPDATE, DELETE
AS
BEGIN
    SET NOCOUNT ON;

    IF
        NOT EXISTS (SELECT 1 FROM INSERTED)
        AND NOT EXISTS (SELECT 1 FROM DELETED)
        RETURN;

    DECLARE @AHORA DATETIME2(3) = SYSDATETIME();
    DECLARE @USUARIO SYSNAME = USER_NAME();

    -- INSERT: VERSIÓN NUEVA
    INSERT INTO DBO.DIRECCION_HISTORIAL (
        ID_DIRECCION, ID_TIPO_OPERACION, USUARIO_RESPONSABLE,
        FECHA_CAMBIO,
        ID_DISTRITO,
        OTRAS_SENAS
    )
    SELECT
        I.ID_DIRECCION,
        T.ID_TIPO_OPERACION,
        @USUARIO AS USUARIO_RESPONSABLE,
        @AHORA AS FECHA_CAMBIO,
        I.ID_DISTRITO,
        I.OTRAS_SENAS
    FROM INSERTED AS I
    INNER JOIN DBO.TIPO_OPERACION AS T
        ON T.CODIGO_OPERACION = 'INSERT'
    WHERE NOT EXISTS (SELECT 1 FROM DELETED);

    -- UPDATE: VERSIÓN ANTERIOR, SOLO SI CAMBIÓ UNA COLUMNA AUDITADA
    INSERT INTO DBO.DIRECCION_HISTORIAL (
        ID_DIRECCION, ID_TIPO_OPERACION, USUARIO_RESPONSABLE,
        FECHA_CAMBIO,
        ID_DISTRITO,
        OTRAS_SENAS
    )
    SELECT
        D.ID_DIRECCION,
        T.ID_TIPO_OPERACION,
        @USUARIO AS USUARIO_RESPONSABLE,
        @AHORA AS FECHA_CAMBIO,
        D.ID_DISTRITO,
        D.OTRAS_SENAS
    FROM DELETED AS D
    INNER JOIN INSERTED AS I
        ON D.ID_DIRECCION = I.ID_DIRECCION
    INNER JOIN DBO.TIPO_OPERACION AS T
        ON T.CODIGO_OPERACION = 'UPDATE'
    WHERE EXISTS (
        SELECT
            D.ID_DISTRITO,
            D.OTRAS_SENAS
        EXCEPT
        SELECT
            I.ID_DISTRITO,
            I.OTRAS_SENAS
    );

    -- DELETE: ÚLTIMA VERSIÓN
    INSERT INTO DBO.DIRECCION_HISTORIAL (
        ID_DIRECCION, ID_TIPO_OPERACION, USUARIO_RESPONSABLE,
        FECHA_CAMBIO,
        ID_DISTRITO,
        OTRAS_SENAS
    )
    SELECT
        D.ID_DIRECCION,
        T.ID_TIPO_OPERACION,
        @USUARIO AS USUARIO_RESPONSABLE,
        @AHORA AS FECHA_CAMBIO,
        D.ID_DISTRITO,
        D.OTRAS_SENAS
    FROM DELETED AS D
    INNER JOIN DBO.TIPO_OPERACION AS T
        ON T.CODIGO_OPERACION = 'DELETE'
    WHERE NOT EXISTS (SELECT 1 FROM INSERTED);
END;
GO
