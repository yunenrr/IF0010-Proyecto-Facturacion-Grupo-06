CREATE OR ALTER VIEW DBO.VW_CLIENTES
AS
SELECT
    C.CEDULA_CLIENTE AS CEDULA,
    C.NOMBRE_CLIENTE AS NOMBREORAZONSOCIAL,
    ISNULL(RESUMEN_FACTURAS.CANTIDAD, 0) AS CANTIDADFACTURAS,
    CASE
        WHEN ISNULL(RESUMEN_FACTURAS.RECIENTES, 0) > 5 THEN N'Sí'
        ELSE N'No'
    END AS CLIENTEFRECUENTE
FROM DBO.CLIENTE AS C
LEFT JOIN (
    SELECT
        F.ID_CLIENTE_COMPRADOR,
        COUNT(*) AS CANTIDAD,
        SUM(
            CASE
                WHEN
                    E.ESTADO IN ('EMITIDA', 'PAGADA')
                    AND F.FECHA_EMISION >= DATEADD(MONTH, -6, SYSDATETIME())
                    THEN 1
                ELSE 0
            END
        ) AS RECIENTES
    FROM DBO.FACTURA AS F
    INNER JOIN DBO.ESTADO_FACTURA AS E
        ON F.ID_ESTADO_FACTURA = E.ID_ESTADO_FACTURA
    WHERE E.ESTADO <> 'BORRADOR'
    GROUP BY F.ID_CLIENTE_COMPRADOR
) AS RESUMEN_FACTURAS
    ON C.ID_CLIENTE = RESUMEN_FACTURAS.ID_CLIENTE_COMPRADOR;
GO
