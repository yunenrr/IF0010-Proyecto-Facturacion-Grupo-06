/*Vista para totales diarios facturados por empresa y tipo de documento
  Se agrupa por los ID porque hay empresas con nombres iguales o parecidos
  de esta manera no se mezclan.
  */
CREATE OR ALTER VIEW DBO.VW_TOTALES_DIARIOS_FACTURADOS
AS
SELECT
    CAST(F.FECHA_EMISION AS DATE) AS FECHAEMISION,
    E.NOMBRE_COMERCIAL AS NOMBREEMPRESA,
    TD.DESCRIPCION AS TIPODOCUMENTO,
    COUNT(*) AS CANTIDADFACTURAS,
    SUM(F.SUBTOTAL_FACTURA) AS SUBTOTALACUMULADO,
    SUM(F.TOTAL_DESCUENTOS) AS TOTALDESCUENTOS,
    SUM(F.TOTAL_IMPUESTOS) AS TOTALIMPUESTOS,
    SUM(F.MONTO_FINAL) AS MONTOTOTALFACTURADO
FROM DBO.FACTURA AS F
INNER JOIN DBO.EMPRESA AS E
    ON F.ID_EMPRESA_EMISORA = E.ID_EMPRESA
INNER JOIN DBO.TIPO_DOCUMENTO AS TD
    ON F.ID_TIPO_DOCUMENTO = TD.ID_TIPO_DOCUMENTO
INNER JOIN DBO.ESTADO_FACTURA AS ES
    ON F.ID_ESTADO_FACTURA = ES.ID_ESTADO_FACTURA
WHERE ES.ESTADO IN ('EMITIDA', 'PAGADA')
GROUP BY
    CAST(F.FECHA_EMISION AS DATE),
    E.ID_EMPRESA,
    E.NOMBRE_COMERCIAL,
    TD.ID_TIPO_DOCUMENTO,
    TD.DESCRIPCION;
GO
