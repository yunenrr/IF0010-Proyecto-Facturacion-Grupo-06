/* DBO.UFN_VENTAS_PRODUCTO_RANGO — LÍNEAS FACTURADAS DE UN PRODUCTO ENTRE DOS
   FECHAS (AMBAS INCLUSIVE). SOLO CUENTA FACTURAS EMITIDAS Y PAGADAS: UN
   BORRADOR NO TIENE VALIDEZ Y UNA CANCELADA NO TIENE EFECTO FISCAL. EL RANGO
   ES SARGABLE (>= DESDE Y < HASTA + 1 DÍA). SIN ORDER BY: EL ORDEN LO PONE
   QUIEN CONSULTA. */

USE SISTEMA_FACTURACION;
GO

SET QUOTED_IDENTIFIER ON;
SET ANSI_NULLS ON;
GO

CREATE OR ALTER FUNCTION DBO.UFN_VENTAS_PRODUCTO_RANGO(
    @CODIGO_INTERNO VARCHAR(20),
    @DESDE DATE,
    @HASTA DATE
)
RETURNS TABLE
AS
RETURN (
    SELECT
        F.ID_FACTURA,
        D.CANTIDAD_FACTURADA,
        F.FECHA_EMISION
    FROM DBO.PRODUCTO AS P
    INNER JOIN DBO.DETALLE_FACTURA AS D
        ON P.ID_PRODUCTO = D.ID_PRODUCTO
    INNER JOIN DBO.FACTURA AS F
        ON D.ID_FACTURA = F.ID_FACTURA
    INNER JOIN DBO.ESTADO_FACTURA AS E
        ON F.ID_ESTADO_FACTURA = E.ID_ESTADO_FACTURA
    WHERE
        P.CODIGO_INTERNO = @CODIGO_INTERNO
        AND E.CODIGO_ESTADO IN ('EMITIDA', 'PAGADA')
        AND F.FECHA_EMISION >= @DESDE
        AND F.FECHA_EMISION < DATEADD(DAY, 1, @HASTA)
);
GO
