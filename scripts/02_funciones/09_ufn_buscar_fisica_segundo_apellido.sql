/* DBO.UFN_BUSCAR_FISICA_SEGUNDO_APELLIDO — BUSCA PERSONAS FÍSICAS POR SU NOMBRE
   Y SU SEGUNDO APELLIDO. */

USE SISTEMA_FACTURACION;
GO

SET QUOTED_IDENTIFIER ON;
SET ANSI_NULLS ON;
GO

CREATE OR ALTER FUNCTION DBO.UFN_BUSCAR_FISICA_SEGUNDO_APELLIDO(
    @NOMBRE NVARCHAR(50),
    @SEGUNDO_APELLIDO NVARCHAR(50)
)
RETURNS TABLE
AS
RETURN (
    SELECT
        C.CEDULA_CLIENTE AS CEDULA,
        CF.NOMBRE,
        CF.PRIMER_APELLIDO,
        CF.SEGUNDO_APELLIDO,
        C.FECHA_REGISTRO
    FROM DBO.CLIENTE_FISICO AS CF
    INNER JOIN DBO.CLIENTE AS C
        ON CF.ID_CLIENTE = C.ID_CLIENTE
    WHERE
        CF.NOMBRE = LTRIM(RTRIM(@NOMBRE))
        AND CF.SEGUNDO_APELLIDO = LTRIM(RTRIM(@SEGUNDO_APELLIDO))
);
GO
