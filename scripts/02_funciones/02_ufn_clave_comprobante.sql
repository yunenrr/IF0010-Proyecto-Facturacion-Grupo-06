CREATE OR ALTER FUNCTION DBO.UFN_CLAVE_COMPROBANTE(
    @FECHA DATETIME2(7),
    @CODIGO_TIPO CHAR(3)
)
RETURNS VARCHAR(18)
AS
BEGIN
    RETURN
    CONVERT(CHAR(8), @FECHA, 112)
    + REPLACE(CONVERT(CHAR(8), @FECHA, 108), ':', '')
    + '-'
    + @CODIGO_TIPO;
END;
GO
