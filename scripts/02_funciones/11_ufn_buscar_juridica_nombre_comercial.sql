   TILDES Y MAYÚSCULAS. UN TEXTO VACÍO NO DEVUELVE FILAS. NO DEVUELVE CORREO
   NI TELÉFONO. */

USE SISTEMA_FACTURACION;
GO

SET QUOTED_IDENTIFIER ON;
SET ANSI_NULLS ON;
GO

CREATE OR ALTER FUNCTION DBO.UFN_BUSCAR_JURIDICA_NOMBRE_COMERCIAL(
    @TEXTO NVARCHAR(150)
)
RETURNS TABLE
AS
RETURN (
    SELECT
        C.CEDULA_CLIENTE AS CEDULA,
        CJ.RAZON_SOCIAL,
        CJ.NOMBRE_COMERCIAL,
        C.FECHA_REGISTRO
    FROM DBO.CLIENTE_JURIDICO AS CJ
    INNER JOIN DBO.CLIENTE AS C
        ON CJ.ID_CLIENTE = C.ID_CLIENTE
    WHERE
        CHARINDEX(
            TRIM(@TEXTO),
            CJ.NOMBRE_COMERCIAL COLLATE LATIN1_GENERAL_CI_AI
        ) > 0
);
GO
