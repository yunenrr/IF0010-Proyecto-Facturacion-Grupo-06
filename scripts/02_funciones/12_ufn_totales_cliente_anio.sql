/* DBO.UFN_TOTALES_CLIENTE_ANIO — TOTALES FACTURADOS EN EL AÑO VIGENTE POR
   CÉDULA DE CLIENTE (FÍSICO O JURÍDICO), AGRUPADOS POR MONEDA. SOLO CUENTA
   FACTURAS EMITIDAS Y PAGADAS. UNA CÉDULA SIN FACTURAS DEVUELVE 0 FILAS. */

USE SISTEMA_FACTURACION;
GO

SET QUOTED_IDENTIFIER ON;
SET ANSI_NULLS ON;
GO

CREATE OR ALTER FUNCTION DBO.UFN_TOTALES_CLIENTE_ANIO(
    @CEDULA VARCHAR(12)
)
RETURNS TABLE
AS
RETURN
(
    SELECT
        C.CEDULA_CLIENTE AS CEDULA,
        M.CODIGO_MONEDA AS MONEDA,
        COUNT(*) AS CANTIDAD_FACTURAS,
        SUM(F.TOTAL_DESCUENTOS) AS TOTAL_DESCUENTOS,
        SUM(F.TOTAL_IMPUESTOS) AS TOTAL_IMPUESTOS,
        SUM(F.MONTO_FINAL) AS MONTO_TOTAL_FACTURADO
    FROM DBO.CLIENTE AS C
    INNER JOIN DBO.FACTURA AS F
        ON C.ID_CLIENTE = F.ID_CLIENTE_COMPRADOR
    INNER JOIN DBO.ESTADO_FACTURA AS E
        ON F.ID_ESTADO_FACTURA = E.ID_ESTADO_FACTURA
    INNER JOIN DBO.MONEDA AS M
        ON F.ID_MONEDA = M.ID_MONEDA
    WHERE
        C.CEDULA_CLIENTE = LTRIM(RTRIM(@CEDULA))
        AND E.ESTADO IN ('EMITIDA', 'PAGADA')
        AND F.FECHA_EMISION >= DATEFROMPARTS(YEAR(SYSDATETIME()), 1, 1)
        AND F.FECHA_EMISION < DATEFROMPARTS(YEAR(SYSDATETIME()) + 1, 1, 1)
    GROUP BY
        C.CEDULA_CLIENTE,
        M.CODIGO_MONEDA
);
GO
