/* DBO.UFN_FACTURAS_PERSONA_JURIDICA — FACTURAS DE UNA PERSONA JURÍDICA POR
   CÉDULA. EXCLUYE BORRADOR Y MUESTRA EL
   ESTADO. UNA CÉDULA FÍSICA O INEXISTENTE DEVUELVE 0 FILAS. */

USE SISTEMA_FACTURACION;
GO

SET QUOTED_IDENTIFIER ON;
SET ANSI_NULLS ON;
GO

CREATE OR ALTER FUNCTION DBO.UFN_FACTURAS_PERSONA_JURIDICA(
    @CEDULA VARCHAR(12)
)
RETURNS TABLE
AS
RETURN
(
    SELECT
        F.ID_FACTURA,
        F.CONSECUTIVO,
        F.FECHA_EMISION,
        TD.DESCRIPCION AS TIPO_DOCUMENTO,
        EM.NOMBRE_COMERCIAL AS EMPRESA_EMISORA,
        E.ESTADO,
        M.CODIGO_MONEDA AS MONEDA,
        F.SUBTOTAL_FACTURA,
        F.TOTAL_DESCUENTOS,
        F.TOTAL_IMPUESTOS,
        F.MONTO_FINAL
    FROM DBO.CLIENTE AS C
    INNER JOIN DBO.CLIENTE_JURIDICO AS CJ
        ON C.ID_CLIENTE = CJ.ID_CLIENTE
    INNER JOIN DBO.FACTURA AS F
        ON C.ID_CLIENTE = F.ID_CLIENTE_COMPRADOR
    INNER JOIN DBO.ESTADO_FACTURA AS E
        ON F.ID_ESTADO_FACTURA = E.ID_ESTADO_FACTURA
    INNER JOIN DBO.TIPO_DOCUMENTO AS TD
        ON F.ID_TIPO_DOCUMENTO = TD.ID_TIPO_DOCUMENTO
    INNER JOIN DBO.EMPRESA AS EM
        ON F.ID_EMPRESA_EMISORA = EM.ID_EMPRESA
    INNER JOIN DBO.MONEDA AS M
        ON F.ID_MONEDA = M.ID_MONEDA
    WHERE
        C.CEDULA_CLIENTE = LTRIM(RTRIM(@CEDULA))
        AND E.ESTADO <> 'BORRADOR'
);
GO
