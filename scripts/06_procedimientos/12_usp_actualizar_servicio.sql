/* DBO.USP_ACTUALIZAR_SERVICIO — ACTUALIZA LA DURACIÓN ESTIMADA Y/O LA
   MODALIDAD A DOMICILIO DE UN SERVICIO. SOLO CAMBIA LO QUE SE ENVÍA; EL
   PRECIO Y LA TASA SE CAMBIAN CON USP_ACTUALIZAR_PRECIO_PRODUCTO. */

USE SISTEMA_FACTURACION;
GO

CREATE OR ALTER PROCEDURE DBO.USP_ACTUALIZAR_SERVICIO
    @ID_PRODUCTO INT,
    @DURACION_ESTIMADA_MIN SMALLINT = NULL,
    @SE_BRINDA_A_DOMICILIO BIT = NULL,
    @CODIGO_ERROR INT OUTPUT,
    @MENSAJE NVARCHAR(4000) OUTPUT
AS
BEGIN
    SET NOCOUNT ON;
    SET XACT_ABORT ON;

    SET @CODIGO_ERROR = 0;
    SET @MENSAJE = N'Servicio actualizado.';

    BEGIN TRY
        IF
            NOT EXISTS (
                SELECT 1 FROM DBO.SERVICIO
                WHERE ID_PRODUCTO = @ID_PRODUCTO
            )
            THROW 51301, N'El servicio no existe.', 1;

        IF @DURACION_ESTIMADA_MIN IS NULL AND @SE_BRINDA_A_DOMICILIO IS NULL
            THROW 51302, N'No se envió ningún dato para actualizar.', 1;

        IF @DURACION_ESTIMADA_MIN IS NOT NULL AND @DURACION_ESTIMADA_MIN <= 0
            THROW 51303, N'La duración estimada debe ser mayor que 0.', 1;

        BEGIN TRANSACTION;

        UPDATE DBO.SERVICIO
        SET
            DURACION_ESTIMADA_MIN = COALESCE(
                @DURACION_ESTIMADA_MIN, DURACION_ESTIMADA_MIN
            ),
            SE_BRINDA_A_DOMICILIO = COALESCE(
                @SE_BRINDA_A_DOMICILIO, SE_BRINDA_A_DOMICILIO
            )
        WHERE ID_PRODUCTO = @ID_PRODUCTO;

        IF @@ROWCOUNT = 0
            THROW 51301, N'El servicio no existe.', 1;

        COMMIT TRANSACTION;
    END TRY
    BEGIN CATCH
        IF XACT_STATE() <> 0
            ROLLBACK TRANSACTION;

        SET @CODIGO_ERROR = ERROR_NUMBER();
        SET @MENSAJE = ERROR_MESSAGE();
    END CATCH;
END;
GO
