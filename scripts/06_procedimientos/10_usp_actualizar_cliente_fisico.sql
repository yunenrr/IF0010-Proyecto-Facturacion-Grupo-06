/* DBO.USP_ACTUALIZAR_CLIENTE_FISICO — ACTUALIZA EL NOMBRE Y LOS APELLIDOS DE
   UNA PERSONA FÍSICA. SOLO CAMBIA LOS PARÁMETROS QUE SE ENVÍAN. */

USE SISTEMA_FACTURACION;
GO

CREATE OR ALTER PROCEDURE DBO.USP_ACTUALIZAR_CLIENTE_FISICO
    @ID_CLIENTE INT,
    @NOMBRE NVARCHAR(50) = NULL,
    @PRIMER_APELLIDO NVARCHAR(50) = NULL,
    @SEGUNDO_APELLIDO NVARCHAR(50) = NULL,
    @CODIGO_ERROR INT OUTPUT,
    @MENSAJE NVARCHAR(4000) OUTPUT
AS
BEGIN
    SET NOCOUNT ON;
    SET XACT_ABORT ON;

    SET @CODIGO_ERROR = 0;
    SET @MENSAJE = N'Persona física actualizada.';

    BEGIN TRY
        SET @NOMBRE = NULLIF(TRIM(@NOMBRE), N'');
        SET @PRIMER_APELLIDO = NULLIF(TRIM(@PRIMER_APELLIDO), N'');
        SET @SEGUNDO_APELLIDO = NULLIF(TRIM(@SEGUNDO_APELLIDO), N'');

        IF
            NOT EXISTS (
                SELECT 1 FROM DBO.CLIENTE_FISICO
                WHERE ID_CLIENTE = @ID_CLIENTE
            )
            THROW 51101, N'El cliente no existe como persona física.', 1;

        IF
            @NOMBRE IS NULL
            AND @PRIMER_APELLIDO IS NULL
            AND @SEGUNDO_APELLIDO IS NULL
            THROW 51102, N'No se envió ningún dato para actualizar.', 1;

        BEGIN TRANSACTION;

        UPDATE DBO.CLIENTE_FISICO
        SET
            NOMBRE = COALESCE(@NOMBRE, NOMBRE),
            PRIMER_APELLIDO = COALESCE(@PRIMER_APELLIDO, PRIMER_APELLIDO),
            SEGUNDO_APELLIDO = COALESCE(@SEGUNDO_APELLIDO, SEGUNDO_APELLIDO)
        WHERE ID_CLIENTE = @ID_CLIENTE;

        IF @@ROWCOUNT = 0
            THROW 51101, N'El cliente no existe como persona física.', 1;

        UPDATE DBO.CLIENTE
        SET FECHA_ACTUALIZACION = SYSDATETIME()
        WHERE ID_CLIENTE = @ID_CLIENTE;

        COMMIT TRANSACTION;
    END TRY
    BEGIN CATCH
        IF XACT_STATE() <> 0
            ROLLBACK TRANSACTION;

        SET @CODIGO_ERROR = ERROR_NUMBER();
        SET @MENSAJE = ERROR_MESSAGE();
    END CATCH;
END;
GO
