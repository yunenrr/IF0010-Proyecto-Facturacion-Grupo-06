/* CUBRE EL REQUISITO DE CONSULTAR FACTURAS POR COMPRADOR.
   EN BORRADOR, CONSECUTIVO Y FECHA_EMISION SON PROVISIONALES, ASÍ QUE LA
   CONSULTA DEBE EXCLUIR LOS BORRADOR. */

USE SISTEMA_FACTURACION;
GO

DROP INDEX IF EXISTS NC_FACTURA_CLIENTE_FECHA ON DBO.FACTURA;
GO

CREATE NONCLUSTERED INDEX NC_FACTURA_CLIENTE_FECHA
    ON DBO.FACTURA (ID_CLIENTE_COMPRADOR, FECHA_EMISION DESC)
    INCLUDE (
        ID_ESTADO_FACTURA,
        CONSECUTIVO,
        MONTO_FINAL
    );
GO
