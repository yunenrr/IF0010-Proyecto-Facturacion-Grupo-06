/* DBO.FN_HISTORIAL_CAMBIOS — CONSULTA UNIFICADA DEL HISTORIAL DE CAMBIOS.
   UNE LAS CUATRO TABLAS DE AUDITORÍA (FACTURA, DETALLE_FACTURA, CLIENTE Y
   PRODUCTO) EN UNA SOLA LÍNEA DE TIEMPO CON COLUMNAS COMUNES. */

USE SISTEMA_FACTURACION;
GO

SET QUOTED_IDENTIFIER ON;
SET ANSI_NULLS ON;
GO

CREATE OR ALTER FUNCTION DBO.FN_HISTORIAL_CAMBIOS(
    @FECHA_DESDE DATE = NULL,
    @FECHA_HASTA DATE = NULL
)
RETURNS TABLE
AS
RETURN (
    SELECT
        H.TABLA,
        H.ID_REGISTRO,
        T.CODIGO_OPERACION AS OPERACION,
        H.USUARIO_RESPONSABLE,
        H.FECHA_CAMBIO,
        H.DETALLE
    FROM (
        SELECT
            'FACTURA' AS TABLA,
            FH.ID_FACTURA AS ID_REGISTRO,
            FH.ID_TIPO_OPERACION,
            FH.USUARIO_RESPONSABLE,
            FH.FECHA_CAMBIO,
            CONCAT(
                N'Consecutivo ', RTRIM(FH.CONSECUTIVO),
                N' | Estado ', E.ESTADO,
                N' | Monto ', FH.MONTO_FINAL
            ) AS DETALLE
        FROM DBO.FACTURA_HISTORIAL AS FH
        INNER JOIN DBO.ESTADO_FACTURA AS E
            ON FH.ID_ESTADO_FACTURA = E.ID_ESTADO_FACTURA

        UNION ALL

        SELECT
            'DETALLE_FACTURA' AS TABLA,
            DH.ID_DETALLE AS ID_REGISTRO,
            DH.ID_TIPO_OPERACION,
            DH.USUARIO_RESPONSABLE,
            DH.FECHA_CAMBIO,
            CONCAT(
                N'Factura ', DH.ID_FACTURA,
                N' | Línea ', DH.NUMERO_LINEA,
                N' | Cantidad ', DH.CANTIDAD_FACTURADA,
                N' | Precio ', DH.PRECIO_UNITARIO,
                N' | Total ', DH.MONTO_TOTAL_LINEA
            ) AS DETALLE
        FROM DBO.DETALLE_FACTURA_HISTORIAL AS DH

        UNION ALL

        SELECT
            'CLIENTE' AS TABLA,
            CH.ID_CLIENTE AS ID_REGISTRO,
            CH.ID_TIPO_OPERACION,
            CH.USUARIO_RESPONSABLE,
            CH.FECHA_CAMBIO,
            CONCAT(
                N'Cédula ', CH.CEDULA_CLIENTE,
                N' | Correo ',
                CASE
                    WHEN IS_ROLEMEMBER('DBA') = 1 THEN CH.CORREO_CLIENTE
                    WHEN CHARINDEX('@', CH.CORREO_CLIENTE) > 1
                        THEN
                            LEFT(CH.CORREO_CLIENTE, 1) + '***'
                            + SUBSTRING(
                                CH.CORREO_CLIENTE,
                                CHARINDEX('@', CH.CORREO_CLIENTE),
                                254
                            )
                    ELSE '***'
                END,
                N' | Teléfono ',
                CASE
                    WHEN IS_ROLEMEMBER('DBA') = 1 THEN CH.TELEFONO_CLIENTE
                    WHEN LEN(CH.TELEFONO_CLIENTE) > 4
                        THEN
                            REPLICATE('*', LEN(CH.TELEFONO_CLIENTE) - 4)
                            + RIGHT(CH.TELEFONO_CLIENTE, 4)
                    ELSE '****'
                END
            ) AS DETALLE
        FROM DBO.CLIENTE_HISTORIAL AS CH

        UNION ALL

        SELECT
            'PRODUCTO' AS TABLA,
            PH.ID_PRODUCTO AS ID_REGISTRO,
            PH.ID_TIPO_OPERACION,
            PH.USUARIO_RESPONSABLE,
            PH.FECHA_CAMBIO,
            CONCAT(
                N'Precio ', PH.PRECIO_UNITARIO,
                N' | Tasa ', PH.TASA_IMPUESTO
            ) AS DETALLE
        FROM DBO.PRODUCTO_HISTORIAL AS PH
    ) AS H
    INNER JOIN DBO.TIPO_OPERACION AS T
        ON H.ID_TIPO_OPERACION = T.ID_TIPO_OPERACION
    WHERE
        (IS_ROLEMEMBER('AUDITOR') = 1 OR IS_ROLEMEMBER('DBA') = 1)
        AND (@FECHA_DESDE IS NULL OR H.FECHA_CAMBIO >= @FECHA_DESDE)
        AND (
            @FECHA_HASTA IS NULL
            OR H.FECHA_CAMBIO < DATEADD(DAY, 1, @FECHA_HASTA)
        )
);
GO

GRANT SELECT ON DBO.FN_HISTORIAL_CAMBIOS
TO AUDITOR, DBA, ADMINISTRATIVO, CAJERO, CONSULTA;
GO

/* DEMOSTRACIÓN: LA FUNCIÓN SOLO DEVUELVE REGISTROS A AUDITOR Y DBA. */
DECLARE @TOTAL_EN_TABLAS INT;
DECLARE @DESDE DATE;
DECLARE @HASTA DATE;
DECLARE @N_DBO INT;
DECLARE @N_AUDITOR INT;
DECLARE @N_AUDITOR_RANGO INT;
DECLARE @N_DBA INT;
DECLARE @N_ADMINISTRATIVO INT;
DECLARE @N_CAJERO INT;
DECLARE @N_CONSULTA INT;
DECLARE @CLIENTE_AUDITOR NVARCHAR(400);
DECLARE @CLIENTE_DBA NVARCHAR(400);
DECLARE @ACCESO_DIRECTO_CAJERO NVARCHAR(400);
DECLARE @PRUEBA INT;

-- CONTROL: FILAS QUE REALMENTE EXISTEN (LEÍDAS DIRECTO, COMO DBO)
SET
    @TOTAL_EN_TABLAS = (SELECT COUNT(*) FROM DBO.FACTURA_HISTORIAL)
    + (SELECT COUNT(*) FROM DBO.DETALLE_FACTURA_HISTORIAL)
    + (SELECT COUNT(*) FROM DBO.CLIENTE_HISTORIAL)
    + (SELECT COUNT(*) FROM DBO.PRODUCTO_HISTORIAL);

-- RANGO DE PRUEBA: EL PRIMER MES CON CAMBIOS EN FACTURAS
SET @DESDE = (
    SELECT CAST(MIN(FECHA_CAMBIO) AS DATE)
    FROM DBO.FACTURA_HISTORIAL
);
SET @HASTA = DATEADD(DAY, 30, @DESDE);

-- DBO (QUIEN EJECUTA EL SCRIPT, NORMALMENTE SA)
SELECT @N_DBO = COUNT(*) FROM DBO.FN_HISTORIAL_CAMBIOS(DEFAULT, DEFAULT);

EXECUTE AS USER = 'USR_AUDITOR'; -- noqa: PRS
SELECT @N_AUDITOR = COUNT(*)
FROM DBO.FN_HISTORIAL_CAMBIOS(DEFAULT, DEFAULT);
SELECT @N_AUDITOR_RANGO = COUNT(*)
FROM DBO.FN_HISTORIAL_CAMBIOS(@DESDE, @HASTA);
SELECT TOP (1) @CLIENTE_AUDITOR = DETALLE
FROM DBO.FN_HISTORIAL_CAMBIOS(DEFAULT, DEFAULT)
WHERE TABLA = 'CLIENTE'
ORDER BY ID_REGISTRO;
REVERT; -- noqa: PRS

EXECUTE AS USER = 'USR_DBA'; -- noqa: PRS
SELECT @N_DBA = COUNT(*)
FROM DBO.FN_HISTORIAL_CAMBIOS(DEFAULT, DEFAULT);
SELECT TOP (1) @CLIENTE_DBA = DETALLE
FROM DBO.FN_HISTORIAL_CAMBIOS(DEFAULT, DEFAULT)
WHERE TABLA = 'CLIENTE'
ORDER BY ID_REGISTRO;
REVERT; -- noqa: PRS

EXECUTE AS USER = 'USR_ADMINISTRATIVO'; -- noqa: PRS
SELECT @N_ADMINISTRATIVO = COUNT(*)
FROM DBO.FN_HISTORIAL_CAMBIOS(DEFAULT, DEFAULT);
REVERT; -- noqa: PRS

EXECUTE AS USER = 'USR_CAJERO'; -- noqa: PRS
SELECT @N_CAJERO = COUNT(*)
FROM DBO.FN_HISTORIAL_CAMBIOS(DEFAULT, DEFAULT);
-- INTENTO DE SALTARSE LA FUNCIÓN LEYENDO LA TABLA DIRECTAMENTE
BEGIN TRY
    SELECT @PRUEBA = COUNT(*) FROM DBO.FACTURA_HISTORIAL;
    SET @ACCESO_DIRECTO_CAJERO = N'PERMITIDO (REVISAR PERMISOS)';
END TRY
BEGIN CATCH
    SET @ACCESO_DIRECTO_CAJERO = CONCAT(
        N'DENEGADO: error ', ERROR_NUMBER(), N' - ', ERROR_MESSAGE()
    );
END CATCH;
REVERT; -- noqa: PRS

EXECUTE AS USER = 'USR_CONSULTA'; -- noqa: PRS
SELECT @N_CONSULTA = COUNT(*)
FROM DBO.FN_HISTORIAL_CAMBIOS(DEFAULT, DEFAULT);
REVERT; -- noqa: PRS

-- RESULTADO 1: QUÉ VE CADA IDENTIDAD
SELECT
    V.IDENTIDAD,
    V.ROL,
    V.FILAS_VISIBLES,
    @TOTAL_EN_TABLAS AS FILAS_EN_TABLAS,
    V.EJEMPLO_CLIENTE
FROM (
    VALUES
    (1, N'dbo (sa)', N'(ninguno)', @N_DBO, NULL),
    (2, N'USR_AUDITOR', N'AUDITOR', @N_AUDITOR, @CLIENTE_AUDITOR),
    (3, N'USR_DBA', N'DBA', @N_DBA, @CLIENTE_DBA),
    (4, N'USR_ADMINISTRATIVO', N'ADMINISTRATIVO', @N_ADMINISTRATIVO, NULL),
    (5, N'USR_CAJERO', N'CAJERO', @N_CAJERO, NULL),
    (6, N'USR_CONSULTA', N'CONSULTA', @N_CONSULTA, NULL)
) AS V (ORDEN, IDENTIDAD, ROL, FILAS_VISIBLES, EJEMPLO_CLIENTE)
ORDER BY V.ORDEN;

-- RESULTADO 2: FILTRO POR FECHAS Y PROTECCIÓN DE LA TABLA
SELECT
    @DESDE AS RANGO_DESDE,
    @HASTA AS RANGO_HASTA,
    @N_AUDITOR_RANGO AS FILAS_AUDITOR_EN_RANGO,
    @ACCESO_DIRECTO_CAJERO AS CAJERO_LEYENDO_TABLA_DIRECTO;
GO
