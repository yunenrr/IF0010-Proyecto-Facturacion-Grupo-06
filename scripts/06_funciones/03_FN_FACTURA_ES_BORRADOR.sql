/* DBO.FN_FACTURA_ES_BORRADOR — INDICA SI UN COMPROBANTE SE PUEDE MODIFICAR.
   RECIBE EL CONSECUTIVO Y DEVUELVE:
     1: LA FACTURA ESTÁ EN BORRADOR (SE PUEDE MODIFICAR)
     0: LA FACTURA ESTÁ EN CUALQUIER OTRO ESTADO
     NULL: NO EXISTE UNA FACTURA CON ESE CONSECUTIVO */

USE SISTEMA_FACTURACION;
GO

SET QUOTED_IDENTIFIER ON;
SET ANSI_NULLS ON;
GO

CREATE OR ALTER FUNCTION DBO.FN_FACTURA_ES_BORRADOR(
    @CONSECUTIVO CHAR(20)
)
RETURNS BIT
AS
BEGIN
    RETURN (
        SELECT
            CAST(
                CASE WHEN E.ESTADO = 'BORRADOR' THEN 1 ELSE 0 END AS BIT
            )
        FROM DBO.FACTURA AS F
        INNER JOIN DBO.ESTADO_FACTURA AS E
            ON F.ID_ESTADO_FACTURA = E.ID_ESTADO_FACTURA
        WHERE F.CONSECUTIVO = @CONSECUTIVO
    );
END;
GO

-- PERMISOS
GRANT EXECUTE ON DBO.FN_FACTURA_ES_BORRADOR
TO AUDITOR, DBA, ADMINISTRATIVO, CAJERO, CONSULTA;
GO

-- PRUEBA RÁPIDA: UNA FACTURA POR ESTADO MÁS UN CONSECUTIVO INEXISTENTE.
-- ESPERADO: BORRADOR = 1, LOS DEMÁS ESTADOS = 0, NO EXISTE = NULL.
WITH MUESTRA AS (
    SELECT
        E.ESTADO,
        F.CONSECUTIVO,
        ROW_NUMBER() OVER (
            PARTITION BY E.ESTADO
            ORDER BY F.ID_FACTURA
        ) AS RN
    FROM DBO.FACTURA AS F
    INNER JOIN DBO.ESTADO_FACTURA AS E
        ON F.ID_ESTADO_FACTURA = E.ID_ESTADO_FACTURA
)

SELECT
    M.ESTADO,
    M.CONSECUTIVO,
    DBO.FN_FACTURA_ES_BORRADOR(M.CONSECUTIVO) AS ES_BORRADOR
FROM MUESTRA AS M
WHERE M.RN = 1
UNION ALL
SELECT
    'NO EXISTE' AS ESTADO,
    '19000101000000-FAC' AS CONSECUTIVO,
    DBO.FN_FACTURA_ES_BORRADOR('19000101000000-FAC') AS ES_BORRADOR;
GO
