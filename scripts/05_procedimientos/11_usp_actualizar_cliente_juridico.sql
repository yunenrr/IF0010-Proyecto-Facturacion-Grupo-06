/* DBO.USP_ACTUALIZAR_CLIENTE_JURIDICO — ACTUALIZA LA RAZÓN SOCIAL Y EL NOMBRE
   COMERCIAL DE UNA PERSONA JURÍDICA. SOLO CAMBIA LOS PARÁMETROS QUE SE
   ENVÍAN */

USE SISTEMA_FACTURACION;
GO

CREATE OR ALTER PROCEDURE DBO.USP_ACTUALIZAR_CLIENTE_JURIDICO
    @ID_CLIENTE INT,
    @RAZON_SOCIAL NVARCHAR(150) = NULL,
    @NOMBRE_COMERCIAL NVARCHAR(150) = NULL,
    @CODIGO_ERROR INT OUTPUT,
    @MENSAJE NVARCHAR(4000) OUTPUT
AS
BEGIN
    SET NOCOUNT ON;
    SET XACT_ABORT ON;

    SET @CODIGO_ERROR = 0;
    SET @MENSAJE = N'Persona jurídica actualizada.';

    BEGIN TRY
        SET @RAZON_SOCIAL = NULLIF(TRIM(@RAZON_SOCIAL), N'');
        SET @NOMBRE_COMERCIAL = NULLIF(TRIM(@NOMBRE_COMERCIAL), N'');

        IF
            NOT EXISTS (
                SELECT 1 FROM DBO.CLIENTE_JURIDICO
                WHERE ID_CLIENTE = @ID_CLIENTE
            )
            THROW 51201, N'El cliente no existe como persona jurídica.', 1;

        IF @RAZON_SOCIAL IS NULL AND @NOMBRE_COMERCIAL IS NULL
            THROW 51202, N'No se envió ningún dato para actualizar.', 1;

        BEGIN TRANSACTION;

        UPDATE DBO.CLIENTE_JURIDICO
        SET
            RAZON_SOCIAL = COALESCE(@RAZON_SOCIAL, RAZON_SOCIAL),
            NOMBRE_COMERCIAL = COALESCE(@NOMBRE_COMERCIAL, NOMBRE_COMERCIAL)
        WHERE ID_CLIENTE = @ID_CLIENTE;

        IF @@ROWCOUNT = 0
            THROW 51201, N'El cliente no existe como persona jurídica.', 1;

        UPDATE DBO.CLIENTE
        SET FECHA_ACTUALIZACION = SYSDATETIME()
        WHERE ID_CLIENTE = @ID_CLIENTE;

        COMMIT TRANSACTION;
    END TRY
    BEGIN CATCH
        IF XACT_STATE() <> 0
            ROLLBACK TRANSACTION;

        SET @CODIGO_ERROR = ERROR_NUMBER();
        SET @MENSAJE = ERROR_MESSAGE();
    END CATCH;
END;
GO
