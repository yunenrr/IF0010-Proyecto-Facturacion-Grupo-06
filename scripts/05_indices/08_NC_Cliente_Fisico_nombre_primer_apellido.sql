/* CUBRE LA BÚSQUEDA DE PERSONAS FÍSICAS POR NOMBRE Y PRIMER APELLIDO
   LAS CONSULTAS USAN EL ÍNDICE EN LUGAR DE BUSCAR FILA POR FILA. */

USE SISTEMA_FACTURACION;
GO

DROP INDEX IF EXISTS NC_CLIENTE_FISICO_NOMBRE_PRIMER_APELLIDO
ON DBO.CLIENTE_FISICO;
GO

CREATE NONCLUSTERED INDEX NC_CLIENTE_FISICO_NOMBRE_PRIMER_APELLIDO
    ON DBO.CLIENTE_FISICO (NOMBRE, PRIMER_APELLIDO)
    INCLUDE (SEGUNDO_APELLIDO);
GO
