/* CUBRE EL REQUISITO DE CONSULTAR TOTALES DE UNA FACTURA POR IDENTIFICADOR DE
   COMPROBANTE. */

USE SISTEMA_FACTURACION;
GO

SET QUOTED_IDENTIFIER ON;
SET ANSI_NULLS ON;
GO

DROP INDEX IF EXISTS NC_FACTURA_CONSECUTIVO ON DBO.FACTURA;
GO

CREATE UNIQUE NONCLUSTERED INDEX NC_FACTURA_CONSECUTIVO
    ON DBO.FACTURA (CONSECUTIVO)
    INCLUDE (
        SUBTOTAL_FACTURA,
        TOTAL_DESCUENTOS,
        TOTAL_IMPUESTOS,
        MONTO_FINAL
    );
GO
