/* CUBRE EL REQUISITO DE CONSULTAR TOTALES DE UNA FACTURA POR IDENTIFICADOR DE
   COMPROBANTE. ES UNIQUE FILTRANDO LOS NULL PORQUE EL CONSECUTIVO PUEDE SER
   NULL MIENTRAS LA FACTURA ESTA EN BORRADOR.
   REQUIERE QUOTED_IDENTIFIER Y ANSI_NULLS EN ON: SON OBLIGATORIOS PARA CREAR
   INDICES FILTRADOS. SQLCMD LOS DEJA EN OFF, POR ESO SE FIJAN AQUI. */

USE SISTEMA_FACTURACION;
GO

SET QUOTED_IDENTIFIER ON;
SET ANSI_NULLS ON;
GO

DROP INDEX IF EXISTS NC_FACTURA_CONSECUTIVO ON DBO.FACTURA;
GO

CREATE UNIQUE NONCLUSTERED INDEX NC_FACTURA_CONSECUTIVO
    ON DBO.FACTURA (CONSECUTIVO)
    INCLUDE (
        SUBTOTAL_FACTURA,
        TOTAL_DESCUENTOS,
        TOTAL_IMPUESTOS,
        MONTO_FINAL
    )
    WHERE CONSECUTIVO IS NOT NULL;
GO
