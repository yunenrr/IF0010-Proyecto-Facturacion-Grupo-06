/* DBO.CLIENTE_JURIDICO — SUBTIPO DE DBO.CLIENTE PARA PERSONAS JURÍDICAS. */

USE SISTEMA_FACTURACION;
GO

CREATE TABLE DBO.CLIENTE_JURIDICO (
    ID_CLIENTE INT NOT NULL,
    RAZON_SOCIAL NVARCHAR(150) NOT NULL,
    NOMBRE_COMERCIAL NVARCHAR(150) NOT NULL,

    CONSTRAINT PK_CLIENTE_JURIDICO PRIMARY KEY (ID_CLIENTE),
    CONSTRAINT FK_CLIENTE_JURIDICO_CLIENTE FOREIGN KEY (ID_CLIENTE)
    REFERENCES DBO.CLIENTE (ID_CLIENTE)
);
GO
