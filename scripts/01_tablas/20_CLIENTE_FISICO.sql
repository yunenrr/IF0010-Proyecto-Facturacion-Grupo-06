/* DBO.CLIENTE_FISICO — SUBTIPO DE DBO.CLIENTE PARA PERSONAS FÍSICAS. */

USE SISTEMA_FACTURACION;
GO

CREATE TABLE DBO.CLIENTE_FISICO (
    ID_CLIENTE INT NOT NULL,
    NOMBRE NVARCHAR(50) NOT NULL,
    PRIMER_APELLIDO NVARCHAR(50) NOT NULL,
    SEGUNDO_APELLIDO NVARCHAR(50) NOT NULL,

    CONSTRAINT PK_CLIENTE_FISICO PRIMARY KEY (ID_CLIENTE),
    CONSTRAINT FK_CLIENTE_FISICO_CLIENTE FOREIGN KEY (ID_CLIENTE)
    REFERENCES DBO.CLIENTE (ID_CLIENTE)
);
GO
