USE SISTEMA_FACTURACION;
GO

CREATE TABLE DBO.PRODUCTO (
    ID_PRODUCTO INT IDENTITY (1, 1) NOT NULL,
    CODIGO_INTERNO VARCHAR(20) NOT NULL,
    DESCRIPCION_PRODUCTO NVARCHAR(150) NOT NULL,
    PRECIO_UNITARIO DECIMAL(18, 5) NOT NULL,
    TASA_IMPUESTO DECIMAL(5, 4) NOT NULL,
    ESTADO_PRODUCTO BIT NOT NULL,
    FECHA_CREACION DATETIME2(3) NOT NULL,

    CONSTRAINT PK_PRODUCTO PRIMARY KEY (ID_PRODUCTO),
    CONSTRAINT UQ_PRODUCTO_CODIGO_INTERNO
        UNIQUE (CODIGO_INTERNO),
    CONSTRAINT CK_PRODUCTO_PRECIO_UNITARIO
        CHECK (PRECIO_UNITARIO >= 0),
    CONSTRAINT CK_PRODUCTO_TASA_IMPUESTO
        CHECK (TASA_IMPUESTO BETWEEN 0 AND 1)
);
GO

ALTER TABLE DBO.PRODUCTO
    ADD CONSTRAINT DF_PRODUCTO_FECHA_CREACION 
        DEFAULT SYSDATETIME() FOR FECHA_CREACION;
GO
