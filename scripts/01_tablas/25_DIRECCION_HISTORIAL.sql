/* DBO.DIRECCION_HISTORIAL — AUDITORÍA DE LAS DIRECCIONES.
   SIN FK HACIA DBO.DIRECCION PORQUE DEBE REGISTRAR EL DELETE DE DIRECCIONES
   QUE YA NO EXISTEN. */

USE SISTEMA_FACTURACION;
GO

DROP TABLE IF EXISTS DBO.DIRECCION_HISTORIAL;
GO

CREATE TABLE DBO.DIRECCION_HISTORIAL (
    ID_HISTORIAL BIGINT IDENTITY (1, 1) NOT NULL,
    ID_DIRECCION INT NOT NULL,
    ID_TIPO_OPERACION TINYINT NOT NULL,
    USUARIO_RESPONSABLE SYSNAME NOT NULL,
    FECHA_CAMBIO DATETIME2(3) NOT NULL,
    ID_DISTRITO INT NOT NULL,
    OTRAS_SENAS NVARCHAR(250) NOT NULL,
    CONSTRAINT PK_DIRECCION_HISTORIAL
    PRIMARY KEY (ID_HISTORIAL),
    CONSTRAINT FK_DIRECCION_HISTORIAL_TIPO_OPERACION
    FOREIGN KEY (ID_TIPO_OPERACION)
    REFERENCES DBO.TIPO_OPERACION (ID_TIPO_OPERACION),
    CONSTRAINT FK_DIRECCION_HISTORIAL_DISTRITO
    FOREIGN KEY (ID_DISTRITO)
    REFERENCES DBO.DISTRITO (ID_DISTRITO)
);
GO
