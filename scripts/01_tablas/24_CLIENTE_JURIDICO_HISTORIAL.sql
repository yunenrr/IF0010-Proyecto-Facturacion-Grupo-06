/* DBO.CLIENTE_JURIDICO_HISTORIAL — AUDITORÍA DE LA RAZÓN SOCIAL Y EL NOMBRE
   COMERCIAL DE LAS PERSONAS JURÍDICAS. SIN FK HACIA DBO.CLIENTE_JURIDICO
   PORQUE DEBE REGISTRAR EL DELETE DE PERSONAS JURÍDICAS QUE YA NO EXISTEN. */

USE SISTEMA_FACTURACION;
GO

DROP TABLE IF EXISTS DBO.CLIENTE_JURIDICO_HISTORIAL;
GO

CREATE TABLE DBO.CLIENTE_JURIDICO_HISTORIAL (
    ID_HISTORIAL BIGINT IDENTITY (1, 1) NOT NULL,
    ID_CLIENTE INT NOT NULL,
    ID_TIPO_OPERACION TINYINT NOT NULL,
    USUARIO_RESPONSABLE SYSNAME NOT NULL,
    FECHA_CAMBIO DATETIME2(3) NOT NULL,
    RAZON_SOCIAL NVARCHAR(150) NOT NULL,
    NOMBRE_COMERCIAL NVARCHAR(150) NOT NULL,
    CONSTRAINT PK_CLIENTE_JURIDICO_HISTORIAL
    PRIMARY KEY (ID_HISTORIAL),
    CONSTRAINT FK_CLIENTE_JURIDICO_HISTORIAL_TIPO_OPERACION
    FOREIGN KEY (ID_TIPO_OPERACION)
    REFERENCES DBO.TIPO_OPERACION (ID_TIPO_OPERACION)
);
GO
