/* DBO.DETALLE_FACTURA — LÍNEAS DEL COMPROBANTE. UNA FACTURA ADMITE HASTA 255
   LÍNEAS. */

USE SISTEMA_FACTURACION;
GO

DROP TABLE IF EXISTS DBO.DETALLE_FACTURA;
GO

CREATE TABLE DBO.DETALLE_FACTURA
(
    ID_DETALLE INT IDENTITY (1, 1) NOT NULL,
    ID_FACTURA INT NOT NULL,
    ID_PRODUCTO INT NOT NULL,
    NUMERO_LINEA TINYINT NOT NULL,
    DESCRIPCION_LINEA NVARCHAR(150) NOT NULL,
    -- FOTO FISCAL: DESCRIPCIÓN TAL COMO SE FACTURÓ.
    CANTIDAD_FACTURADA DECIMAL(9, 3) NOT NULL,
    PRECIO_UNITARIO DECIMAL(18, 5) NOT NULL,
    TASA_IMPUESTO DECIMAL(5, 4) NOT NULL,
    MONTO_DESCUENTO DECIMAL(18, 2) NOT NULL,
    MONTO_IMPUESTO_LINEA DECIMAL(18, 2) NOT NULL,
    SUBTOTAL_LINEA DECIMAL(18, 2) NOT NULL,
    MONTO_TOTAL_LINEA DECIMAL(18, 2) NOT NULL,

    CONSTRAINT PK_DETALLE_FACTURA
    PRIMARY KEY (ID_DETALLE),
    CONSTRAINT UQ_DETALLE_FACTURA_FACTURA_LINEA
    UNIQUE (ID_FACTURA, NUMERO_LINEA),

    CONSTRAINT FK_DETALLE_FACTURA_FACTURA
    FOREIGN KEY (ID_FACTURA)
    REFERENCES DBO.FACTURA (ID_FACTURA),
    CONSTRAINT FK_DETALLE_FACTURA_PRODUCTO
    FOREIGN KEY (ID_PRODUCTO)
    REFERENCES DBO.PRODUCTO (ID_PRODUCTO)
);
GO
