/* DBO.TIPO_PRODUCTO — CATÁLOGO QUE DISTINGUE BIENES DE SERVICIOS.
   LO REFERENCIA PRODUCTO */

USE SISTEMA_FACTURACION;
GO

CREATE TABLE DBO.TIPO_PRODUCTO (
    ID_TIPO_PRODUCTO TINYINT NOT NULL,
    CODIGO_TIPO CHAR(3) NOT NULL, -- PRD | SRV
    DESCRIPCION_TIPO NVARCHAR(30) NOT NULL,

    CONSTRAINT PK_TIPO_PRODUCTO PRIMARY KEY (ID_TIPO_PRODUCTO),
    CONSTRAINT UQ_TIPO_PRODUCTO_CODIGO_TIPO UNIQUE (CODIGO_TIPO),
    CONSTRAINT UQ_TIPO_PRODUCTO_DESCRIPCION_TIPO UNIQUE (DESCRIPCION_TIPO)
);
GO
