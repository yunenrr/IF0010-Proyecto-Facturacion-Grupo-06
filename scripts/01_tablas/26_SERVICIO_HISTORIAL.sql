/* DBO.SERVICIO_HISTORIAL — AUDITORÍA DE LOS DATOS PROPIOS DE UN SERVICIO.
   SIN FK HACIA DBO.SERVICIO PORQUE DEBE REGISTRAR EL DELETE DE SERVICIOS QUE
   YA NO EXISTEN. */

USE SISTEMA_FACTURACION;
GO

DROP TABLE IF EXISTS DBO.SERVICIO_HISTORIAL;
GO

CREATE TABLE DBO.SERVICIO_HISTORIAL (
    ID_HISTORIAL BIGINT IDENTITY (1, 1) NOT NULL,
    ID_PRODUCTO INT NOT NULL,
    ID_TIPO_OPERACION TINYINT NOT NULL,
    USUARIO_RESPONSABLE SYSNAME NOT NULL,
    FECHA_CAMBIO DATETIME2(3) NOT NULL,
    DURACION_ESTIMADA_MIN SMALLINT NOT NULL,
    SE_BRINDA_A_DOMICILIO BIT NOT NULL,
    CONSTRAINT PK_SERVICIO_HISTORIAL
    PRIMARY KEY (ID_HISTORIAL),
    CONSTRAINT FK_SERVICIO_HISTORIAL_TIPO_OPERACION
    FOREIGN KEY (ID_TIPO_OPERACION)
    REFERENCES DBO.TIPO_OPERACION (ID_TIPO_OPERACION)
);
GO
