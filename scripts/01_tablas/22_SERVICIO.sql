/* DBO.SERVICIO — SUBTIPO DE DBO.PRODUCTO PARA LOS PRODUCTOS DE TIPO SRV.
   GUARDA SOLO LO PROPIO DE UN SERVICIO; EL RESTO VIVE EN DBO.PRODUCTO. */

USE SISTEMA_FACTURACION;
GO

CREATE TABLE DBO.SERVICIO (
    ID_PRODUCTO INT NOT NULL,
    DURACION_ESTIMADA_MIN SMALLINT NOT NULL,
    SE_BRINDA_A_DOMICILIO BIT NOT NULL,

    CONSTRAINT PK_SERVICIO PRIMARY KEY (ID_PRODUCTO),
    CONSTRAINT FK_SERVICIO_PRODUCTO FOREIGN KEY (ID_PRODUCTO)
    REFERENCES DBO.PRODUCTO (ID_PRODUCTO)
);
GO
