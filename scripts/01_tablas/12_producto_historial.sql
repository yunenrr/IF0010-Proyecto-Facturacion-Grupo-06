/* DBO.PRODUCTO_HISTORIAL — AUDITORÍA DEL CATÁLOGO DE PRODUCTOS.
   SIN FK HACIA DBO.PRODUCTO PORQUE DEBE REGISTRAR EL DELETE DE PRODUCTOS QUE
   YA NO EXISTEN.
   CADA FILA ES UNA FOTO DEL PRODUCTO: EN INSERT Y UPDATE GUARDA LOS VALORES
   DESPUÉS DE LA OPERACIÓN; EN DELETE, LOS VALORES BORRADOS. EL VALOR ANTERIOR
   ES LA FILA PREVIA DEL MISMO ID_PRODUCTO. ASÍ NINGUNA COLUMNA ADMITE NULL.
   USUARIO_RESPONSABLE Y FECHA_CAMBIO LOS ASIGNA EL TRIGGER CON ORIGINAL_LOGIN()
   Y SYSDATETIME(). */

USE SISTEMA_FACTURACION;
GO

DROP TABLE IF EXISTS DBO.PRODUCTO_HISTORIAL;
GO

CREATE TABLE DBO.PRODUCTO_HISTORIAL (
    ID_HISTORIAL BIGINT IDENTITY (1, 1) NOT NULL,
    ID_PRODUCTO INT NOT NULL,
    OPERACION CHAR(6) NOT NULL, -- INSERT | DELETE | UPDATE
    USUARIO_RESPONSABLE SYSNAME NOT NULL,
    FECHA_CAMBIO DATETIME2(3) NOT NULL,
    DESCRIPCION_CAMBIO NVARCHAR(500) NOT NULL, -- N'' SI NO HAY
    PRECIO_UNITARIO DECIMAL(18, 5) NOT NULL,
    TASA_IMPUESTO DECIMAL(5, 4) NOT NULL,
    CONSTRAINT PK_PRODUCTO_HISTORIAL
    PRIMARY KEY (ID_HISTORIAL)
);
GO
