/* DBO.DETALLE_FACTURA_HISTORIAL — AUDITORÍA DE LAS LÍNEAS DE COMPROBANTES.
   SIN FK HACIA DBO.DETALLE_FACTURA PORQUE DEBE REGISTRAR EL DELETE DE DETALLES
   QUE YA NO EXISTEN.
   CADA FILA ES UNA FOTO DE LA LÍNEA: EN INSERT Y UPDATE GUARDA LOS VALORES
   DESPUÉS DE LA OPERACIÓN; EN DELETE, LOS VALORES BORRADOS. EL VALOR ANTERIOR
   ES LA FILA PREVIA DEL MISMO ID_DETALLE. ASÍ NINGUNA COLUMNA ADMITE NULL.
   USUARIO_RESPONSABLE Y FECHA_CAMBIO LOS ASIGNA EL TRIGGER CON ORIGINAL_LOGIN()
   Y SYSDATETIME(). */

USE SISTEMA_FACTURACION;
GO

DROP TABLE IF EXISTS DBO.DETALLE_FACTURA_HISTORIAL;
GO

CREATE TABLE DBO.DETALLE_FACTURA_HISTORIAL (
    ID_HISTORIAL BIGINT IDENTITY (1, 1) NOT NULL,
    ID_DETALLE INT NOT NULL, -- MISMO TIPO QUE DETALLE_FACTURA.ID_DETALLE
    ID_FACTURA INT NOT NULL,
    NUMERO_LINEA TINYINT NOT NULL, -- NUMERO CORRELATIVO
    OPERACION CHAR(6) NOT NULL, -- INSERT | DELETE | UPDATE
    USUARIO_RESPONSABLE SYSNAME NOT NULL,
    FECHA_CAMBIO DATETIME2(3) NOT NULL,
    DESCRIPCION_CAMBIO NVARCHAR(500) NOT NULL, -- N'' SI NO HAY
    CANTIDAD_FACTURADA DECIMAL(9, 3) NOT NULL,
    PRECIO_UNITARIO DECIMAL(18, 5) NOT NULL,
    MONTO_DESCUENTO DECIMAL(18, 2) NOT NULL,
    TASA_IMPUESTO DECIMAL(5, 4) NOT NULL,
    MONTO_IMPUESTO_LINEA DECIMAL(18, 2) NOT NULL,
    MONTO_TOTAL_LINEA DECIMAL(18, 2) NOT NULL,
    CONSTRAINT PK_DETALLE_FACTURA_HISTORIAL
    PRIMARY KEY (ID_HISTORIAL)
);
GO
