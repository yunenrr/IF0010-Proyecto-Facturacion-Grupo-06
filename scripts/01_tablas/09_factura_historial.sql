/* DBO.FACTURA_HISTORIAL — AUDITORÍA DEL ENCABEZADO DE COMPROBANTES.
   SIN FK HACIA FACTURA PORQUE DEBE REGISTRAR EL DELETE DE FACTURAS QUE YA NO
   EXISTEN. */

USE SISTEMA_FACTURACION;
GO

DROP TABLE IF EXISTS DBO.FACTURA_HISTORIAL;
GO

CREATE TABLE DBO.FACTURA_HISTORIAL (
    ID_HISTORIAL BIGINT IDENTITY (1, 1) NOT NULL,
    ID_FACTURA INT NOT NULL,
    ID_TIPO_OPERACION TINYINT NOT NULL,
    USUARIO_RESPONSABLE SYSNAME NOT NULL,
    FECHA_CAMBIO DATETIME2(3) NOT NULL,
    CONSECUTIVO CHAR(20) NOT NULL,
    ID_ESTADO_FACTURA TINYINT NOT NULL,
    MONTO_FINAL DECIMAL(18, 2) NOT NULL,
    CONSTRAINT PK_FACTURA_HISTORIAL
    PRIMARY KEY (ID_HISTORIAL),
    CONSTRAINT FK_FACTURA_HISTORIAL_ESTADO_FACTURA
    FOREIGN KEY (ID_ESTADO_FACTURA)
    REFERENCES DBO.ESTADO_FACTURA (ID_ESTADO_FACTURA),
    CONSTRAINT FK_FACTURA_HISTORIAL_TIPO_OPERACION
    FOREIGN KEY (ID_TIPO_OPERACION)
    REFERENCES DBO.TIPO_OPERACION (ID_TIPO_OPERACION)
);
GO
