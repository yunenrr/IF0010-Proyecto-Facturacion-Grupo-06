USE SISTEMA_FACTURACION;
GO

CREATE TABLE DBO.CLIENTE (
    ID_CLIENTE INT IDENTITY (1, 1) NOT NULL,
    CEDULA_CLIENTE VARCHAR(12) NOT NULL,
    NOMBRE_CLIENTE NVARCHAR(150) NOT NULL,
    CORREO_CLIENTE VARCHAR(254) NOT NULL,
    TELEFONO_CLIENTE VARCHAR(12) NOT NULL,
    ID_DIRECCION INT NOT NULL,
    FECHA_REGISTRO DATETIME2(3) NOT NULL
    CONSTRAINT DF_CLIENTE_FECHA_REGISTRO DEFAULT SYSDATETIME(),
    FECHA_ACTUALIZACION DATETIME2(3) NOT NULL
    CONSTRAINT DF_CLIENTE_FECHA_ACTUALIZACION DEFAULT SYSDATETIME(),

    CONSTRAINT PK_CLIENTE PRIMARY KEY (ID_CLIENTE),
    CONSTRAINT UQ_CLIENTE_CEDULA_CLIENTE UNIQUE (CEDULA_CLIENTE),
    CONSTRAINT UQ_CLIENTE_CORREO_CLIENTE UNIQUE (CORREO_CLIENTE),
    CONSTRAINT FK_CLIENTE_DIRECCION FOREIGN KEY (ID_DIRECCION) 
    REFERENCES DBO.DIRECCION (ID_DIRECCION)
);
GO
