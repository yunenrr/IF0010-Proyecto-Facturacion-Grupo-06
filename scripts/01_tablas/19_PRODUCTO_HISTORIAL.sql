/* DBO.PRODUCTO_HISTORIAL — AUDITORÍA DEL CATÁLOGO DE PRODUCTOS.
   GUARDA UNA COPIA DE LA FILA COMPLETA DE DBO.PRODUCTO (MISMAS COLUMNAS Y
   TIPOS, TODAS NOT NULL). SIN FK HACIA DBO.PRODUCTO PORQUE DEBE REGISTRAR EL
   DELETE DE PRODUCTOS QUE YA NO EXISTEN. */

USE SISTEMA_FACTURACION;
GO

DROP TABLE IF EXISTS DBO.PRODUCTO_HISTORIAL;
GO

CREATE TABLE DBO.PRODUCTO_HISTORIAL (
    ID_HISTORIAL BIGINT IDENTITY (1, 1) NOT NULL,
    ID_PRODUCTO INT NOT NULL,
    ID_TIPO_OPERACION TINYINT NOT NULL,
    USUARIO_RESPONSABLE SYSNAME NOT NULL,
    FECHA_CAMBIO DATETIME2(3) NOT NULL,
    CODIGO_INTERNO VARCHAR(20) NOT NULL,
    ID_TIPO_PRODUCTO TINYINT NOT NULL,
    ID_RUBRO TINYINT NOT NULL,
    DESCRIPCION_PRODUCTO NVARCHAR(150) NOT NULL,
    PRECIO_UNITARIO DECIMAL(18, 5) NOT NULL,
    EXISTENCIA INT NOT NULL,
    TASA_IMPUESTO DECIMAL(5, 4) NOT NULL,
    ESTADO_PRODUCTO BIT NOT NULL,
    FECHA_CREACION DATETIME2(3) NOT NULL,
    CONSTRAINT PK_PRODUCTO_HISTORIAL
    PRIMARY KEY (ID_HISTORIAL),
    CONSTRAINT FK_PRODUCTO_HISTORIAL_TIPO_OPERACION
    FOREIGN KEY (ID_TIPO_OPERACION)
    REFERENCES DBO.TIPO_OPERACION (ID_TIPO_OPERACION)
);
GO
