/* DBO.CLIENTE_FISICO_HISTORIAL — AUDITORÍA DEL NOMBRE Y APELLIDOS DE LAS
   PERSONAS FÍSICAS. */

USE SISTEMA_FACTURACION;
GO

DROP TABLE IF EXISTS DBO.CLIENTE_FISICO_HISTORIAL;
GO

CREATE TABLE DBO.CLIENTE_FISICO_HISTORIAL (
    ID_HISTORIAL BIGINT IDENTITY (1, 1) NOT NULL,
    ID_CLIENTE INT NOT NULL,
    ID_TIPO_OPERACION TINYINT NOT NULL,
    USUARIO_RESPONSABLE SYSNAME NOT NULL,
    FECHA_CAMBIO DATETIME2(3) NOT NULL,
    NOMBRE NVARCHAR(50) NOT NULL,
    PRIMER_APELLIDO NVARCHAR(50) NOT NULL,
    SEGUNDO_APELLIDO NVARCHAR(50) NOT NULL,
    CONSTRAINT PK_CLIENTE_FISICO_HISTORIAL
    PRIMARY KEY (ID_HISTORIAL),
    CONSTRAINT FK_CLIENTE_FISICO_HISTORIAL_TIPO_OPERACION
    FOREIGN KEY (ID_TIPO_OPERACION)
    REFERENCES DBO.TIPO_OPERACION (ID_TIPO_OPERACION)
);
GO
