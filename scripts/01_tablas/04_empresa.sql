-- Tabla EMPRESA
CREATE TABLE DBO.EMPRESA
(
    ID_EMPRESA INT IDENTITY (1, 1) NOT NULL,
    NOMBRE_COMERCIAL NVARCHAR(150) NOT NULL,
    RAZON_SOCIAL NVARCHAR(150) NOT NULL,
    CEDULA_EMPRESA VARCHAR(12) NOT NULL,
    -- Utiliza formato sin guiones
    ID_DIRECCION INT NOT NULL,
    TELEFONO_EMPRESA VARCHAR(12) NOT NULL,
    CORREO_ELECTRONICO VARCHAR(254) NOT NULL,
    FECHA_CREACION DATETIME2(3) NOT NULL,
    ESTA_ACTIVA BIT NOT NULL, -- 1 = Si | 0 = No

    CONSTRAINT PK_EMPRESA PRIMARY KEY (ID_EMPRESA),
    CONSTRAINT UQ_EMPRESA_CEDULA_EMPRESA
    UNIQUE (CEDULA_EMPRESA),
    CONSTRAINT FK_EMPRESA_DIRECCION
    FOREIGN KEY (ID_DIRECCION)
    REFERENCES DBO.DIRECCION (ID_DIRECCION)
);
GO
