/* DBO.CLIENTE_HISTORIAL — AUDITORÍA DEL REGISTRO DE CLIENTES.
   SIN FK HACIA DBO.CLIENTE PORQUE DEBE REGISTRAR EL DELETE DE CLIENTES QUE YA
   NO EXISTEN.
   CADA FILA ES UNA FOTO DEL CLIENTE: EN INSERT Y UPDATE GUARDA LOS VALORES
   DESPUÉS DE LA OPERACIÓN; EN DELETE, LOS VALORES BORRADOS. EL VALOR ANTERIOR
   ES LA FILA PREVIA DEL MISMO ID_CLIENTE. ASÍ NINGUNA COLUMNA ADMITE NULL.
   LA DIRECCIÓN SE GUARDA COMO ID_DIRECCION (FK), NO COMO TEXTO: LAS
   DIRECCIONES NO SE EDITAN NI SE BORRAN, CADA CAMBIO CREA UNA NUEVA.
   USUARIO_RESPONSABLE Y FECHA_CAMBIO LOS ASIGNA EL TRIGGER CON ORIGINAL_LOGIN()
   Y SYSDATETIME(). */

USE SISTEMA_FACTURACION;
GO

DROP TABLE IF EXISTS DBO.CLIENTE_HISTORIAL;
GO

CREATE TABLE DBO.CLIENTE_HISTORIAL (
    ID_HISTORIAL BIGINT IDENTITY (1, 1) NOT NULL,
    ID_CLIENTE INT NOT NULL,
    ID_TIPO_OPERACION TINYINT NOT NULL,
    USUARIO_RESPONSABLE SYSNAME NOT NULL,
    FECHA_CAMBIO DATETIME2(3) NOT NULL,
    CEDULA_CLIENTE VARCHAR(12) NOT NULL,
    CORREO_CLIENTE VARCHAR(254) NOT NULL,
    TELEFONO_CLIENTE VARCHAR(12) NOT NULL,
    ID_DIRECCION INT NOT NULL,
    CONSTRAINT PK_CLIENTE_HISTORIAL
    PRIMARY KEY (ID_HISTORIAL),
    CONSTRAINT FK_CLIENTE_HISTORIAL_DIRECCION
    FOREIGN KEY (ID_DIRECCION)
    REFERENCES DBO.DIRECCION (ID_DIRECCION),
    CONSTRAINT FK_CLIENTE_HISTORIAL_TIPO_OPERACION
    FOREIGN KEY (ID_TIPO_OPERACION)
    REFERENCES DBO.TIPO_OPERACION (ID_TIPO_OPERACION)
);
GO
