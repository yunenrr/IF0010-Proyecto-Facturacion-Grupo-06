USE SISTEMA_FACTURACION;
GO

--Creación de la tabla PROVINCIA:
CREATE TABLE DBO.PROVINCIA
(
    ID_PROVINCIA TINYINT NOT NULL,
    NOMBRE_PROVINCIA NVARCHAR(50) NOT NULL,

    CONSTRAINT PK_PROVINCIA PRIMARY KEY (ID_PROVINCIA),
    CONSTRAINT UQ_PROVINCIA_NOMBRE_PROVINCIA UNIQUE (NOMBRE_PROVINCIA)
);
GO

----------------------------------------------------------------
--Creación de la tabla CANTON:
CREATE TABLE DBO.CANTON
(
    ID_CANTON SMALLINT NOT NULL,
    ID_PROVINCIA TINYINT NOT NULL,
    NOMBRE_CANTON NVARCHAR(50) NOT NULL,

    CONSTRAINT PK_CANTON PRIMARY KEY (ID_CANTON),
    CONSTRAINT UQ_CANTON_PROVINCIA_NOMBRE
    UNIQUE (ID_PROVINCIA, NOMBRE_CANTON),
    CONSTRAINT FK_CANTON_PROVINCIA
    FOREIGN KEY (ID_PROVINCIA)
    REFERENCES DBO.PROVINCIA (ID_PROVINCIA)
);
GO

-----------------------------------------------------------------
--Creación de la tabla DISTRITO:
CREATE TABLE DBO.DISTRITO
(
    ID_DISTRITO INT NOT NULL,
    ID_CANTON SMALLINT NOT NULL,
    NOMBRE_DISTRITO NVARCHAR(50) NOT NULL,

    CONSTRAINT PK_DISTRITO PRIMARY KEY (ID_DISTRITO),
    CONSTRAINT UQ_DISTRITO_CANTON_NOMBRE
    UNIQUE (ID_CANTON, NOMBRE_DISTRITO),
    CONSTRAINT FK_DISTRITO_CANTON
    FOREIGN KEY (ID_CANTON)
    REFERENCES DBO.CANTON (ID_CANTON)
);
GO

-----------------------------------------------------------------
--Creación de la tabla DIRECCION
CREATE TABLE DBO.DIRECCION
(
    ID_DIRECCION INT IDENTITY (1, 1) NOT NULL,
    ID_DISTRITO INT NOT NULL,
    OTRAS_SENAS NVARCHAR(250) NOT NULL,

    CONSTRAINT PK_DIRECCION PRIMARY KEY (ID_DIRECCION),
    CONSTRAINT FK_DIRECCION_DISTRITO
    FOREIGN KEY (ID_DISTRITO)
    REFERENCES DBO.DISTRITO (ID_DISTRITO)
);
GO
